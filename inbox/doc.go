// Package inbox — приём событий чужих систем (вебхуков): подлинность до базы,
// дедуп по смысловому ключу источника, отметка и эффект в одной транзакции,
// ответ, который не теряет событие и не врёт дашборду (ADR-0012).
//
// Верификатор источника пишет проект и проверяет его набором
// inboxtest.RunVerifierSuite; обработчик события — хук хранилища, внешний
// эффект — сообщение outbox в той же транзакции. Ручка — inboxhttp, двойник и
// наборы — inboxtest, пример подключения — example_test.go, рецепт — README.md.
// Хранилище Postgres — inboxpg; метрики — следующий шаг модуля.
//
// Безопасность:
//
//  1. ПОДЛИННОСТЬ ДО БАЗЫ: неподтверждённый запрос не стоит соединения из пула.
//  2. PAYLOAD — ТОЛЬКО ПОДТВЕРЖДЁННОЕ: неподписанная часть тела и присланное
//     вместо перечитанного в событие не попадают. Страж — RunVerifierSuite.
//  3. ДОПУСК ПО ВРЕМЕНИ НЕ НОЛЬ, СРАВНЕНИЕ ПОСТОЯННОГО ВРЕМЕНИ, АДРЕС — ОТ
//     ПЕРИМЕТРА: CheckTimestamp паникует на нулевом допуске, AddrIn на пустом
//     адресе отвечает false.
//  4. ОТМЕТКА И ЭФФЕКТ — ОДНА ТРАНЗАКЦИЯ: ошибка обработчика откатывает отметку,
//     и повтор отправителя применится.
//  5. 200 — ТОЛЬКО ЗАКОММИЧЕННОМУ И ТОМУ, ЧТО НЕ ОБРАБОТАЕТСЯ НИКОГДА;
//     параллельному дублю и неизвестному типу — не 2xx: первая транзакция
//     может откатиться, а новый тип знает новая реплика.
//  6. ОШИБКА ОБРАБОТЧИКА — 503 ПРИ ЛЮБОМ ЕЁ КЛАССЕ: ядро заворачивает её в
//     ErrUnavailable снаружи, иначе 4xx-класс хука остановил бы повтор.
//  7. ТЕЛО, ЗАГОЛОВКИ И ПОДПИСИ НЕ ЛОГИРУЮТСЯ: заголовки не хранятся, ошибки
//     ядра их не цитируют, метки — закрытые наборы.
//  8. ТЕЛО ОГРАНИЧЕНО ДО ПРОВЕРКИ: подпись не считается по неограниченному
//     входу, а too_large считает одно место — Receive.
//  9. ПОДПИСЬ БЕЗ ВРЕМЕНИ ПОВТОРЯЕМА ВЕЧНО: от повтора перехваченного запроса
//     защищает только отметка, и Config.Retention — граница защиты.
//  10. ТЕЛО ХРАНИТСЯ ТОЛЬКО С КОРОТКИМ СРОКОМ: Config.PayloadRetention
//     обязателен и не длиннее Retention, ноль — паника; в нём персональные
//     данные, а таблица тел не попадает ни в логи, ни в метки.
//
// # Чего в пакете НЕТ
//
//  1. ВЕРИФИКАТОРОВ ПРОВАЙДЕРОВ: синтаксис подписи у каждого свой, и
//     «универсальный HMAC» стал бы языком конфигурации. Первым уедет Standard
//     Webhooks — спецификация, а не провайдер.
//  2. СИНХРОННЫХ ВЕБХУКОВ-РЕШЕНИЙ (Check у CloudPayments): ответ там — решение,
//     это обычная ручка.
//  3. ПОВТОРНОЙ ОБРАБОТКИ СОХРАНЁННЫХ ТЕЛ: пересылка у отправителя или сверка
//     по API; пересмотр — инцидент, где окна пересылки не хватило.
//  4. ДОСЫЛКИ У ОТПРАВИТЕЛЕЙ БЕЗ ПОВТОРОВ (GitHub): это сверка проекта.
//  5. ГАРАНТИИ ПОРЯДКА: её не даёт отправитель; порядок держит машина статусов
//     обработчика.
//  6. РЕЖИМА «ТЕЛО НЕ ХРАНИТЬ»: пересмотр — источник, чьё тело нельзя хранить и
//     сутки.
//  7. ОТПРАВКИ ВЕБХУКОВ НАРУЖУ: другая задача (SSRF, расписание повторов).
//  8. МАРШРУТИЗАЦИИ, TLS И СПИСКОВ СЕТЕЙ НА ПЕРИМЕТРЕ: у проекта.
//
// Метрики и алерты — ADR-0012, решение 16.
