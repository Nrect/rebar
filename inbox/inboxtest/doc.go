// Package inboxtest — двойники портов inbox и контрактные наборы для тестов
// проекта и адаптеров. Двойник — не мок: он держит инварианты схемы, чтобы
// тест проверял исход, а не список вызовов. Собирается без тестовых
// зависимостей: пакет компилирует потребитель.
//
// Сбой (SetErr) и отменённый контекст двойник отдаёт в inbox.ErrUnavailable,
// как адаптер; ошибку обработчика — как есть: её класс решает ядро (ADR-0007,
// «Двойники»).
//
// Жители:
//
//   - MemStore — inbox.Store в памяти: ключ дедупа в пределах источника,
//     отпечаток, исключение по ключу без общего замка, CHECK схемы, тело
//     отдельно от отметки, моменты как в timestamptz; Mark и Payload — окно
//     теста мимо порта, CallCount — «до хранилища не дошли».
//   - HMACVerifier, SignHMAC, EventBody — тестовая схема подписи для ручки
//     проекта без провайдера. Не боевая.
//   - RunStoreSuite — контрактный набор порта: один на двойник и адаптер.
//   - RunVerifierSuite — набор для верификатора проекта: порт проекта
//     проверяется набором блока.
//   - Observer — наблюдатель: Watched — источники, которые завёл NewService,
//     Deliveries — доставки по порядку.
//   - Clock — управляемые часы.
package inboxtest
