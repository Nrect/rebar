// Package idem — ответ на повтор запроса клиента по ключу Idempotency-Key:
// первый запрос исполняет операцию и записывает её ответ в той же транзакции,
// повтор получает записанный ответ байт в байт с Idempotent-Replayed: true
// (ADR-0012, решения 9–12).
//
// Порта хранилища в ядре нет, как нет Enqueue в ядре outbox: транзакцию, в
// которой исполняется op, видит только адаптер. Ядро даёт чистые решения —
// ParseKey, Request.Fingerprint, Replay, Config.CheckRequest и
// Config.CheckResponse, отказ InFlight, — и их зовут Do адаптера и двойника.
// Одинаковость остального держит idemtest.RunDoSuite. Пример подключения —
// example_test.go, рецепт — README.md.
//
// Ядро — stdlib и kit; двойник и контрактный набор — idemtest; HTTP — idemhttp;
// хранилище Postgres — idempg; метрика idem_requests{operation,outcome} и
// алерты решения 16 — idemotel.
//
// Безопасность:
//
//  1. ОБЛАСТЬ — ПРИНЦИПАЛ, А НЕ ЗАПРОС: чужой ключ не отдаёт чужого ответа.
//     Scope берётся из сессии auth; пустая — ErrInvalidScope до хранилища.
//  2. ЗАПИСЬ ОТВЕТА И ЭФФЕКТ — ОДНА ТРАНЗАКЦИЯ; в WithTx ошибка оставляет
//     транзакцию потребителя в aborted. Страж — RunDoSuite и тесты idempg.
//  3. ПАРАЛЛЕЛЬНЫЙ ПОВТОР НЕ ЖДЁТ: InFlight, 409 с Retry-After, соединение не
//     держится.
//  4. ТОТ ЖЕ КЛЮЧ, ДРУГОЙ ЗАПРОС — ErrKeyReused (409), А НЕ ЧУЖОЙ ОТВЕТ И НЕ
//     ВТОРОЕ ИСПОЛНЕНИЕ. Отпечаток — сырые байты с префиксом длины у поля.
//  5. СБОЙ НЕ ЗАПИСЫВАЕТСЯ: 5xx — ErrNotRecordable, откат и повторное
//     исполнение.
//  6. ХРАНЯТСЯ ТОЛЬКО Content-Type И Location: куки в таблицу повторов не
//     попадают.
//  7. КЛЮЧ, ОБЛАСТЬ И ТЕЛО НЕ ЛОГИРУЮТСЯ; метки — операция и исход. Тексты
//     ошибок входа не цитируют.
//  8. ПОТОЛОК ОТВЕТА — ОТКАТ, А НЕ УСЕЧЁННЫЙ ПОВТОР (ErrResponseTooLarge).
//
// # Чего в пакете НЕТ
//
//  1. РУЧЕК С ВНЕШНИМ ВЫЗОВОМ: внешний эффект уходит в outbox изнутри op, либо
//     ручка идемпотентна доменом, как payment (решение 12).
//  2. КАНОНИЗАЦИИ ОТПЕЧАТКА ПО ОПЕРАЦИИ: пересмотр — клиент, законно меняющий
//     презентационные поля между повторами.
//  3. ПОВТОРА 5xx: временный сбой не отвечает клиенту до конца срока.
//  4. ЗАЩИТЫ ОДНОРАЗОВОГО СЕКРЕТА В ТЕЛЕ ОТВЕТА: тело хранится как есть до
//     срока, поэтому ручка, отдающая ключ API или токен один раз, в idem не
//     заворачивается. Стража у правила нет.
//  5. СРОКА НА ОПЕРАЦИЮ: срок один на Config.
//  6. КЛЮЧЕЙ БЕЗ ПРИНЦИПАЛА (сервис к сервису): придут с apikeys.
//  7. ОБВЯЗОК НЕ-HTTP ТРАНСПОРТОВ.
