// Package idemhttp — idem на HTTP: ключ из заголовка Idempotency-Key, ответ
// ручки в idem.Response и выдача результата с Idempotent-Replayed.
//
// Пакет не пишет ответ об ошибке сам: ошибку Do, NewRequest и Key ручка отдаёт
// своим ответчиком (kit/errs/httperr). Класс уже в ошибке — 400 на ключе, 409 на
// переиспользовании и параллельном повторе, у последнего с Retry-After через
// структурный контракт. Второй формат ошибки, зашитый сюда, дал бы клиенту два
// разных тела на соседних ручках. Порядок ручки — пример в example_test.go
// модуля.
//
// Ядро — stdlib и idem.
//
// Безопасность:
//
//  1. ВЫДАЧА СТАВИТ ТОЛЬКО ЗАПИСАННОЕ: Content-Type, Location и
//     Idempotent-Replayed; куку ручка ставит вне idem. Страж — TestWrite.
//  2. ПУТЬ И СТРОКА ЗАПРОСА — КАК ПРИШЛИ (EscapedPath, RawQuery): другая запись
//     того же пути даёт лишний 409, а не чужой ответ. Страж — TestNewRequest.
//  3. КЛЮЧ ТОЛЬКО ИЗ ЗАГОЛОВКА: поле тела ключом не становится, и заголовок
//     один на весь API, включая ручку оплаты.
//
// Чего в пакете нет (решения, не пробелы): прозрачного middleware — транзакцию
// op видит только адаптер, а отдельный коммит «в работе» отвергнут (ADR-0012);
// чтения тела — его потолок и разбор принадлежат ручке; ответа об ошибке — его
// формат принадлежит API потребителя.
