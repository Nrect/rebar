// Package idemtest — двойник хранилища idem и контрактный набор для тестов
// потребителей и адаптеров. Двойник — не мок: он держит инварианты записи,
// чтобы тест проверял исход, а не список вызовов. Собирается без тестовых
// зависимостей: пакет компилирует потребитель.
//
// Сбой (SetErr) и отменённый контекст приходят в idem.ErrUnavailable с
// причиной, как у idempg (ADR-0007, «Двойники»); ошибка op — как есть.
//
// Жители:
//
//   - MemStore — Do и idem.Pruner в памяти: уникальность (реалм, субъект,
//     ключ), отпечаток, исключение по ключу без общего замка, срок записи,
//     моменты как в timestamptz, копия тела на записи и выдаче; SetErr и
//     SetClock — сеттеры под замком. Код теста отличается от кода прода
//     одним конструктором и формой op: без pgx.Tx.
//   - RunDoSuite — контрактный набор: один на двойник и idempg.
//   - Observer — двойник idem.Observer, запоминает исходы по порядку.
//   - Clock — управляемые часы для MemStore.SetClock и idem.Purger.SetClock.
package idemtest
