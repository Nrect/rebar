// Package retry — повторы с экспонентой и полным джиттером, уважение
// Retry-After и три класса ошибок.
//
// Вызывающий оборачивает шаг в Retrier.Do и помечает исход обёртками:
// Permanent — повторять нечего, Throttled — провайдер попросил подождать.
// Классы читаются структурно, по методам Permanent() bool и
// RetryAfter() (time.Duration, bool), поэтому outbox, httperr и адаптеры
// провайдеров понимают их без импорта этого пакета.
//
// Do годится для одного шага (запрос к провайдеру), а не для задачи целиком:
// длинные ожидания — дело планировщика, см. п. 3.
//
// Безопасность:
//
//  1. ДЖИТТЕР ПОЛНЫЙ И ОБЯЗАТЕЛЬНЫЙ: delay = random(0, потолок). Без него
//     застрявшие задачи уходят одной волной и получают 429 той же волной.
//  2. ПЕРЕПОЛНЕНИЕ СДВИГА — ПОТОЛОК Max, НЕ НОЛЬ. Base<<61 обнуляется на
//     дальних попытках; потолок в ноль убил бы джиттер ровно там, где он
//     нужнее всего (мутант из mail).
//  3. RETRY-AFTER БОЛЬШЕ MaxRetryAfter — ErrRetryAfterTooLong СРАЗУ. Бан на
//     десятки минут нельзя отсиживать внутри задачи: воркер занят, а решение
//     «когда вернуться» принимает планировщик.
//  4. Permanent НЕ ПОВТОРЯЕТСЯ НИКОГДА: повтор постоянного отказа — спам
//     провайдеру и двойные эффекты у него же.
//  5. ОТМЕНА ctx ПРЕРЫВАЕТ СОН СРАЗУ. Исчерпание попыток оборачивает
//     последнюю причину через %w, но не наследует Permanent: класс ошибки
//     принадлежит причине, а не счётчику попыток.
//  6. МУСОРНЫЙ Retry-After — «ПОДСКАЗКИ НЕТ» (ok == false), а не ноль:
//     ноль означал бы «можно сразу», то есть подсказку наоборот.
//  7. op ОБЯЗАН БЫТЬ ИДЕМПОТЕНТНЫМ. Do не знает ключа идемпотентности;
//     неоднозначный таймаут он повторит, и без ключа это второй эффект.
//
// Чего в пакете нет (решения, не пробелы): circuit breaker и hedging
// (нужен общий на процесс, это отдельный пакет), http.RoundTripper (v0.2,
// retryhttp), классификации ошибок Postgres (это модуль postgres),
// собственного счётчика метрик — исход считает вызывающий.
package retry
