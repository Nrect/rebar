// Package secrets — AES-256-GCM с версией блоба, номером ключа и ротацией.
//
// Потребитель держит кольцо ключей (Keyring) из переменной окружения вида
// "1:<base64>,2:<base64>", шифрует поле через Cipher.Seal и связывает блоб с
// контекстом строки через AAD. Ротация — фоновый проход Reseal: блоб,
// зашифрованный старым ключом, перешифровывается активным, пока старый ключ
// ещё в кольце.
//
// Формат блоба: версия(1) | keyID(2, BigEndian) | nonce(12) | ciphertext+tag.
// Заголовок открыт (по нему видно, чем расшифровывать) и одновременно входит
// в аутентифицируемые данные, поэтому подмена версии или номера ключа — такая
// же подделка, как порча шифротекста.
//
// Безопасность:
//
//  1. ТОЛЬКО AEAD. Порча, подделка и «не тот ключ» неотличимы для клиента —
//     все дают ErrMalformed. Отдельно стоит ErrUnknownKey: это не атака, а
//     операционный сигнал «ключ убрали из кольца до перешифровки».
//  2. ЗАГОЛОВОК С ВЕРСИЕЙ И keyID — С ПЕРВОГО ДНЯ. Добавить их потом нельзя:
//     блобы без заголовка неотличимы от блобов с ним, и ротация задним
//     числом становится невозможной.
//  3. ЗАГОЛОВОК ВХОДИТ В AAD: понижение версии формата или подмена keyID не
//     проходят проверку тега.
//  4. AAD СВЯЗЫВАЕТ БЛОБ С КОНТЕКСТОМ (id строки, имя поля). Без него чужой
//     зашифрованный ключ переставляется в свою строку и расшифровывается
//     сервисом от имени владельца строки.
//  5. КЛЮЧ РОВНО 32 БАЙТА, ИЗ МАСТЕР-СЕКРЕТА — ТОЛЬКО ЧЕРЕЗ DeriveKey
//     (HKDF-SHA256, info = purpose): один секрет не должен служить и HMAC, и
//     AES. Разный purpose — разные ключи, и компрометация одного не отдаёт
//     второй.
//  6. NONCE 96 БИТ ИЗ crypto/rand НА КАЖДЫЙ Seal. Порог NIST — 2^32 Seal на
//     один ключ (SP 800-38D, §8.3): дальше вероятность повтора nonce
//     перестаёт быть пренебрежимой. Это документированный триггер ротации;
//     пакет не считает вызовы за потребителя.
//  7. НИ PLAINTEXT, НИ КЛЮЧЕЙ В ОШИБКАХ И ЛОГАХ. Текст ошибки GCM наружу не
//     идёт, разбор кольца называет только позицию и номер ключа, а Keyring и
//     Cipher редактируются во всех формах печати (fmt любым глаголом, slog,
//     json): без этого %v достал бы ключи рефлексией.
//  8. ПУСТОЕ ИЛИ nil-КОЛЬЦО — ОШИБКА И ПАНИКА КОНСТРУКТОРА: «шифрование не
//     настроено» обязано падать на старте, а не писать открытый текст.
//
// Чего в пакете нет (решения, не пробелы): KMS и Vault (порт появится вместе
// с потребителем, которому они нужны), envelope encryption (ключ на строку),
// асимметрии и подписи, детерминированного шифрования и поиска по
// шифротексту, сжатия, CLI для ротации (проход по таблице — дело
// потребителя), счётчика Seal на ключ.
