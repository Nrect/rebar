// Package ratelimithttp — HTTP-обвязка лимитера: middleware, ключ по IP и
// разбор X-Forwarded-For.
//
// Middleware спрашивает Gate, ставит Retry-After и передаёт решение
// обработчику отказа; тело ответа пишет потребитель своим httperr — пакет
// не знает ни его слагов, ни формата. Роутера не знает: обычный
// func(http.Handler) http.Handler.
//
// Безопасность:
//
//  1. X-FORWARDED-FOR ЧИТАЕТСЯ ТОЛЬКО ОТ ДОВЕРЕННОГО ПРОКСИ. Если сосед по
//     соединению не входит в trusted, заголовок игнорируется целиком: иначе
//     лимит обходится одной строкой в запросе.
//  2. ЦЕПОЧКА РАЗБИРАЕТСЯ СПРАВА НАЛЕВО и обрывается на первом недоверенном
//     адресе — он и есть клиент. Мусор в цепочке тоже обрывает разбор: всё,
//     что левее подделки, подделка.
//  3. ОШИБКА Gate И ПУСТОЙ КЛЮЧ — ОТКАЗ. Fail-open достигается подменой
//     Gate, а не флагом.
//  4. IPv6 АГРЕГИРУЕТСЯ ПО ПРЕФИКСУ (обычно /64). Полный адрес дал бы
//     отдельный лимит каждому адресу подсети, а их у клиента 2^64.
//  5. КЛЮЧ НЕ ЛОГИРУЕТСЯ И НЕ ПОПАДАЕТ В ОТВЕТ. IP — персональные данные;
//     пакет логгера не имеет вовсе, а в ответ пишет только Retry-After.
//  6. RETRY-AFTER — ЦЕЛЫЕ СЕКУНДЫ ВВЕРХ. Округление вниз вернуло бы клиента
//     ровно в отказ, а ноль в заголовке означал бы «прямо сейчас».
//
// Чего в пакете нет (решения, не пробелы): заголовков X-RateLimit-*
// (рассказывают клиенту устройство лимита), заголовка Forwarded (RFC 7239 —
// когда появится прокси, который его ставит), разбора CIDR из строки
// конфигурации (это config потребителя), тела ответа 429 и его слага (это
// httperr потребителя), логирования и метрик.
