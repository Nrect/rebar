// Package ratelimit — лимитер частоты на ключ: token bucket в памяти
// процесса, без фоновых горутин.
//
// Ключ выбирает вызывающий: IP, e-mail, идентификатор пользователя.
// Пополнение — Limit токенов за Window, ёмкость — Burst. Забытые ключи
// удаляет Sweep, у которого сигнатура задачи планировщика: лимитер сам
// ничего не запускает и останавливать его не нужно.
//
// Порт Gate позволяет заменить память процесса на общее хранилище (адаптер
// redis — v0.2), не меняя вызывающий код; HTTP-обвязка — подпакет
// ratelimithttp.
//
// Безопасность:
//
//  1. ПУСТОЙ КЛЮЧ — ОТКАЗ И ErrEmptyKey, НЕ ПРОПУСК. Пустой ключ означает,
//     что KeyFunc не смогла его вычислить (не разобрался адрес, нет поля);
//     пропуск превратил бы эту ошибку в бесплатный обход лимита.
//  2. ОШИБКА Gate — ОТКАЗ. Fail-open достигается подменой Gate, а не флагом:
//     флаг «пропускать при сбое» рано или поздно останется включённым.
//  3. ПОТОЛОК КЛЮЧЕЙ MaxKeys. При переполнении сначала выметаются
//     простаивающие, и только потом отказ новым ключам со счётчиком
//     Overflows: ротация ключей (случайный заголовок на каждый запрос) не
//     должна приводить к OOM.
//  4. БЕЗ ФОНОВОЙ ГОРУТИНЫ И БЕЗ Stop(). Горутина внутри библиотеки — это
//     утечка у того, кто забыл её остановить, и гонка с подменёнными часами
//     в тестах. Уборку заказывает планировщик потребителя.
//  5. RETRY-AFTER ЧЕСТНЫЙ: время до следующего токена, а не константа.
//     Врать в меньшую сторону — приглашать клиента вернуться в отказ, в
//     большую — терять доступность.
//  6. КЛЮЧ НЕ ЛОГИРУЕТСЯ. Пакет не пишет логов вовсе: IP и e-mail — ПДн, а
//     запись «ключ X превысил лимит» живёт дольше, чем сам лимит.
//  7. НУЛЕВОЙ Config — ПАНИКА В КОНСТРУКТОРЕ. «Лимит не настроен» обязано
//     падать на старте, а не пропускать всё подряд.
//
// Чего в пакете нет (решения, не пробелы): адаптера redis и GCRA (v0.2),
// sliding-window log (память на каждый запрос ради точности, которая
// лимитеру не нужна), глобальных лимитов на процесс, исходящего адаптивного
// гейта по заголовкам корзины провайдера, отдельного подпакета с двойником
// Gate — двойник и есть сам Limiter, он in-memory и работает на подменённых
// часах.
