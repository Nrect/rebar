// Package reqid — идентификатор запроса: middleware, контекст, эхо в ответе.
//
// Ставится первым в цепочке; httperr кладёт значение в тело ошибки, логи
// склеиваются по нему. Роутера не знает — обычный http.Handler.
//
// Безопасность:
//
//  1. ЧУЖОЕ ЗНАЧЕНИЕ ПРИНИМАЕТСЯ ТОЛЬКО В БЕЗОПАСНОЙ ФОРМЕ
//     ([A-Za-z0-9._-], до MaxLen). CR и LF из заголовка клиента иначе
//     разрежут строку лога и заголовки ответа; длинное значение раздует
//     каждую строку лога.
//  2. НЕГОДНОЕ — ЗАМЕНЯЕТСЯ, А НЕ ОТКЛОНЯЕТСЯ: 400 на кривой заголовок
//     ломал бы запрос из-за поля, которое ни на что не влияет.
//  3. ИДЕНТИФИКАТОР НЕ АУТЕНТИФИКАЦИЯ. По нему ничего не авторизуется,
//     поэтому клиенту разрешено назвать свой.
//  4. СВОЙ — 16 БАЙТ ИЗ crypto/rand: значение видно в теле ошибки, и
//     угадывать чужие не должно быть смысла.
//
// Чего в пакете нет: зависимости от роутера, W3C traceparent и связи с
// OpenTelemetry (это otelboot), логирования запросов, метрик.
