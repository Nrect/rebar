// Package httperr — единственная точка, где ошибка становится HTTP-ответом.
//
// Ответчик собирается один раз при старте (New) и зовётся из хендлеров и
// middleware: Write(ctx, w, err). Тело плоское — {"slug", "request_id"},
// статус берётся из errs.Kind. Второго пути нет и не должно появиться: за
// этим следит errstest.NoDirectHTTPErrors в тестах потребителя.
//
// Безопасность:
//
//  1. НАРУЖУ ТОЛЬКО SLUG И REQUEST_ID. Причина, текст и стек уходят в лог:
//     по request_id их находит поддержка, клиенту они не нужны.
//  2. НИ СЛАГА, НИ КЛАССА — 500 И InternalSlug. Текст чужой ошибки наружу не
//     идёт никогда: то, что никто не разбирал, называет таблицы и адреса. Слаг
//     собранной вручную SlugError проверяется ValidSlug, иначе тоже 500.
//  3. СЛАГ ПО УМОЛЧАНИЮ — ИМЯ КЛАССА. errs.KindError без перевода в Translate
//     отвечает string(Kind): набор имён закрыт, просочиться в слаг нечему.
//  4. TRANSLATE ПЕРВЫМ И ОДИН РАЗ. Чужие sentinel'ы переводятся в SlugError
//     до всех решений — так граница не импортирует auth ради ErrBusy.
//  5. УРОВНИ ЛОГА ПО КЛАССУ: 5xx — Error (в трекер), 401/403/429 — Warn
//     (сигнал безопасности), прочие 4xx — Debug. Сведи их — и сканер портов
//     зальёт Error-лог, а алерт по нему перестанут читать.
//  6. ОТМЕНЁННЫЙ ctx — БЕЗ ЛОГА. Клиент ушёл, сервер не сбоил.
//  7. Retry-After ТОЛЬКО ИЗ СТРУКТУРНОГО КОНТРАКТА RetryAfter() (time.Duration, bool).
//     Из статуса и текста ошибки задержка не вычисляется.
//  8. ОТВЕТ НЕ ПИШЕТСЯ ДВАЖДЫ. Если обёртка ResponseWriter говорит, что
//     заголовки ушли, остаётся только лог.
//  9. Cache-Control: no-store НА КАЖДОЙ ОШИБКЕ: 403 из кэша прокси —
//     чужой отказ, показанный не тому.
//
// Чего в пакете нет (решения, не пробелы): текстов и i18n, текста ошибки в
// теле (у errs.KindError текст и причина — только в лог), HTML-страниц
// ошибок, маппинга в gRPC, отправки в Sentry, зависимости от роутера — Write
// принимает голый http.ResponseWriter.
