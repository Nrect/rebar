// Package errs — ошибка со слагом: стабильная машиночитаемая причина для
// клиента и закрытый класс для HTTP-статуса.
//
// Прикладной слой объявляет ошибки в var-блоке (errs.NotFound("user-not-found")),
// возвращает их наверх и обогащает причиной через WithCause; клиент ветвится
// по слагу, а не по статусу. В HTTP-ответ ошибку превращает единственная
// точка — подпакет httperr. Guard-тесты потребителя (реестр слагов, запрет
// http.Error) — в errstest.
//
// Безопасность:
//
//  1. НАРУЖУ ТОЛЬКО SLUG. cause не сериализуется и доступен лишь через
//     Unwrap: текст чужой ошибки называет таблицы, адреса и SQL.
//  2. ЧУЖАЯ ОШИБКА — KindUnknown. KindOf не угадывает класс по тексту: то,
//     что никто не разбирал, отдаётся как 500 без подробностей.
//  3. KIND И SLUG ЗАКРЫТЫ. Kind — из AllKinds, слаг — kebab-case не длиннее
//     MaxSlugLen: оба попадают в метку метрики, значение извне туда не идёт.
//  4. НЕГОДНЫЙ СЛАГ — ПАНИКА В КОНСТРУКТОРЕ. Ошибки объявляются в var-блоке,
//     поэтому падение случится на старте, а не на запросе клиента.
//  5. Is СРАВНИВАЕТ SLUG И KIND, а не причину: иначе ветвление потребителя
//     зависело бы от того, что обернули в WithCause.
//
// Чего в пакете нет (решения, не пробелы): текстов и i18n (слаг мапит фронт),
// маппинга в gRPC-коды, стека вызовов, отправки в Sentry (отдельный пакет),
// реестра слагов — реестр доменный и живёт у потребителя, а errstest даёт ему
// guard-тест.
