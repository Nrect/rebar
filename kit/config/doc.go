// Читатели не возвращают ошибку по одной: они копят проблемы, и Err() отдаёт
// их одним errors.Join. Иначе выкат чинится по одной переменной за цикл.
//
// Безопасность:
//
//  1. ЗНАЧЕНИЕ ПЕРЕМЕННОЙ НИКОГДА НЕ ПОПАДАЕТ В ТЕКСТ ОШИБКИ — только имя
//     ключа и ожидание. DSN и токен выглядят как обычные строки, а список
//     ошибок идёт в лог выката.
//  2. Secret РЕДАКТИРУЕТСЯ ВО ВСЕХ ФОРМАТАХ (fmt, slog, json); значение
//     достаёт только Reveal.
//  3. У СЕКРЕТА НЕТ УМОЛЧАНИЯ И ЕСТЬ МИНИМАЛЬНАЯ ДЛИНА: SESSION_SECRET=abc
//     не должен проходить, а «забыли задать» не должно превращаться в
//     предсказуемый ключ из кода.
//  4. ОТСУТСТВИЕ ПЕРЕМЕННОЙ — ОТКАЗ, НЕ ПУСТАЯ СТРОКА. Пустое значение
//     считается отсутствующим по той же причине.
//  5. ЗАКРЫТЫЕ ГРАНИЦЫ: Enum из списка, Duration > 0, Ratio в (0, 1] и
//     NaN-safe (ParseFloat принимает "NaN" и "Inf"), URL со схемой из списка
//     — опечатка в схеме endpoint'а даёт тихо мёртвые трейсы.
//  6. ПОВЕРХНОСТЬ — ТОЛЬКО ОКРУЖЕНИЕ. Файлов не читаем, YAML не разбираем:
//     разбор чужого формата — это и код, и путь до диска.
//
// Чего в пакете нет (решения, не пробелы): файлов, флагов и .env, reflection
// и тегов структур, hot reload, Vault и Secret Manager — значение приносит
