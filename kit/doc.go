// Package kit — семейство мелких утилит, у которых нет и не будет внешних
// зависимостей: ошибки со слагом и их HTTP-форма (errs, errs/httperr),
// идентификатор запроса (reqid), загрузка окружения (config), а также
// secrets, ratelimit и retry.
//
// Почему один модуль на всех, вопреки правилу «модуль на пакет»
// (VERSIONING.md): плата за отдельный модуль — тег, строка в go.mod
// потребителя и колонка в матрице CI. Она окупается только тогда, когда у
// пакета есть своя внешняя зависимость, которую не должен тащить чужой
// проект. Здесь её нет ни у кого: всё ядро — stdlib, а тестам разрешён
// testify. Правило и записано так: ПОЯВЛЕНИЕ ВНЕШНЕЙ ЗАВИСИМОСТИ У ПАКЕТА
// KIT — ЭТО ПОВОД ВЫНЕСТИ ЕГО В СВОЙ МОДУЛЬ, а не расширить белый список
// стража импортов. Страж (importguard_test.go) держит инвариант: белый
// список каждого каталога пуст.
//
// Сам пакет kit кода не содержит: подключается тот подпакет, который нужен.
//
// Безопасность: у каждого подпакета свой список в его doc.go. Общее для
// семейства — ноль внешнего кода в проде: то, что не импортируется, не имеет
// CVE и не требует бампа у потребителя.
package kit
