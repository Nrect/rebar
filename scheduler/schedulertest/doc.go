// Package schedulertest — двойники для тестов потребителей scheduler.
// Двойник — не мок: он не проверяет «метод вызвали», он хранит то, что
// планировщик о себе сообщил, чтобы тест проверял исход. Потокобезопасны:
// тесты идут под -race, а Finished зовут горутины задач.
//
// Жители:
//
//   - RecordingObserver — scheduler.Observer, хранящий вызовы Started и все
//     прогоны; Runs отдаёт копии по задаче, Wait ждёт нужное число прогонов.
//   - FakeClock — управляемые часы для scheduler.SetClock: двигает штампы
//     Run, но НЕ тики (тикер живёт на настоящем времени).
package schedulertest
