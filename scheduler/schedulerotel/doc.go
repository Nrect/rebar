// Package schedulerotel — наблюдаемость планировщика на OpenTelemetry metric
// API: scheduler.Observer, который считает прогоны и держит гейдж времени
// последнего УСПЕШНОГО прогона.
//
// Ядро метрик не пишет и otel не импортирует (CONVENTIONS §6); зависимость
// живёт здесь. Собирается так:
//
//	obs, err := schedulerotel.NewObserver(meter)
//	s, err := scheduler.New(obs, jobs...)
//	s.Start(ctx)
//
// Инструменты (meter даёт потребитель; имена и единицы — часть контракта, на
// них стоят алерты):
//
//	| Метрика                                    | Тип       | Что |
//	|--------------------------------------------|-----------|-----|
//	| cron.runs{job,result}                      | counter   | прогоны по исходу: ok / error / panic |
//	| cron.duration{job}                         | histogram | длительность прогона, секунды |
//	| cron.processed{job}                        | counter   | обработанных элементов |
//	| cron.last_success_timestamp{job}           | gauge     | unix-время последнего успеха, секунды |
//
// Prometheus-экспортёр припишет _total счётчикам и _seconds тому, у чего
// единица s. Алерт «крон умер» — единственный, который ловит молчание:
// time() − cron_last_success_timestamp_seconds{job="mail_deliver"} > порог
// (несколько интервалов задачи).
//
// Безопасность:
//
//  1. МЕТКИ — ЗАКРЫТЫЕ НАБОРЫ: job приходит из scheduler.Job.Name, а его
//     конструктор ограничил [a-z0-9_]{1,32} и запретил дубли; result — из
//     AllResults. Текст ошибки, текст паники и содержимое обработанных
//     элементов в метки не попадают: кардинальность метрики задаёт сборка
//     процесса, а не внешний мир.
//  2. ГЕЙДЖ ЗАСЕИВАЕТСЯ НА Started, ДО ПЕРВОГО ПРОГОНА: без ряда «крон умер»
//     для Prometheus — NoData, а не срабатывание, и алерт промолчал бы ровно
//     после неудачного выката. Затравка не врёт про успех — она утверждает
//     «с этого момента успеха не было», и порог отмеряется от старта.
//  3. УПАВШИЙ ПРОГОН ГЕЙДЖ НЕ ДВИГАЕТ: иначе вечно падающая задача выглядела
//     бы живой. Затравка тоже не перезаписывает уже случившийся успех.
//  4. ПАНИКА ОТДЕЛЕНА ОТ ОШИБКИ (result="panic"): ошибка прогона — обычная
//     жизнь фоновой задачи, паника — баг в коде, и алерт на неё другой.
//
// Чего нет (решения, не пробелы): трейсов (прогон — не запрос; span на
// фоновую задачу дал бы дерево из одного узла); счётчика тиков (тик без
// прогона не бывает, а пропущенный из-за долгого прогона виден по duration);
// снятия коллбэка гейджа (Unregister) — планировщик живёт со процессом, и
// пересборка наблюдателя на лету не поддерживается.
