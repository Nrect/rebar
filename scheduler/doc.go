// Package scheduler — in-process планировщик периодических задач: на каждую
// задачу горутина с тикером, прогон обёрнут в recover, наблюдение уходит в
// порт Observer. Stop() дожидается текущих прогонов (join), а не просто
// просит их закончиться.
//
// Ядро — только stdlib: метрик оно не пишет и otel не импортирует
// (CONVENTIONS §6). Наблюдаемость собирается снаружи: schedulerotel даёт
// Observer с метриками, LogObserver — Observer на slog, двойники для тестов —
// в schedulertest.
//
// Первый потребитель — rebar/mail: Service.Deliver и Service.Purge объявлены
// как (context.Context) (int, error) и ложатся в Job.Run без обёртки.
//
//	obs, err := schedulerotel.NewObserver(meter)
//	s, err := scheduler.New(obs,
//		scheduler.Job{Name: "mail_deliver", Interval: 30 * time.Second, Run: mailSvc.Deliver},
//		scheduler.Job{Name: "mail_purge", Interval: time.Hour, Run: mailSvc.Purge},
//	)
//	s.Start(ctx)
//	defer s.Stop()
//
// Безопасность:
//
//  1. RECOVER НА КАЖДЫЙ ПРОГОН. Паника в горутине не ловится ничем выше по
//     стеку: middleware накрывает HTTP-хендлеры, а фоновая горутина роняет
//     ВЕСЬ процесс — вместе с приёмом вебхуков и входом в кабинет. Один
//     неудачный nil в задаче сверки погасил бы сервис целиком.
//  2. STOP — JOIN, А НЕ ПРОСЬБА. Прогон посередине — это открытая транзакция
//     и наполовину применённый исход; процесс, вышедший из-под него,
//     оставляет их базе и провайдеру на разбор. Цена — Stop ждёт столько,
//     сколько длится прогон, поэтому бюджет времени задаёт САМА задача
//     (context.WithTimeout внутри Run): сколько ей позволено висеть в чужом
//     API, знает она, а не планировщик.
//  3. ГЕЙДЖ ПОСЛЕДНЕГО УСПЕХА ЗАСЕИВАЕТСЯ НА СТАРТЕ. Observer.Started
//     зовётся до первого прогона именно для этого: без ряда «крон умер» для
//     Prometheus — NoData, а не срабатывание, и алерт промолчал бы ровно
//     после неудачного выката, когда крон не отработал ни разу.
//  4. ДУБЛЬ ИМЕНИ — ОТКАЗ КОНСТРУКТОРА. Две задачи в одной строке гейджа:
//     живая вечно освежает её за мёртвую, и алерт не сработает никогда.
//  5. INTERVAL ≤ 0 — ОТКАЗ КОНСТРУКТОРА, а не паника time.NewTicker внутри
//     горутины, где её некому поймать: recover стоит вокруг Run.
//  6. ОШИБКА ПРОГОНА НЕ СРЫВАЕТ РАСПИСАНИЕ. Следующий тик выполнится как
//     обычно; вечно падающая задача видна по result="error" и по
//     остановившемуся гейджу последнего успеха, а не по мёртвому крону.
//  7. РАСПРЕДЕЛЁННОЙ БЛОКИРОВКИ НЕТ НАМЕРЕННО. При двух инстансах задача
//     выполнится дважды, и безопасность этого — свойство САМОЙ задачи
//     (FOR UPDATE SKIP LOCKED в outbox и mail). Блокировка в планировщике
//     создала бы обратное впечатление: «можно писать неидемпотентные задачи».
//
// Чего в пакете нет (решения, не пробелы): cron-выражений (интервал — это
// всё, что нужно фоновой периодике; расписание «в 3 ночи по Москве» — повод
// для отдельного пакета, а не для парсера здесь); распределённой блокировки
// (см. п. 7; порт и адаптер pglock появятся, когда появится второй инстанс);
// персистентности прогонов (журнал в SQL — это Observer потребителя, а порт
// без реализации разъезжается с кодом молча); прогона при старте (нужен —
// зови RunNow до Start); backoff на ошибке (задача, которой он нужен, ставит
// его внутри Run, где известна причина отказа); отдельного таймаута прогона
// (см. п. 2).
