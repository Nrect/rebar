// Package pwzxcvbn — адаптер порта password.StrengthChecker на
// github.com/trustelem/zxcvbn: оценка угадываемости вместо правил состава.
//
// Единственная внешняя зависимость каталога — сама библиотека. Ради неё
// адаптер и существует: словари частых паролей, клавиатурных рядов, имён и
// дат весят мегабайты, и ядро, потянувшее их за собой, перестало бы
// собираться у потребителя, который оценки силы не просил.
//
// Безопасность:
//
//  1. ОЦЕНКА ВМЕСТО ПРАВИЛ СОСТАВА. Библиотека ловит то, что действительно
//     перебирают первым: повторы, ряды клавиатуры, словарь, даты, свой же
//     адрес. Правило «цифра и спецсимвол» не ловит ничего из этого.
//  2. ПОТОЛОК ДЛИНЫ ДЕРЖИТ ВЫЗЫВАЮЩИЙ. Алгоритм квадратичен по длине, и
//     тысяча символов стоит секунд; префикс режет password.Policy — до, а не
//     после вызова адаптера.
//  3. ШКАЛА ТА ЖЕ, ЧТО У ФРОНТЕНДА. Тот же zxcvbn крутится в браузере для
//     живого индикатора, поэтому порог совпадает, и человек не видит
//     «сильный» на форме и «слабый» в ответе сервера.
//  4. АДАПТЕР БЕЗ СОСТОЯНИЯ И БЕЗ СЕТИ. Словари внутри библиотеки; ни пароль,
//     ни его префикс никуда не уходят и не логируются.
//
// Чего в адаптере нет (решения, не пробелы): проверки по спискам утёкших
// паролей (это сетевой вызов, то есть второй адаптер того же порта со своим
// таймаутом и своим fail-closed); настроек словарей и весов — расхождение с
// фронтендом стоит дороже тонкой настройки; кэша оценок — ключом кэша был бы
// пароль.
