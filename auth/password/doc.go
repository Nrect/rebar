// Package password — argon2id в формате PHC, общий на процесс потолок
// одновременных хеширований и политика пароля (длина плюс порог силы).
//
// Hasher.Hash отдаёт строку с параметрами внутри, поэтому перенастройка цены
// не ломает проверку старых паролей. Hasher.Verify берёт параметры из строки
// и ограничивает их сверху. Hasher.Equalize делает холостое хеширование той же
// цены — для ответа на несуществующий логин. Policy.Check проверяет длину, а
// затем силу через порт StrengthChecker (адаптер — auth/pwzxcvbn).
//
// Ядро пакета — stdlib плюс golang.org/x/crypto ради argon2id: в stdlib его
// нет, а своя реализация в пакете аутентификации — своя криптография.
//
// Безопасность:
//
//  1. ПАРАМЕТРЫ ПРОВЕРКИ ОГРАНИЧЕНЫ СВЕРХУ. Они лежат внутри строки хэша,
//     то есть их задаёт тот, кто эту строку записал: без потолков одна
//     враждебная или повреждённая строка в колонке заставила бы процесс
//     выделить гигабайт на одну проверку пароля. Память — самый дорогой из
//     трёх параметров, поэтому её потолок узкий (MaxVerifyMemoryKiB).
//  2. ПОТОЛОК ОДНОВРЕМЕННОСТИ ОДИН НА ПРОЦЕСС, 2..4 СЛОТА. Память — свойство
//     ОДНОВРЕМЕННОСТИ, а не частоты: сто запросов в секунду при двух слотах
//     стоят двух буферов, а десять одновременных при десяти слотах — десяти.
//     Ограничитель частоты запросов этого не режет вовсе. Семафор пакетный, и
//     второй хешер с другим числом слотов роняет процесс на старте: два реалма
//     иначе сложили бы свои лимиты памяти.
//  3. ПЕРЕГРУЗКА НЕОТЛИЧИМА ОТ НЕВЕРНЫХ ДАННЫХ. Verify и Equalize отвечают
//     одним ErrBusy с одним текстом; вызывающий обязан свернуть его в обычный
//     отказ входа. Иначе сам потолок становится каналом перебора: по ответу
//     видно, нашёл ли сервер логин. У ErrBusy нет и Retry-After — он сообщил
//     бы перебирающему, что потолок найден.
//  4. ErrBusy НЕ ОБОРАЧИВАЕТ КОНТЕКСТ. Обёртка сделала бы errors.Is(err,
//     context.DeadlineExceeded) истинным, и слой HTTP отдал бы таймаут вместо
//     отказа по занятости: другой алерт и другой инцидент. Отменённый на входе
//     контекст, наоборот, отдаётся как есть — очередь ещё не занимали.
//  5. ДЛИНА ПРОВЕРЯЕТСЯ ДО ХЕШИРОВАНИЯ И ДО ОЦЕНКИ СИЛЫ. Мегабайтный пароль
//     на публичной ручке — это отказ в обслуживании; оценка силы вдобавок
//     квадратична по длине, поэтому в неё уходит только префикс
//     ScoreSampleLen.
//  6. СОСТАВНЫХ ПРАВИЛ НЕТ ОСОЗНАННО (NIST 800-63B). «Цифра, спецсимвол и
//     заглавная» гонят людей к Password1! и к записке на мониторе, но не
//     мешают перебору; слабость ловит оценка угадываемости.
//  7. ПРОВЕРКА СИЛЫ ОБЯЗАТЕЛЬНА. Порт без реализации — паника конструктора,
//     а не «политика только по длине»: флаг, выключающий инвариант, рано или
//     поздно окажется включённым в проде как разрешённая настройка.
//  8. СОЛЬ СВОЯ НА КАЖДЫЙ ХЭШ, СРАВНЕНИЕ ПОСТОЯННОГО ВРЕМЕНИ. Одинаковые
//     хэши у двух людей с одним паролем превращают дамп базы в список «кого
//     перебирать первым».
//  9. НИ ПАРОЛЬ, НИ ХЭШ, НИ СОЛЬ НЕ ПОПАДАЮТ В ТЕКСТ ОШИБКИ. Лог — самое
//     доступное место системы и переживает инцидент дольше всех.
//  10. БИТАЯ СТРОКА — ОШИБКА, А НЕ «ПАРОЛЬ НЕ ПОДОШЁЛ». ErrHashInvalid значит
//     дефект данных, который чинят; молча слитый с несовпадением, он выглядел
//     бы как забывчивость пользователя.
//
// Метрики (декоратором у потребителя; ядро otel не импортирует):
//
//	rebar.auth.password.inflight   gauge     Hasher.InFlight — занятость потолка
//	rebar.auth.password.slots      gauge     Hasher.Slots — сам потолок
//	rebar.auth.password.busy       counter   отказы ErrBusy
//
// Алерт: inflight == slots дольше минуты — потолок насыщен, вход деградирует;
// busy > 0 на устойчивом фоне — либо всплеск, либо перебор.
//
// Чего в пакете нет (решения, не пробелы): хранения паролей и истории смен;
// проверки по спискам утёкших паролей — это сетевой вызов за портом
// StrengthChecker, а не дело ядра; bcrypt и scrypt — один алгоритм проще
// сопровождать, а PHC-строка оставляет место для второго; перехеширования при
// смене параметров — оно нужно на входе, где виден и пароль, и старый хэш,
// то есть в сервисе сессий; счётчика попыток и блокировки — они в
// auth/session, потому что ведутся по логину, а не по паролю.
