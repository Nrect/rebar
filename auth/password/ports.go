package password

// Score — оценка угадываемости пароля, 0 (тривиальный) .. 4 (стойкий).
// Шкала zxcvbn; её же крутит фронтенд для живого индикатора.
const (
	ScoreMin = 0
	ScoreMax = 4
)

// StrengthChecker — оценка силы пароля за портом.
//
// ПОРТ НУЖЕН РАДИ ГРАНИЦЫ ЗАВИСИМОСТЕЙ: словарь частых паролей и клавиатурных
// рядов весит мегабайты и приезжает с внешней библиотекой, а ядро обязано
// собираться у потребителя, который её не подключал. Реализация — auth/pwzxcvbn.
//
// Score обязан вернуть значение в [ScoreMin, ScoreMax]; всё, что вне, Policy
// считает нулём — испорченный адаптер должен ужесточать проверку, а не
// открывать её.
type StrengthChecker interface {
	// Score оценивает пароль с учётом userInputs — данных самого человека
	// (адрес, имя), которые в его пароле означают слабость, а в чужом нет.
	Score(password string, userInputs []string) int
}
