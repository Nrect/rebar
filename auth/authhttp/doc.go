// Package authhttp — сессионная кука, CSRF double-submit и middleware поверх
// session.Service.
//
//	cfg := authhttp.DefaultCookieConfig("shop_session")
//	r.Use(authhttp.Middleware(svc, cfg, func(w http.ResponseWriter, r *http.Request, err error) {
//		responder.Write(r.Context(), w, err) // kit/errs/httperr потребителя
//	}))
//
// Пакет НЕ пишет тело ответа сам: 401 и 403 отдаёт Deny потребителя. Формат
// ошибки принадлежит его API, и второй формат, зашитый в middleware, дал бы
// клиенту два разных тела на соседних ручках (ADR-0003, «authhttp»).
//
// Ядро — stdlib и auth; внешних зависимостей у каталога нет.
//
// Безопасность:
//
//  1. СЕССИОННАЯ КУКА HttpOnly ВСЕГДА, И ЭТО НЕ НАСТРОЙКА. XSS не должен
//     превращаться в кражу сессии, поэтому флага «дайте скрипту почитать» тут
//     нет.
//  2. CSRF-КУКА НЕ HttpOnly, И ТОЖЕ НЕ ПО ВЫБОРУ. Её обязан прочитать
//     фронтенд, чтобы вернуть значение заголовком: в этом весь double-submit.
//  3. СРАВНЕНИЕ ПОСТОЯННОГО ВРЕМЕНИ. Обычное == выходит из цикла на первом
//     несовпавшем байте, и токен подбирается по байту за раз по времени
//     ответа (TestCSRF_ComparisonIsConstantTime).
//  4. SameSite ОБЯЗАТЕЛЕН ЯВНО. http.SameSiteDefaultMode означает «на
//     усмотрение браузера», то есть разные правила у разных браузеров — и
//     защита, о которой нельзя сказать, есть она или нет. SameSite=None без
//     Secure браузер отвергает МОЛЧА: кука не ставится, вход не работает, а
//     ошибки нет.
//  5. ПРЕФИКС __Host- ПРОВЕРЯЕТСЯ. Он и делает наивный double-submit
//     осмысленным: куку с таким именем нельзя поставить с поддомена, то есть
//     нельзя подсунуть свой CSRF-токен. Условия браузера (Secure, Path=/,
//     пустой Domain) держит инвариант CookieConfig.
//  6. ПОРЯДОК ПРОВЕРОК ОТ ДЕШЁВОЙ К ДОРОГОЙ. Подделанный межсайтовый запрос
//     несёт куку, но не несёт заголовка: проверка CSRF до Resolve отбивает
//     его, не тратя соединение из пула.
//  7. НЕБЕЗОПАСНЫМ СЧИТАЕТСЯ ВСЁ, КРОМЕ ЧЕТЫРЁХ МЕТОДОВ. Список безопасных
//     закрыт (GET, HEAD, OPTIONS, TRACE), список опасных — нет: нестандартный
//     глагол обязан проходить проверку, а не мимо неё.
//  8. ПУСТОЙ ПРИНЦИПАЛ НАРУЖУ НЕ ВЫДАЁТСЯ. PrincipalFrom отвечает false на
//     запрос без сессии: нулевое значение, принятое за принципала, — это
//     доступ от лица uuid.Nil.
//
// Чего в пакете нет (решения, не пробелы): форм и ручек входа — их пишет
// потребитель, у него свои поля, своя валидация и свои тексты; тела ответа
// об ошибке — его формат (Deny); ограничителя частоты запросов — он снаружи,
// в kit/ratelimit; определения IP клиента — в kit/ratelimit/ratelimithttp уже
// есть ClientIP со списком доверенных прокси; сессий в подписанной куке —
// непрозрачная сессия отзывается одним DELETE, подписанная не отзывается
// никак.
