// Package auth — общие типы аутентификации: реалм, принципал, личность и порт
// таблицы пользователей. Механика живёт в подпакетах: password — argon2id и
// политика пароля, token — одноразовые токены и секрет реалма, pwzxcvbn —
// адаптер оценки силы, authtest — двойники.
//
// Реалм — это экземпляр сервиса, а не поле в запросе: покупатели и персонал
// различаются секретом, кукой и источником личностей, то есть конфигурацией.
// Общим на процесс остаётся один password.Hasher — ради общего потолка памяти
// (password, «Безопасность», п. 2).
//
// Таблицы пользователей в пакете нет и не будет: у каждого потребителя свой
// профиль, свои связи и свои внешние ключи. Он реализует порт Identities —
// это около двадцати строк, и его таблица остаётся его.
//
// Ядро — stdlib плюс github.com/google/uuid. Проект и причины —
// docs/adr/0003-auth-authz-entitlement.md.
//
// Безопасность:
//
//  1. ОДНА ОШИБКА НА «НЕТ ЛОГИНА» И «НЕ ТОТ ПАРОЛЬ». ErrIdentityNotFound
//     наружу не выходит: разные ответы превращают форму входа в проверялку
//     существования адреса, работающую без всякой блокировки.
//  2. ЗАНЯТЫЙ ЛОГИН НЕ ВИДЕН СНАРУЖИ. ErrLoginTaken остаётся внутри:
//     регистрация отвечает «принято» и шлёт письмо владельцу адреса.
//  3. В ПРИНЦИПАЛЕ ХЭШ СЕССИИ, А НЕ ТОКЕН. Principal уезжает в контекст
//     запроса и в аудит потребителя; сырой токен там означал бы токен в логе.
//  4. ФОРМА РЕАЛМА ЗЕРКАЛИТСЯ CHECK-АМИ СХЕМЫ. Реалм входит в ключи строк и
//     в WHERE уборки: разъезд кода и базы даёт строки, которые уже нельзя ни
//     прочитать, ни удалить.
//  5. СБОЙ ИСТОЧНИКА ЛИЧНОСТЕЙ — ErrUnavailable, ТО ЕСТЬ 503. «Неверные
//     данные» при недоступной базе учит поддержку и клиента чинить пароль
//     вместо базы, а инцидент тонет.
//  6. ЛОГИН НОРМАЛИЗУЕТСЯ ОДИН РАЗ (NormalizeLogin). Счётчик блокировок
//     ведётся по логину, поэтому разные написания одного адреса обязаны дать
//     один ключ — иначе блокировка обходится клавишей Shift. Точка
//     нормализации ровно одна: порт получает логин уже нормализованным.
//  7. ВРЕМЯ В ПОРТ ПРИХОДИТ ПАРАМЕТРОМ. Без now() внутри адаптера тесты на
//     управляемых часах проверяют то же, что пишет база.
//
// Чего в пакете нет (решения, не пробелы): таблицы пользователей и её
// миграций; второй нормализации логина — индекс потребителя строится на
// сохранённой колонке, а не на выражении в SQL, иначе функция в индексе стала
// бы второй точкой нормализации и разъехалась с NormalizeLogin на первом же
// обновлении ICU; ролей и разрешений — это отдельная ось
// (модуль authz); прав по покупке — третья ось (модуль entitlement); вторых
// факторов, passkeys, OAuth, JWT и bearer-токенов; ограничителя частоты
// запросов — он снаружи, в kit/ratelimit. Причины — ADR-0003, раздел «Чего
// нет в auth».
