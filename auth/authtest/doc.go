// Package authtest — двойники для тестов потребителя и самого модуля auth.
// Docker не нужен, всё потокобезопасно: тесты идут под -race.
//
// FastHasher — настоящий argon2id на полах OWASP: примерно тридцать
// миллисекунд на хэш вместо сотни, поэтому набор тестов идёт за секунды.
// Заглушки вместо хеширования здесь нет осознанно — тест, гоняющий подделку,
// зелен при сломанном разборе PHC, и потребитель узнаёт об этом в проде.
//
// MemIdentities — двойник порта auth.Identities: логин уникален по-настоящему,
// повторное Create отвечает auth.ErrLoginTaken, времена приходят параметром и
// хранятся, а отказ хранилища инъецируется полем Err и отличим от доменных
// ошибок (ErrInjected).
//
// Strength — проверка силы с заданным ответом: так тест задаёт «этот пароль
// слабый», не подбирая строку, которую забракует настоящий словарь. Двойник
// не запоминает вызовы: он моделирует исход, а не протокол (docs/PATTERNS.md,
// паттерн 7).
//
// MemSessions и MemAttempts — двойники портов session.Sessions и
// session.Attempts. Оба гоняются тем же контрактным набором, что и адаптер:
// RunSessionsSuite и RunAttemptsSuite живут здесь, пишутся на голом testing и
// зовутся и из authtest, и из authpg — расхождение двойника с базой обязано
// быть видно сразу, а не у потребителя (CONVENTIONS §5).
//
// MemTokens — двойник порта session.Tokens, единственного, который в проде
// пишет потребитель. Он СВЯЗАН С MemIdentities и честно применяет эффект
// назначения: подтверждает адрес, пишет новый хэш, переносит логин. Двойник,
// который только помечает токен использованным, оставил бы зелёным тест
// «подтверждение адреса работает» при неработающем подтверждении. Эффект и
// гашение идут под одним мьютексом, поэтому сбой эффекта оставляет токен
// живым — как откат транзакции в адаптере потребителя.
//
// RecordingNotifier и RecordingAuditor копят письма и события; наружу отдают
// копии, чтобы правка полученного не меняла состояние двойника. Clock —
// управляемые часы для Service.SetClock.
//
// Calls — счётчик вызовов, вшитый в двойники хранилищ. Он не превращает их в
// моки: исход они моделируют по-настоящему, а счётчик нужен там, где инвариант
// — это ОТСУТСТВИЕ вызова («до стора не дошли», «известный и несуществующий
// логин дали одни и те же обращения»). Через исход такое не видно: гвард
// сервиса и та же проверка в сторе отдают один и тот же sentinel.
//
// ЛОВУШКА: потолок одновременных хеширований один на процесс, поэтому
// FastHasherConfig берёт password.MinSlots. Тест, собравший хешер с другим
// числом слотов, уронит конструктор — это не дефект двойника, а тот самый
// инвариант (password, «Безопасность», п. 2). MaxWait при этом менять можно и
// нужно: десятки параллельных тестов на двух слотах с боевым ожиданием
// упираются в ErrBusy и падают «перегрузкой» вместо своего сценария.
