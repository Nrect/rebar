// Package session — вход, сессии, одноразовые токены и уборка одного реалма.
//
// Реалм — это ЭКЗЕМПЛЯР Service: покупатели и персонал живут в одном процессе,
// но с разными секретами, куками и источниками личностей. Общим на процесс
// остаётся один password.Hasher — ради общего потолка памяти.
//
//	svc := session.New(session.Deps{
//		Identities: myUsers, Sessions: store, Attempts: store, Tokens: myTokens,
//		Hasher: hasher, Policy: policy, Notifier: myMailer,
//	}, session.DefaultConfig("shop", token.MustSecret(key)))
//
// Сессии непрозрачные: в базе лежит HMAC, у человека — сырой токен в куке.
// Ни JWT, ни refresh-токенов: у сессии в куке роль refresh играет скользящее
// продление, а плата за JWT — невозможность мгновенного отзыва.
//
// Ядро — stdlib плюс github.com/google/uuid. Проект и причины —
// docs/adr/0003-auth-authz-entitlement.md.
//
// # Порт Tokens пишет потребитель
//
// Issue и Consume обязаны быть атомарны с ЕГО таблицами: Issue кладёт строку
// токена и ставит письмо в очередь, Consume гасит токен и применяет эффект в
// таблице пользователей. Половину даёт authpg (Insert, ConsumeRow,
// RevokeOfSubject, PurgeExpired на postgres.Querier), вторую — он сам; пример
// адаптера целиком лежит в authpg/doc.go.
//
// # Что видеть на дашборде
//
// Ядро метрик не пишет и otel не импортирует (CONVENTIONS §6), поэтому таблица
// ниже — контракт с потребителем, а не список того, что пакет отдаёт сам.
// Декоратора session.Service в v0.1 нет осознанно: счётчик снимается там же,
// где живёт httperr, из ответов ручек входа, и второй источник тех же цифр
// разошёлся бы с первым.
//
//	rebar.auth.signin{result}     counter   ok | invalid | locked | unverified | unavailable
//	rebar.auth.tokens{purpose}    counter   выданные ссылки: verify | reset | email_change
//	rebar.auth.sweep{table}       counter   убрано строк: sessions | attempts | tokens
//	rebar.auth.password.inflight  gauge     Hasher.InFlight — занятость потолка (password)
//
// Метки — ЗАКРЫТЫЕ наборы; логин, адрес и идентификатор субъекта меткой не
// становятся: они взрывают кардинальность и уносят персональные данные в
// систему мониторинга, откуда их уже не удалить по требованию субъекта.
//
// Алерты: доля result=locked выше обычного фона — либо перебор, либо сломанная
// форма входа; result=unavailable больше нуля дольше минуты — недоступно
// хранилище, и вход отвечает 503; sweep{sessions} = 0 сутки подряд — уборка не
// запускается, и таблица растёт.
//
// Безопасность:
//
//  1. ОДНА ОШИБКА НА «НЕТ ЛОГИНА» И «НЕ ТОТ ПАРОЛЬ». Сюда же — битый хэш в
//     колонке и отключённый субъект. Любое различие превращает форму входа в
//     проверялку существования адреса, которая работает быстрее перебора
//     паролей и не трогает ни счётчик, ни лимитер.
//  2. ХОЛОСТАЯ ПРОВЕРКА ДЛЯ НЕИЗВЕСТНОГО ЛОГИНА. Ответ на чужой адрес обязан
//     стоить того же argon2id, что ответ на свой: без Equalize перебор идёт по
//     секундомеру, вообще не оставляя следов.
//  3. ПЕРЕГРУЗКА НЕОТЛИЧИМА. password.ErrBusy сворачивается в
//     ErrTooManyAttempts одинаково для существующего и несуществующего логина
//     — иначе сам потолок хеширований становится каналом перебора адресов.
//     Попытка при этом НЕ пишется: всплеск не должен запирать законных
//     владельцев.
//  4. СЧЁТЧИК ВЕДЁТСЯ ПО ЛОГИНУ, В ТОМ ЧИСЛЕ НЕСУЩЕСТВУЮЩЕМУ, и по
//     нормализованному (loginid.Normalize). Счётчик только для заведённых
//     логинов сам отвечает «есть ли такой адрес»; счётчик без нормализации
//     обходится клавишей Shift. Исчерпанный счётчик не пополняется — иначе
//     любой желающий запирает чужой адрес навсегда.
//  5. РЕГИСТРАЦИЯ ОТВЕЧАЕТ «ПРИНЯТО», А ПОВТОРНАЯ ОТПРАВКА И СБРОС — ТИХИЙ
//     NO-OP. На занятый адрес уходит письмо ВЛАДЕЛЬЦУ, а не ответ «занято»
//     тому, кто спрашивал. Хэш считается до Create, поэтому обе ветки стоят
//     одинаково.
//  6. ТОКЕНЫ НЕ ХРАНЯТСЯ. В порт уходит только HMAC под секретом реалма; сырой
//     токен живёт в письме и в куке. Дамп базы не даёт ни живой сессии, ни
//     рабочей ссылки сброса, и в событие аудита сырой токен не попадает.
//  7. ОДНОРАЗОВОСТЬ АТОМАРНА. Consume гасит токен и применяет эффект одной
//     транзакцией, Issue гасит прежние токены того же назначения. Смена
//     пароля отзывает ВСЕ сессии и ВСЕ токены сброса, причём отзыв идёт до
//     записи нового хэша: на сбое отзыва чужая сессия не должна пережить
//     смену.
//  8. СЕССИЯ СКОЛЬЗЯЩАЯ, НО С ПОТОЛКОМ. IdleTTL продлевается не чаще
//     RenewEvery, SessionTTL абсолютен и не двигается никогда; отключённый
//     субъект отвергается на первом же Resolve, не дожидаясь истечения.
//  9. СБОЙ ХРАНИЛИЩА — ОТКАЗ, А НЕ ПРОПУСК. Непрочитанный счётчик попыток,
//     незаписанная попытка, неудавшееся продление дают auth.ErrUnavailable
//     (503): вход, работающий при сломанной защите от перебора, — это вход
//     без защиты от перебора.
//  10. ПЕРСОНАЛЬНЫХ ДАННЫХ НЕТ В ОШИБКАХ И СОБЫТИЯХ. Логин, пароль, хэш и
//     сырой токен не попадают ни в текст ошибки, ни в Event: журнал
//     безопасности живёт дольше всего, а причина неудачного входа в нём —
//     та же проверялка существования, только для читающего журнал.
//
// Чего в пакете нет (решения, не пробелы): таблицы пользователей — она у
// потребителя за портом auth.Identities; реализации Tokens — эффект токена
// применяется в ЕГО таблице, и атомарность живёт там, где видны обе;
// сброса счётчика попыток удачным входом — окно короткое, а лишняя запись
// стоит на самом горячем пути; вторых факторов и TOTP — шов оставлен,
// SignIn возвращает результат, а не токен; passkeys, OAuth, входа через
// соцсети, JWT, bearer- и refresh-токенов; API-ключей; «запомнить меня»
// сверх IdleTTL; управления устройствами; ролей — это отдельная ось (модуль
// authz); отправки писем — порт Notifier и Tokens.Issue ведут в mail;
// ограничителя частоты запросов — он снаружи, в kit/ratelimit; HTTP-форм
// входа. Причины — ADR-0003, раздел «Чего нет в auth».
