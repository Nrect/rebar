// Package token — одноразовые токены и секрет реалма: генерация 256 случайных
// бит, HMAC-SHA256 под секретом реалма и закрытый набор назначений.
//
// Сырой токен отдаётся человеку один раз — в куке или в ссылке письма. В
// хранилище ложится только Hash: и для сессий, и для подтверждения адреса, и
// для сброса пароля.
//
// Ядро — stdlib, внешних зависимостей нет.
//
// Безопасность:
//
//  1. В ХРАНИЛИЩЕ ТОЛЬКО ХЭШ. Дамп базы не даёт ни живой сессии, ни рабочей
//     ссылки сброса: HMAC необратим, а без секрета реалма его не пересчитать
//     и по угаданному токену. Сырой токен не логируется и не попадает в
//     событие аудита.
//  2. ХЭШ КЛЮЧЕВОЙ, И КЛЮЧ — СЕКРЕТ РЕАЛМА. Простой SHA-256 позволил бы
//     проверять догадки офлайн по украденной таблице; ключ это закрывает и
//     заодно разводит реалмы — один сырой токен даёт в них разные хэши.
//  3. СЕКРЕТ НЕ КОРОЧЕ MinSecretLen. HMAC под коротким ключом создаёт
//     видимость защиты: он перебирается офлайн по одной украденной строке,
//     после чего дамп снова даёт живые токены.
//  4. НЕНАСТРОЕННЫЙ СЕКРЕТ РОНЯЕТ ВЫЗОВ. HMAC под пустым ключом дал бы
//     одинаковый хэш у всех, кто собрал сервис без секрета, — молчаливый
//     отказ защиты вместо громкого.
//  5. СЕКРЕТ РЕДАКТИРУЕТСЯ ВО ВСЕХ ФОРМАХ ПЕЧАТИ. Одного String мало: %#v и
//     %x достают байты рефлексией, json.Marshal выкладывает их в ответ
//     отладочной ручки, slog — в лог. Реализованы fmt.Formatter,
//     slog.LogValuer и json.Marshaler разом.
//  6. СЕКРЕТ КОПИРУЕТСЯ ПРИ СОЗДАНИИ. Правка исходного среза вызывающим иначе
//     меняла бы секрет реалма на ходу, и все выданные до правки сессии тихо
//     переставали бы проверяться.
//  7. НАЗНАЧЕНИЕ — ЗАКРЫТЫЙ НАБОР, ЗЕРКАЛЯЩИЙ CHECK. Токен без известного
//     назначения нельзя ни погасить, ни применить; расхождение словаря кода
//     и базы иначе всплывает в проде на первом новом значении.
//
// Чего в пакете нет (решения, не пробелы): хранения токенов — таблица и
// атомарное гашение живут в адаптере, потому что эффект токена применяется в
// таблице потребителя (ADR-0003, «Почему Tokens реализует потребитель»);
// сроков жизни — они в Config сервиса сессий; отзыва и подсчёта попыток;
// кодов из шести цифр — короткий код требует своей защиты от перебора, и это
// отдельное решение, а не короче Generate.
