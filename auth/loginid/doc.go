// Package loginid — нормализация логина: единственная точка, через которую
// логин проходит перед тем, как стать ключом строки и ключом счётчика попыток.
//
// ОТДЕЛЬНЫМ КАТАЛОГОМ РАДИ ЗАВИСИМОСТИ. Нормализация Unicode требует
// golang.org/x/text — в stdlib её нет. Корень auth импортируют все: сервис
// сессий, адаптеры, двойники и слой хранения ПОТРЕБИТЕЛЯ, который всего лишь
// реализовал порт auth.Identities на четыре метода. Таблицы Unicode в графе
// зависимостей слоя данных — последнее, чего он ждёт, а нужны они ровно одному
// вызывающему. Правило «вторая внешняя зависимость — повод выносить, а не
// расширять белый список» (ADR-0005) здесь и применяется.
//
// Имя loginid, а не login: в пакете аутентификации «login» читается как вход,
// то есть как то, что живёт в сервисе сессий. Здесь речь про идентификатор.
//
// Безопасность:
//
//  1. ОДНА ТОЧКА НОРМАЛИЗАЦИИ, И ЭТО ПОЛОВИНА ЗАЩИТЫ ОТ ПЕРЕБОРА. Счётчик
//     блокировок ведётся по логину, в том числе несуществующему. Дай Alice@x.ru
//     и alice@x.ru разные ключи — и атакующий получит LockoutAttempts попыток
//     на каждое написание одного адреса, то есть блокировка обходится клавишей
//     Shift. Порт auth.Identities получает логин уже нормализованным, а
//     уникальный индекс потребитель строит на СОХРАНЁННОЙ колонке: функция в
//     индексе была бы второй точкой нормализации и разъехалась бы с этой на
//     первом же обновлении ICU.
//  2. НОРМАЛИЗАЦИЯ ИДЕМПОТЕНТНА, И ЭТО ПРОВЕРЕНО ФАЗЗЕРОМ, А НЕ ОБЕЩАНО.
//     Сохранённый логин проходит функцию один раз, искомый — другой; если
//     второй проход даёт другую строку, найденное и сохранённое расходятся, и
//     вход перестаёт работать у того, кто уже зарегистрирован.
//  3. NFKC ПРИМЕНЯЕТСЯ ДВАЖДЫ. Приведение регистра умеет выводить строку из
//     нормальной формы (у буквы с кольцом сверху нижний регистр даёт
//     разложенную пару), поэтому одного прохода до регистра мало. Нашёл фаззер;
//     вход лежит в testdata.
//  4. НЕГОДНЫЙ UTF-8 ОТВЕРГАЕТСЯ ДО НОРМАЛИЗАЦИИ. На испорченной
//     последовательности NFKC не идемпотентен: ведущий байт оборванной
//     четвёрки закрывает собой следующую руну, и она разворачивается только на
//     втором проходе. Тоже находка фаззера.
//  5. УПРАВЛЯЮЩИЕ И НЕВИДИМЫЕ СИМВОЛЫ — ОТКАЗ. Управляющий даёт перевод строки
//     в записи аудита, то есть подделку соседней строки журнала. Символ
//     форматирования (нулевая ширина, мягкий перенос, метки направления) NFKC
//     не убирает, поэтому логин с ним печатается неотличимо от чужого, а
//     строкой в базе и ключом счётчика он другой.
//  6. ПОТОЛОК ДЛИНЫ ПРОВЕРЯЕТСЯ ДО НОРМАЛИЗАЦИИ И ПОСЛЕ. До — чтобы
//     мегабайтная строка не доезжала до разбора; после — потому что NFKC умеет
//     удлинять.
//  7. ЛОГИНА НЕТ В ТЕКСТЕ ОШИБКИ. Он персональные данные, а текст ошибки
//     доезжает до лога и переживает инцидент дольше всех.
//  8. БАМП golang.org/x/text И ВЕРСИИ Go — СОБЫТИЕ, А НЕ РУТИНА. Результат
//     Normalize задают таблицы Unicode, и живут они не у нас: NFKC — в x/text,
//     приведение регистра и категория Cf — в stdlib. Смена результата для того
//     же сырого входа означает, что сохранённые логины перестают находиться, а
//     починить это задним числом нечем: в базе лежит нормализованный логин,
//     сырого входа нет и восстановить его не из чего. Обновлять сознательно;
//     страж — золотые значения в TestNormalize_GoldenValuesPinTheUnicodeTables,
//     покрасневший тест значит «посмотри, что стало с чужими логинами», а не
//     «поправь ожидание». Политика стабильности Unicode прикрывает уже
//     назначенные символы, но не прикрывает два случая: символ, ставший
//     назначенным после бампа, и приведение регистра — на него она не
//     распространяется вовсе.
//
// Чего в пакете нет (решения, не пробелы): проверки, что логин похож на адрес
// почты, — логином может быть телефон или имя, а разбор адреса живёт в mail;
// сравнения похожих начертаний (кириллическая «а» против латинской) — это
// таблицы confusables, отдельная зависимость и отдельное решение, а к перебору
// оно отношения не имеет; развёртывания плюс-адресации (alice+tag@x.ru) —
// склеивать её с alice@x.ru значит решать за потребителя, что это один
// человек; хранения и поиска — они за портом auth.Identities.
