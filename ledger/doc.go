// Package ledger — журнал движений остатка, который приложение не может
// переписать: пополнения и списания, отмена встречной записью, остаток в
// самой записи и цепь подписей HMAC (ADR-0009).
//
// Книга — экземпляр, а не копия пакета: кошелёк и баллы — два Config с разными
// Book и ключами. Движение идёт в транзакции потребителя —
// svc.WithStore(store.WithTx(tx)).Post(ctx, req): под блокировкой счёта ядро
// пробует ключ идемпотентности, подписывает и вставляет запись. Пример
// подключения — example_test.go.
//
// Ядро — stdlib, github.com/google/uuid и kit; двойник и контрактный набор
// хранилища — ledgertest. Адаптер Postgres с триггерами и привилегиями и
// сверка по расписанию с метриками — следующие шаги ADR-0009.
//
// Безопасность:
//
//  1. ПОДПИСЬ ОБЯЗАТЕЛЬНА: HMAC-SHA256 ключом вне базы. Config без ключа —
//     паника, выключателя нет (решение 4).
//  2. КЛЮЧ НЕ ПОКИДАЕТ GO: в порт, SQL и тексты ошибок не попадает, Config
//     печатается без байтов ключей в любой форме.
//  3. ПРЕФИКС ДЛИНЫ У КАЖДОГО ПОЛЯ ПОДПИСИ: причину пишет оператор, ключ шлёт
//     клиент, и без префикса "ab"+"cd" совпало бы с "abcd"+"". Страж —
//     TestCanonical_FieldBoundariesDoNotCollide.
//  4. МОМЕНТ НОРМАЛИЗУЕТСЯ ВНУТРИ ПОДПИСИ (UTC, микросекунды): из базы он
//     приходит в зоне соединения и без наносекунд.
//  5. ПОДПИСЬ СРАВНИВАЕТСЯ ЗА ПОСТОЯННОЕ ВРЕМЯ: ранний выход подсказывал бы
//     её побайтно.
//  6. ПРОБА ИДЕМПОТЕНТНОСТИ — ПОД БЛОКИРОВКОЙ СЧЁТА: до неё порт ключ не
//     даёт. Тот же ключ на другую операцию — ErrKeyReused, а не тихий повтор.
//  7. НОМЕР БЕЗ ДЫР, ОСТАТОК В ЗАПИСИ, ГРАНИЦА — ЗНАЧЕНИЕ. Ядро проверяет их
//     под блокировкой, хранилище — ещё раз при вставке: запись мимо пакета
//     отбивается схемой. Страж — гонки ledgertest.RunStoreSuite.
//  8. ОТМЕНА — ВСТРЕЧНОЙ ЗАПИСЬЮ: сумма ровно противоположная, одна на запись,
//     отмена отмены запрещена, род по умолчанию не отменяет никто (решение 10).
//  9. НЕИЗВЕСТНЫЙ НОМЕР КЛЮЧА — «ПРОВЕРИТЬ НЕЧЕМ», А НЕ ПОДДЕЛКА
//     (CheckUnknownKey): старые ключи из Config.Keys не удаляются никогда.
//  10. ФОРМАТ ПОДПИСИ — КОНТРАКТ СОВМЕСТИМОСТИ: подписанные строки лежат у
//     потребителей. Страж — TestSign_GoldenVector.
//
// # Чего в пакете НЕТ
//
//  1. ВНЕШНЕГО ЯКОРЯ ЦЕПИ. Цепь tamper-evident, а не tamper-proof: владелец
//     базы и ключа перепишет хвост целиком, утёкший ключ подделает записи под
//     своим номером. Якорь — публикация головы вовне — отдельное решение.
//  2. ДВОЙНОЙ ЗАПИСИ: вторая нога была бы фиктивной, пока нет своего учёта
//     кассы; журнал append-only, и переход к ней остаётся возможным.
//  3. ЧАСТИЧНОЙ ОТМЕНЫ: остаток — отдельное движение.
//  4. МУЛЬТИВАЛЮТНОСТИ И ПЕРЕВОДА МЕЖДУ КНИГАМИ: единица — свойство книги,
//     курс предметен.
//  5. НАЧИСЛЕНИЙ ПО РАСПИСАНИЮ, СГОРАНИЯ, КВОТ: это политика потребителя.
//  6. ВЫПИСКИ С ПРАВАМИ И СТРАНИЦАМИ, HTTP-РУЧЕК: выборки и доступ — домен
//     потребителя.
