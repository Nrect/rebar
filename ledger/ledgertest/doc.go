// Package ledgertest — двойник хранилища ledger и контрактный набор порта для
// тестов потребителей и адаптеров. Двойник — не мок: он держит инварианты
// схемы, чтобы тест проверял исход, а не список вызовов. Собирается без
// тестовых зависимостей: пакет компилирует потребитель.
//
// Ошибки двойника отличимы от доменных (ErrTxDone, ErrUnknownBook) и завёрнуты
// в sentinel модуля с тем классом, что даст адаптер. Сбой (SetErr) и
// отменённый контекст приходят в ledger.ErrUnavailable, как у ledgerpg
// (ADR-0007, «Двойники»).
//
// Жители:
//
//   - MemStore — ledger.Store в памяти: номер без дыр, цепь prev_hash, остаток
//     в записи и в голове счёта, граница книги, ключ в пределах счёта, одна
//     отмена на запись, моменты как в timestamptz; SetErr и CallCount для
//     утверждений «до хранилища не дошли».
//   - RunStoreSuite — контрактный набор: один на двойник и ledgerpg, с гонками
//     условий выпуска 5 и 6 ADR-0009.
//   - Clock — управляемые часы для ledger.Service.SetClock.
