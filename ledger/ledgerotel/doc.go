// Package ledgerotel — наблюдаемость сверки журнала на OpenTelemetry metric API:
// ledger.Observer со счётчиком ledger_reconcile_mismatch{book,check}.
//
// Ядро метрик не пишет и otel не импортирует (CONVENTIONS §6); зависимость
// живёт здесь. Meter — rebar.ledger. Собирается так:
//
//	obs, err := ledgerotel.NewObserver(meter)
//	rec := ledger.NewReconciler(svc, obs, ledger.ReconcileConfig{Accounts: 200, Page: 500})
//	job := scheduler.Job{Name: "wallet_reconcile", Interval: 10 * time.Minute, Run: rec.Run}
//
// Инструменты (имя и единица — контракт, на них стоят алерты потребителя;
// ADR-0009, решение 5):
//
//	| Метрика                               | Тип          | Что |
//	|---------------------------------------|--------------|-----|
//	| ledger_reconcile_mismatch{book,check} | counter      | расхождения сверки, по одному на найденное за проход; все пары книги × ledger.AllChecks заводятся нулём |
//	| cron.*{job="wallet_reconcile"}        | из scheduler | прогоны сверки; cron.processed — проверенные записи |
//
// Prometheus-экспортёр отрисует ledger_reconcile_mismatch_total. Алерты:
//
//   - «журнал правили мимо пакета» — рост
//     ledger_reconcile_mismatch_total{check!="unknown_key"}, порог 1, разбор
//     обязателен: запись, остаток или подпись разошлись с цепью;
//   - «ключ подписи удалён» — рост ledger_reconcile_mismatch_total{check="unknown_key"},
//     порог 1: не подделка, а Config без старого ключа (ledger/doc.go, п. 9) —
//     записи проверить нечем, ключ возвращают в Config;
//   - «сверка умерла» — time() − cron_last_success_timestamp_seconds{job="wallet_reconcile"}
//     больше двух интервалов: сверка, которая не идёт, молчит так же, как сверка
//     без расхождений.
//
// Расхождение, оставшееся в базе, находится на каждом проходе: алерт горит,
// пока журнал не восстановлен или ключ не возвращён.
//
// Безопасность:
//
//  1. МЕТКИ — ЗАКРЫТЫЕ НАБОРЫ: check из ledger.AllChecks, book — имя книги из
//     ledger.Config, форму [a-z0-9_]{1,32} проверяет ledger.NewService. Счёт,
//     номер и id записи меткой не становятся: это данные покупателя и
//     кардинальность.
//  2. РЯДЫ РОЖДАЮТСЯ НУЛЁМ: ledger.NewReconciler зовёт Watch до первого прогона.
//     Ряд, появившийся сразу единицей, increase() не видит, а у обоих алертов
//     порог 1 — первое расхождение и есть тревога.
//  3. НАБЛЮДАТЕЛЬ НЕ ЧИТАЕТ ЗАПИСЕЙ И НЕ ЛОГИРУЕТ: из находки берутся книга и
//     проверки.
//  4. FAIL CLOSED НА СБОРКЕ: nil-метр — паника; ошибка создания инструмента
//     возвращается — метрик у потребителя может не быть, а сверка нужна.
//
// Чего нет (решения, не пробелы): счётчика проверенных записей — его даёт
// cron.processed планировщика, Run отдаёт ровно это число; гейджа «расхождений
// сейчас» — счётчик растёт на каждом проходе, пока расхождение в базе; трейсов —
// прогон идёт под span'ом задачи потребителя; выбора имени инструмента — на нём
// стоят чужие алерты.
