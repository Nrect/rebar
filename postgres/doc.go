// Package postgres — идиомы транзакций и ошибок на github.com/jackc/pgx/v5:
// транзакция с таймаутами, повтор по SQLSTATE, ошибка без содержимого строки,
// параметры соединения.
//
// Пул создаёт потребитель и отдаёт его New вместе с политикой. Дальше вся
// работа с базой идёт через Runner: он ставит SET LOCAL таймауты внутри
// транзакции, доводит её до commit или rollback и очищает ошибку на выходе.
//
//	run := postgres.New(pool, postgres.Config{
//		LockTimeout: 3 * time.Second, StatementTimeout: 15 * time.Second,
//		MaxAttempts: 3, RetryBase: 20 * time.Millisecond,
//	})
//	err := run.InTx(ctx, func(ctx context.Context, tx pgx.Tx) error {
//		return store.WithTx(tx).Save(ctx, order)
//	})
//	if postgres.IsUniqueViolation(err, "ux_orders_idem") { … }
//
// PGX-ТИПЫ В API ЗАКОНОМЕРНЫ. Правило «порты без чужих типов» (CONVENTIONS §1)
// охраняет переносимость ядра; этот модуль — сам адаптерный уровень, ради pgx
// он и существует. Прятать pgx.Tx за своим интерфейсом значило бы вводить
// второй словарь поверх первого и терять pgx.Rows, CopyFrom и Batch.
//
// Безопасность:
//
//  1. SANITIZE ОБЯЗАТЕЛЕН НА ГРАНИЦЕ АДАПТЕРА. В pgconn.PgError.Detail лежит
//     «Failing row contains (…)» — вся строка: хэш пароля, тело письма,
//     токен. InTx и InTxRetry применяют Sanitize сами; адаптер, вызывающий
//     pgx напрямую, обязан звать его руками. Классификаторы (IsRetryable,
//     IsContention, IsUniqueViolation) работают и после Sanitize.
//  2. ТАЙМАУТЫ — SET LOCAL ВНУТРИ ТРАНЗАКЦИИ, А НЕ В DSN. В DSN они достались
//     бы и миграциям, которые идут по тому же пулу и законно длинные.
//  3. LOCK_TIMEOUT КОРОТКИЙ. Запрос, ждущий блокировку, держит соединение:
//     десяток таких выбирает весь пул, и падает то, что блокировки не ждало.
//  4. INTXRETRY — ТОЛЬКО ДЛЯ ИДЕМПОТЕНТНЫХ fn. Тело исполняется заново
//     целиком. Повторяются 40001 и 40P01; 57014 (statement_timeout) — нет:
//     бюджет уже съеден, повтор съест ещё один.
//  5. UTC-ПИН ПОБЕЖДАЕТ ОКРУЖЕНИЕ СЕРВЕРА. Параметр стартового пакета выше
//     по приоритету, чем postgresql.conf, ALTER DATABASE и ALTER ROLE: датам
//     всё равно, в каком образе поднят Postgres.
//  6. УНИКАЛЬНОСТЬ — ПО ИМЕНИ CONSTRAINT, НЕ ПО ЛЮБОМУ 23505. В таблице не
//     один UNIQUE, и чужой конфликт не должен превращаться в «повтор по
//     ключу идемпотентности».
//  7. DSN НЕ ПОПАДАЕТ В ОШИБКИ. WithUTC и WithRuntimeParam на неразобранном
//     DSN возвращают ErrDSN без его текста: в нём пароль, а ошибка старта
//     почти всегда оказывается в логе.
//  8. FAIL CLOSED. Nil-пул и негодный Config — паника в New; паника в fn —
//     rollback и паника дальше; отмена ctx — rollback, идущий мимо отмены,
//     чтобы соединение вернулось в пул живым.
//
// Чего нет (решения, не пробелы): создания пула и настроек соединения — их
// держит потребитель; миграций и раннера — схему накатывает goose потребителя;
// savepoint и вложенных транзакций — вложенность прячет реальную границу
// атомарности; транзакции в ctx (ADR-0001 §3) — tx передаётся явным
// аргументом, иначе «в той же транзакции» проверяет не компилятор, а
// внимательность; ORM, построителя запросов и других СУБД.
//
// Postgres для интеграционных тестов — подпакет pgtest.
