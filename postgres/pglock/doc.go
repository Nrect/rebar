// Package pglock — распределённая блокировка периодических прогонов
// сессионным advisory lock Postgres (ADR-0008): прогон выполняет одна реплика,
// остальные его пропускают.
//
// Декоратор, а не порт планировщика: Wrap берёт func(ctx) (int, error) и
// возвращает такую же — это форма scheduler.Job.Run, но импорта планировщика
// нет. Имя — то же, что Job.Name: ряды cron_lock и cron_* сходятся по job.
//
//	lock := pglock.New(pool, observer)
//	jobs := []scheduler.Job{{
//		Name:     "report_daily",
//		Interval: 24 * time.Hour,
//		Run:      lock.Wrap("report_daily", reports.Send),
//	}}
//
// Первая линия — идемпотентность прогона (PATTERNS §12): задача, безопасная
// при любом числе воркеров, в pglock не заворачивается.
//
// Безопасность:
//
//  1. ОДНО СОЕДИНЕНИЕ НА ПРОГОН. Ключ принадлежит сессии: берётся и снимается
//     на соединении, которое прогон держит из пула всё время.
//  2. СОЕДИНЕНИЕ С КЛЮЧОМ В ПУЛ НЕ ВОЗВРАЩАЕТСЯ. pgxpool сессию не сбрасывает:
//     ключ застрял бы в простаивающем соединении, и соседи пропускали бы вечно.
//  3. СНЯТИЕ В DEFER, МИМО ОТМЕНЫ. Прогон, кончившийся паникой или отменой,
//     ключ не держит; паника уходит дальше — её ловит планировщик.
//  4. ТРИ ИСХОДА, И ОНИ РАЗЛИЧИМЫ. Пропуск отдаёт (0, nil), как пустой прогон,
//     и планировщик запишет его успехом; различает их только Observer, поэтому
//     nil-наблюдатель — паника в New.
//  5. БАЗА НЕДОСТУПНА — ОШИБКА, И ПРОГОНА НЕТ (ErrUnavailable): без
//     проверенного ключа работа не идёт, а nil записал бы в успехи прогон,
//     которого не было ни у кого.
//  6. ОТМЕНА ДО ОТВЕТА БАЗЫ — НЕ ИСХОД: остановка процесса не зажигает error,
//     наблюдатель молчит, наружу — ошибка ctx. Истёк бюджет попытки (10 с) при
//     живом ctx — это error.
//  7. КЛЮЧ ПОТЕРЯН ДО СНЯТИЯ — ОШИБКА ПРОГОНА (ErrLockLost) поверх его
//     результата: сессия умерла посреди прогона или пул не сессионный
//     (PgBouncer в режиме transaction), и сосед мог выполнить тот же прогон.
//  8. КЛЮЧ — КОНТРАКТ МЕЖДУ ВЕРСИЯМИ: SHA-256 под золотым тестом. Разные ключи
//     у старой и новой реплики на выкате — двойной прогон.
//  9. ИМЯ ЗАКРЫТО — [a-z0-9_]{1,32}, как у Job.Name: оно уходит меткой метрики;
//     негодное — паника в Wrap.
//  10. ОШИБКА БАЗЫ — ЧЕРЕЗ postgres.Sanitize: Detail наружу не уходит.
//
// Чего в пакете нет (решения, не пробелы; ADR-0008, «Чего НЕТ»): аренды со
// сроком, таблицы блокировок, очереди ожидания, pg_advisory_xact_lock и знания
// планировщика о блокировке; повтора в том же тике — пропуск ждёт следующего;
// слежения за ключом во время прогона — потеря видна при снятии; метрик и
// логов — Observer реализует потребитель.
//
// Метрики (Observer у потребителя; ядро метрик не пишет):
//
//	| Метрика               | Тип     | Что |
//	|-----------------------|---------|-----|
//	| cron_lock{job,result} | counter | исход попытки: acquired / skipped / error; все пары job × AllResults заводятся нулём |
//
// Prometheus-экспортёр припишет счётчику _total. Алерт «ключ застрял» — по
// задаче нет ни одного acquired ни от одной реплики дольше нескольких
// интервалов. Считается по СУММЕ реплик: при застрявшем ключе каждая пишет
// skipped, и «у всех зелено» — это и есть поломка. Он же ловит базу,
// недоступную всем. Для суточной задачи:
//
//	sum by (job) (increase(cron_lock_total{job="report_daily",result="acquired"}[3d])) == 0
