// Package objectstoretest — двойники портов objectstore и контрактный набор
// для любой реализации Store.
//
// Двойники моделируют инвариант, а не запоминают вызовы: та же проверка ключа,
// что у адаптеров, перезапись по ключу, идемпотентное удаление, пагинация с
// курсором. Ошибки двойника (ErrDoubleBroken) отличимы от доменных, чтобы тест
// не принял свою оплошность за проверяемый инвариант.
//
// Пакет собирается БЕЗ ТЕСТОВЫХ ЗАВИСИМОСТЕЙ: его файлы компилирует
// потребитель, и testify здесь означал бы testify в go.mod каждого, кто взял
// двойник. Поэтому RunStoreSuite написан на голом testing (CONVENTIONS §3).
//
// Безопасность: двойник отдаёт копии тел и объектов — правка полученного
// значения не меняет его состояния, как и у адаптера, где значение приходит
// свежим из запроса. Ссылки двойника указывают на домен .invalid: тест,
// который случайно по ним пойдёт, упадёт, а не сходит наружу.
