// Package imgproxy — подписанные ссылки на преобразование картинок.
//
// Сам imgproxy — отдельный контейнер, а не библиотека: пакет только собирает и
// подписывает адрес. Схема подписи — HMAC-SHA256 по salt и пути, base64url без
// набивки, как в эталонной реализации самого imgproxy; вектор из неё пинует
// тест, потому что расхождение здесь не падает, а молча отдаёт 403.
//
// Безопасность:
//
//  1. ПОДПИСЬ ПОКРЫВАЕТ ВЕСЬ ПУТЬ — источник и параметры вместе. Иначе
//     получатель ссылки подставил бы в неё чужой адрес и превратил бы наш
//     imgproxy в открытый прокси, ходящий по внутренней сети.
//  2. КЛЮЧ И СОЛЬ — СЕКРЕТЫ. Не логируются, не попадают в ошибки, в текст
//     паники валидации Config и в саму ссылку: там подпись, а не ключ.
//  3. СОЛЬ ОБЯЗАТЕЛЬНА наравне с ключом: без неё чужой imgproxy с тем же
//     ключом принимал бы наши ссылки.
//  4. У СТОРОН ЕСТЬ ПОТОЛОК (MaxDimension). Размер, пришедший из внешнего мира
//     без потолка, — это заказ на отрисовку картинки в гигапиксель.
//  5. НУЛЕВЫЕ Options — ССЫЛКА НА ИСХОДНИК, а не молчаливый ресайз наугад:
//     забытое поле не имеет права менять картинку.
//  6. ИСТОЧНИК КОДИРУЕТСЯ BASE64URL: его собственные слэши и query иначе
//     разъезжались бы с разбором imgproxy, и подписанной оказалась бы не та
//     ссылка, которую прочитает сервер.
//
// Настройка на стороне imgproxy — не наша, но без неё подпись бесполезна:
// IMGPROXY_KEY и IMGPROXY_SALT обязаны совпадать с Config, а
// IMGPROXY_ALLOWED_SOURCES — ограничивать источники, потому что подпись
// защищает от подмены адреса, а не от нашей собственной ошибки в SourceBase.
//
// Чего в пакете НЕТ: обработки картинок (её делает imgproxy), проверки того,
// что объект существует (ссылка строится локально и в сеть не ходит), полного
// словаря опций imgproxy — здесь ровно то, что нужно каталогу: режим, размеры,
// качество, формат.
