// Package objectstore — файлы пользователей: порт хранилища, загрузчик с
// проверками и сборщик объектов, потерявших владельца.
//
// Потребитель зовёт Uploader.Upload с телом запроса; загрузчик решает
// ЕДИНСТВЕННЫЙ вопрос «можно ли это принять» — размер, тип по содержимому,
// отказ SVG — и кладёт файл под ключом НАШЕЙ постройки. Ключ возвращается
// потребителю, тот сохраняет его у себя строкой. Collector сверяет содержимое
// хранилища со списком владельцев (порт Owned) и убирает то, что не
// принадлежит никому; его Run(ctx) (int, error) — это scheduler.Job.Run, и
// планировщик с пакетом друг друга не импортируют.
//
// Ядро — stdlib + github.com/google/uuid; адаптеры (s3, fs, imgproxy) —
// подпакеты, и внешних библиотек нет ни у одного. Проект и причины —
// docs/adr/0006-objectstore.md.
//
// Безопасность:
//
//  1. ПОТОЛОК РАЗМЕРА ДЕЙСТВУЕТ ДО ЧТЕНИЯ, А НЕ ПОСЛЕ. Заявленный размер
//     отсекает лишнее, не тронув тело; остальное читается через
//     io.LimitReader(body, MaxSize+1), и превышение узнаётся по лишнему байту.
//     Проверка после чтения — это проверка после того, как память уже занята.
//  2. ТИП ОПРЕДЕЛЯЕТСЯ ПО СОДЕРЖИМОМУ (http.DetectContentType по первым 512
//     байтам). Заголовок Content-Type пишет клиент, и доверять ему значит
//     принимать имя за суть; в UploadRequest он есть, но ни на что не влияет.
//  3. SVG ОТВЕРГАЕТСЯ ВСЕГДА. Это документ со скриптами, а не картинка: отдав
//     его со своего домена, мы отдаём чужой JS в своей origin. Исключений нет,
//     поэтому это не поле конфигурации: image/svg+xml не входит в
//     AllContentTypes, а UploaderConfig паникует на типе вне набора.
//  4. КЛЮЧ СТРОИМ МЫ: <Prefix>/<uuid>.<ext>, расширение — из белого списка по
//     ОПРЕДЕЛЁННОМУ типу. Ключ от клиента — это ключ, который клиент и выберет.
//  5. ИМЯ ФАЙЛА ПОЛЬЗОВАТЕЛЯ — ДАННЫЕ, А НЕ ПУТЬ. В ключ оно не попадает
//     никогда: там бывают ../, символы, ломающие подпись, и персональные
//     данные. Нужно показывать исходное имя — потребитель хранит его в своей
//     колонке.
//  6. СБОРЩИК НЕ ТРОГАЕТ МОЛОДЫЕ ОБЪЕКТЫ (CollectorConfig.MinAge). Между Put и
//     вставкой строки потребителя есть окно, и без grace сборщик удалял бы
//     файлы, которые прямо сейчас загружают.
//  7. СБОЙ IsOwned ОСТАНАВЛИВАЕТ ПРОГОН, а не «считаем сиротой»: недоступный
//     источник владения признал бы сиротами всех, то есть одна недоступная
//     база вычистила бы бакет.
//  8. РЕЖИМ СБОРЩИКА НАЗЫВАЕТСЯ ЯВНО (CollectMode), и нулевое значение — отказ
//     на старте. Будь это булев DryRun, нулевым значением было бы «удалять», и
//     забытое поле снимало бы предохранитель молча.
//  9. КЛЮЧ ОБЪЕКТА И ИМЯ ФАЙЛА НЕ ЛОГИРУЮТСЯ И НЕ ПОПАДАЮТ В ОШИБКИ. Ключ
//     бывает выведен из персональных данных, а лог переживает инцидент дольше
//     всех: адаптеры отдают класс ошибки, а не текст провайдера или *fs.PathError.
//  10. FAIL CLOSED. Nil-порт и негодный Config — паника на старте; ключ,
//     выходящий за корень (в том числе через символическую ссылку), — ошибка,
//     а не файл; флага, выключающего инвариант, нет — режим разработки
//     достигается подменой порта (fs вместо s3).
//
// Наблюдаемость: Collector.Run отдаёт число убранных объектов и ошибку —
// планировщик потребителя пишет по ним свои метрики. Своего otel-декоратора у
// пакета пока нет (см. «Чего нет»).
//
// Чего в пакете НЕТ — решения, а не пробелы:
//
//   - РЕСАЙЗА И ОБРАБОТКИ КАРТИНОК В ПРОЦЕССЕ: govips и bimg тянут
//     C-библиотеку и делают из веб-процесса обработчик изображений.
//     Преобразование — работа imgproxy как отдельного контейнера, мы лишь
//     подписываем ссылку (подпакет imgproxy).
//   - MULTIPART-ЗАГРУЗКИ: она нужна файлам от сотен мегабайт, а у каталога их
//     нет. Появится потребность — появится метод, ломать порт не придётся.
//     Отсюда же и потолок памяти: Uploader держит принимаемое тело целиком, и
//     пик при N параллельных загрузках равен N·MaxSize.
//   - ПУБЛИЧНЫХ БАКЕТОВ ПО УМОЛЧАНИЮ и PutBucketPolicy: права бакета — работа
//     инфраструктуры, а пакет, умеющий открыть бакет миру, однажды его откроет.
//     PublicURL строит адрес, но ничего не открывает.
//   - СВОЕГО КЭША И CDN: то и другое живёт перед приложением.
//   - ВИРУСНОГО СКАНИРОВАНИЯ: это отдельный сервис и отдельное решение.
//   - УДАЛЕНИЯ ПО РАСПИСАНИЮ БЕЗ ВЛАДЕЛЬЦА: без порта Owned сборщик — это
//     rm -rf с таймером, поэтому NewCollector паникует на nil.
//   - ДЕКОРАТОРА objectstoreotel: наблюдаемость пакета — отдельная работа, и
//     до неё метрики пишет потребитель по возврату Run.
//   - ХРАНЕНИЯ ИСХОДНОГО ИМЕНИ ФАЙЛА: это данные потребителя, и живут они в
//     его колонке рядом с ключом (см. пункт 5).
