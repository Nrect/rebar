// Package s3 — objectstore.Store поверх S3-совместимого хранилища на stdlib.
//
// Подпись SigV4 считается своими руками: приём тот же, что в mail/sesv2, и это
// осознанная копия — ADR-0005 разрешает внутри rebar зависимости только на
// kit, postgres и postgres/pgtest, а тянуть модуль почты ради подписи нельзя.
// Отличия от копии — подпись query-строки (её требуют List и Presign) и
// кодирование пути: у SES путь всегда «/», здесь в нём лежит ключ объекта.
// Правило «копируемые мелочи не выносятся до третьего потребителя» делает
// копию законной; долг записан в ADR-0006.
//
// Проверено на официальном AWS SigV4 test suite и на живом MinIO
// (интеграционный тест, пропускается по -short).
//
// Безопасность:
//
//  1. ADDRESSING ВСЕГДА PATH-STYLE: <endpoint>/<bucket>/<key>. Так работают
//     Yandex Object Storage, VK Cloud и MinIO; virtual-host требует своего
//     DNS-имени на бакет, а поле выбора однажды выставят неверно.
//  2. СЕКРЕТ ЖИВЁТ ТОЛЬКО КЛЮЧОМ HMAC. Ни в лог, ни в ошибку, ни в текст
//     паники валидации Config он не попадает; в подписанной ссылке его тоже
//     нет — там подпись, а не ключ.
//  3. ИЗ ОШИБКИ ПРОВАЙДЕРА БЕРЁТСЯ ТОЛЬКО Code. Message и Key провайдер
//     заполняет содержательно («The specified key does not exist», ключ
//     целиком), и в лог это уносило бы ключ объекта.
//  4. СБОЙ ДО ОТВЕТА НЕ ЗАВОРАЧИВАЕТСЯ: в *url.Error лежит адрес запроса
//     вместе с ключом, поэтому наружу уходит класс ошибки.
//  5. ПОДПИСЬ СЧИТАЕТСЯ ДО ОТПРАВКИ, по телу, а не по обещанию: PutRequest.Size
//     обязан быть известен и совпадать с телом, иначе ErrSizeUnknown. «Читать
//     сколько дадут» у чужого источника — это отказ по памяти.
//  6. КЛЮЧ ПРОВЕРЯЕТСЯ ДО СЕТИ (objectstore.CheckKey): запрос с ключом,
//     выходящим за префикс, к провайдеру не уходит вовсе.
//  7. У ПОДПИСАННОЙ ССЫЛКИ ЕСТЬ ПОТОЛОК ЖИЗНИ — семь суток, предел SigV4;
//     непозитивный и слишком долгий ttl — ErrBadTTL, а не «ссылка навсегда».
//
// Чего в адаптере НЕТ: multipart-загрузки (нужна файлам от сотен мегабайт),
// PutBucketPolicy и создания бакетов (права бакета — работа инфраструктуры),
// разбора вебхуков и подписи заголовком для чужих сервисов — signer знает
// ровно то, что нужно этому адаптеру. Причины — ADR-0006, «Чего нет».
