// Разбор мутационного прогона (gremlins) по ядру.
//
// Выживший мутант — строка, покрытая тестами, но ими НЕ ПРОВЕРЯЕМАЯ: подмена
// `>` на `>=` или отрицание условия не роняет ни одного теста. Покрытие о таком
// молчит: оно считает, что строка выполнилась, а не что от неё чего-то ждали.
//
// Итог: убито 54, выжил 1, «не покрыто» 2, просрочек 0; эффективность 98.18%,
// mutator coverage 96.49%. Первый прогон: 49 убито, 4 выжило, 4 «не покрыто»,
// эффективность 92.45%. Два прогона подряд дали одинаковый список LIVED —
// значит, разбирать есть что, а не шум мигающего теста.
//
// ТРИ ИЗ ЧЕТЫРЁХ ПЕРВЫХ ВЫЖИВШИХ ОКАЗАЛИСЬ НАСТОЯЩИМИ ДЫРАМИ, и все три — на
// границах, которые тесты обходили с одной стороны:
//
//   - keys.go, граница управляющих символов (`r < 0x20`). Мутант `r <= 0x20`
//     запрещал ключ с ПРОБЕЛОМ — законный ключ, который S3 кодирует как %20.
//     Ни один тест не подавал такого ключа. Убит:
//     TestCheckKey_AcceptsOrdinaryKeys, строка с пробелом.
//   - uploader.go, потолок по ЗАЯВЛЕННОМУ размеру (`req.Size > MaxSize`).
//     Мутант `>=` отвергал заявку ровно в потолок: честный клиент не мог бы
//     загрузить файл предельного размера. Тест на точную границу шёл с
//     Size == -1 и этой ветки не касался. Убит:
//     TestUploader_ExactlyAtDeclaredLimitIsAccepted.
//   - uploader.go, окно снятия типа (`len(head) > SniffLen`), отрицание.
//     Мутант искал "<svg" по ВСЕМУ телу, а не по первым 512 байтам, и потому
//     был строже нашего кода — ни один тест не замечал разницы. Строже здесь
//     значит «отвергать настоящий PNG, у которого байты "<svg" случайно попали
//     в сжатые данные», а в достаточно большом файле они попадают. Убит:
//     TestUploader_AcceptsImageWhoseBodyMentionsSVGBeyondTheSniffWindow.
//
// ЕДИНСТВЕННЫЙ ОСТАВШИЙСЯ ВЫЖИВШИЙ — uploader.go:61, `len(head) > SniffLen`,
// сдвиг границы (`>=`). Он ЭКВИВАЛЕНТЕН: при длине ровно SniffLen обе ветки
// дают одно и то же значение — head[:SniffLen] это и есть head. Убить его
// можно было бы только утверждением, отличающим срез от самого себя, то есть
// проверкой ради проверки. Что граница именно здесь и что за окном ничего не
// смотрят, сторожат тест выше и TestSniffWindow_EndsAtSniffLen ниже.
//
// «НЕ ПОКРЫТО» — config.go:10, константа MaxPresignTTL (`7 * 24 * time.Hour`).
// Это объявление константы: исполняемой строки под ним нет, профиль покрытия
// её не описывает, и gremlins не запускает мутанта вовсе. Артефакт снятия
// покрытия, а не дыра в тестах; значение константы сторожат тесты Presign у
// двойника и обоих адаптеров (ErrBadTTL за семью сутками).
//
// Повторить:
//
//	GOWORK=off gremlins unleash --timeout-coefficient 20 --workers 4 \
//	    -E '^objectstoretest/' -E '^s3/' -E '^fs/' -E '^imgproxy/'
//
// (GOWORK=off обязателен, пока модуль не внесён в go.work; коэффициент
// таймаута 20 — на меньшем прогон врёт зелёным. Прогон повторяется, когда
// тронуто ядро ИЛИ двойник, через который ядро тестируется.)

// Окно снятия типа кончается ровно на SniffLen: дальше не смотрит ни
// определение типа, ни отказ SVG. Это тот самый инвариант, вокруг которого
// живёт эквивалентный мутант.
func TestSniffWindow_EndsAtSniffLen(t *testing.T) {
	t.Parallel()

	// http.DetectContentType по построению читает не больше SniffLen байт:
	// хвост на его решение не влияет.
	head := bytes.Repeat([]byte{'A'}, SniffLen)
	assert.Equal(t, http.DetectContentType(head), http.DetectContentType(append(head, "<svg"...)))

	// looksLikeSVG смотрит ровно то, что ему дали: маркер внутри окна ловится,
	// за окном — нет, потому что за окно ему ничего не передают.
	inside := append(bytes.Repeat([]byte{'A'}, SniffLen-8), "<SVG"...)
	assert.True(t, looksLikeSVG(inside), "маркер внутри окна обязан ловиться в любом регистре")
	assert.False(t, looksLikeSVG(head), "в окне без маркера SVG не мерещится")
}
