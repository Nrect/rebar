// Package fs — objectstore.Store поверх каталога на диске.
//
// АДАПТЕР РАЗРАБОТКИ, А НЕ ПРОДА. Он существует, чтобы стенд поднимался без
// контейнера хранилища: подмена порта — законный способ получить режим
// разработки, в отличие от флага в конфиге (CONVENTIONS §2). В прод берут s3.
//
// Безопасность:
//
//  1. ОБХОД КАТАЛОГА ОТВЕРГАЕТСЯ, А НЕ ЧИНИТСЯ. Ключ, вышедший за корень после
//     filepath.Clean, — ошибка, а не файл: «почистим и запишем» означает
//     запись туда, куда просили не мы.
//  2. СИМВОЛИЧЕСКАЯ ССЫЛКА ИЗ КОРНЯ ТОЖЕ ЗАКРЫТА. filepath.Clean чистит путь
//     лексически и ссылки не видит: каталог внутри корня, ведущий наружу,
//     пропустил бы запись мимо проверки. Разрешается ближайший существующий
//     предок, и результат сверяется с корнем ещё раз.
//  3. В ОШИБКЕ НЕТ ПУТИ, ТО ЕСТЬ НЕТ КЛЮЧА. *fs.PathError печатает путь
//     целиком, а ключ бывает выведен из персональных данных потребителя;
//     наружу уходят класс ошибки и операция.
//  4. ЗАПИСЬ ИДЁТ ВО ВРЕМЕННЫЙ ФАЙЛ И ПЕРЕИМЕНОВЫВАЕТСЯ: оборванная запись не
//     оставляет полуфайла под ключом, который потребитель уже сохранил.
//  5. PRESIGN НЕ ПОДПИСЫВАЕТ, И ЭТО НАЗВАННОЕ РЕШЕНИЕ. Ключа для подписи у
//     адаптера нет, поэтому ссылка защищает ровно настолько, насколько
//     защищает знание ключа. Проверки метода и срока при этом те же, что у s3,
//     чтобы код потребителя не расходился между стендом и продом.
//
// Чего в адаптере НЕТ: раздачи файлов по HTTP (сервер поднимает потребитель),
// квот на размер каталога, блокировок между процессами. Это адаптер стенда, и
// каждая такая добавка приближала бы его к тому, чем он быть не должен, — к
// хранилищу для прода.
