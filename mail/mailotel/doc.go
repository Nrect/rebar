// Package mailotel — наблюдаемость почты на OpenTelemetry metric API:
// декоратор mail.Transport со счётчиком emails_sent{type,result} и Gauges —
// три observable gauge очереди, читающие снимок mail.Stats.
//
// Ядро метрик не пишет и otel не импортирует (CONVENTIONS §6); зависимость
// живёт здесь. Собирается так:
//
//	tr, err := mailotel.Wrap(sesTransport, meter)
//	g, err := mailotel.NewGauges(meter)
//	svc := mail.NewService(store, tr, nil, cfg)
//	// после каждого прогона Deliver:
//	g.Set(stats)
//
// Имена и единицы инструментов — часть контракта: на них стоят алерты
// потребителя (ADR-0001, «Наблюдаемость и алерты»).
//
// Безопасность:
//
//  1. МЕТКИ — ЗАКРЫТЫЕ НАБОРЫ: type — mail.Kind (набор задаёт Config.Kinds),
//     result — ok/rejected/error. Адрес, код провайдера, текст ошибки, имя
//     транспорта в метку не попадают.
//  2. ДЕКОРАТОР НЕ ЧИТАЕТ ТЕЛО И НИЧЕГО НЕ ЛОГИРУЕТ: из конверта берётся
//     только Kind, ошибка next уходит вызывающему и никуда больше.
//  3. NAME() ПРОБРАСЫВАЕТСЯ БЕЗ ИЗМЕНЕНИЙ: Deliver узнаёт Unconfigured по
//     имени (ADR-0001, «Доставка», шаг 0), подмена ослепила бы проверку.
//  4. ГЕЙДЖИ ЧИТАЮТ СНИМОК, А НЕ ХОДЯТ В БД НА КАЖДЫЙ SCRAPE (CONVENTIONS §6):
//     расписание у потребителя, коллбэк отдаёт последний Set.
//  5. rejected И error РАЗДЕЛЕНЫ: сведи их — и алерт «провайдер недоступен»
//     будет гореть от фонового шума временных сбоев.
//
// Чего нет (решения, не пробелы): трейсов — Send уже под span'ом воркера;
// гистограммы латентности — долгую отправку режет SendTimeout ядра, а не
// алерт; автообновления снимка — Gauges в Store не ходит, Set зовёт
// потребитель после Deliver; счётчиков очереди (enqueued, expired,
// suppressed) — их состояние видно гейджами и аудитом потребителя.
