// Package mail — транзакционная почта: outbox в хранилище потребителя,
// фоновая доставка с ретраями, транспорт за портом, стоп-лист.
//
// Потребитель зовёт Service.Enqueue с готовым письмом и ключом
// идемпотентности; письмо ложится строкой в outbox, ответ клиенту не ждёт
// провайдера. Фоновый Service.Deliver забирает пачку, шлёт через Transport,
// помечает исход и назначает повтор. Строка в outbox есть ⇒ письмо либо
// уйдёт, либо станет видимым отказом (failed + метрика), но не потеряется.
// Вставка в транзакцию бизнес-факта — через чистый Service.Prepare и адаптер
// потребителя (mailpg.Store.WithTx).
//
// Ядро — stdlib + github.com/google/uuid; адаптеры (mailpg, smtp, sesv2,
// mailotel) — подпакеты с одной библиотекой каждый. Проект и причины —
// docs/adr/0001-mail.md.
//
// Безопасность:
//
//  1. ОДИН ПОЛУЧАТЕЛЬ НА ПИСЬМО. Outbox со списками адресатов — релей.
//  2. ЗАГОЛОВКИ ПО БЕЛОМУ СПИСКУ, БЕЗ CR/LF. From задаёт Config, не письмо;
//     проверка одна, в Prepare, до записи в хранилище.
//  3. ТЕЛО ПИСЬМА — СЕКРЕТ (ссылка с токеном). Не логируется, стирается в
//     терминальном статусе, строки удаляются после Retention.
//  4. ИДЕМПОТЕНТНОСТЬ ГРОМКАЯ. Тот же ключ и то же письмо — повтор как успех;
//     тот же ключ и другое письмо — ErrKeyReused, не тихий no-op.
//  5. ДОСТАВКА AT-LEAST-ONCE. Падение между Send и Finish даёт второе письмо
//     после истечения аренды. Окно сужают Lease > SendTimeout,
//     детерминированный Message-ID и политика Config.Uncertain.
//  6. FAIL CLOSED. Nil-порт и негодный Config — паника на старте; неизвестный
//     Kind — отказ; NotAfter наступил — expired; стоп-лист недоступен — не
//     слать и повторить; постоянный отказ провайдера — failed без ретраев.
//  7. ТРАНСПОРТ НЕ ЗНАЕТ ОЧЕРЕДИ: у Send нет доступа к Store, исход помечает
//     только Deliver.
//  8. ФЛАГА «СЛАТЬ СИНХРОННО» НЕТ. Режим разработки — подмена Transport.
//  9. АДРЕС НОРМАЛИЗУЕТСЯ ОДИН РАЗ (NormalizeAddress): стоп-лист не
//     обходится сменой регистра.
//
// Чего в пакете нет (решения, не пробелы): шаблонов, массовых рассылок и
// List-Unsubscribe, вложений, входящей почты, разбора вебхуков провайдера,
// распределённой блокировки, приоритетов, DKIM (подписывает провайдер или
// адаптер smtp). Причины — ADR-0001, раздел «Чего нет».
//
// Состояние: типы, порты, Config и Prepare реализованы; Enqueue, Deliver,
// адаптеры и двойники — после обсуждения ADR-0001.
