// Package mail — транзакционная почта: outbox в хранилище потребителя, фоновая
// доставка с ретраями, транспорт за портом, стоп-лист.
//
// Форма скопирована с payment ЛайфУрока — первого переносимого пакета, из
// которого вырос этот тулкит: порты объявлены пакетом и реализуются
// адаптерами, Config с panic-валидацией в конструкторе, SetClock, закрытые
// enum-типы, ноль импортов из проекта-потребителя. Внешняя зависимость у ядра
// одна — github.com/google/uuid; адаптеры (mailpg, smtp, sesv2, mailotel) —
// подпакеты, каждый с ровно одной библиотекой, ради которой существует.
// Инвариант держит TestPackageImportsAreWhitelisted.
//
// # Что делает
//
// Потребитель зовёт Service.Enqueue с готовым письмом (тема, текст, HTML —
// отрендерены им самим) и ключом идемпотентности. Письмо ложится строкой в
// outbox; ответ клиенту не ждёт провайдера. Фоновый прогон Service.Deliver
// (задача планировщика потребителя) забирает пачку, шлёт через Transport,
// помечает исход и назначает повтор с экспоненциальным backoff. Гарантия
// пакета: строка в outbox есть ⇒ письмо либо уйдёт, либо станет видимым
// отказом (статус failed с причиной и метрика), — никогда не потеряется молча.
//
// Гарантию «операция состоялась ⇒ письмо уйдёт» пакет даёт только вместе с
// потребителем: строка outbox обязана вставляться В ТОЙ ЖЕ транзакции, что и
// бизнес-факт (создание пользователя, выдача токена). Для этого есть чистый
// Service.Prepare: он валидирует, нормализует и считает отпечаток, а вставку
// в свою транзакцию делает адаптер потребителя (mailpg.Store.WithTx).
//
// Безопасность:
//
//  1. ОДИН ПОЛУЧАТЕЛЬ НА ПИСЬМО. Ни Cc, ни Bcc, ни списка To. Транзакционному
//     письму второй адресат не нужен, а outbox, принимающий списки,
//     превращается в релей: одна дыра в вызывающем коде — и очередь рассылает
//     чужие письма с нашего домена и нашей репутацией.
//
//  2. ЗАГОЛОВКИ — БЕЛЫЙ СПИСОК, ЗНАЧЕНИЯ БЕЗ CR/LF. From задаётся Config, а не
//     письмом. Адрес, тема и каждое значение заголовка проверяются на перевод
//     строки: инъекция заголовка через тему — это Bcc, дописанный
//     пользователем. Проверка одна и в одном месте (Prepare), до записи в
//     хранилище: адаптеры и транспорты получают уже чистый Envelope.
//
//  3. ТЕЛО ПИСЬМА — СЕКРЕТ. В нём ссылка с токеном подтверждения или сброса
//     пароля. Тело и тема не попадают ни в лог, ни в текст ошибки, ни в
//     аудит; в терминальном статусе (sent, failed, expired, suppressed)
//     хранилище обязано стереть тело, оставив метаданные; строки старше
//     Config.Retention удаляются целиком. Дамп таблицы outbox не должен быть
//     дампом действующих ссылок сброса пароля.
//
//  4. ИДЕМПОТЕНТНОСТЬ ГРОМКАЯ. Ключ нормализуется в одной точке (NormalizeKey).
//     Тот же ключ и тот же отпечаток письма — прежняя строка как УСПЕХ
//     (OutcomeDuplicate); тот же ключ и другое письмо — ErrKeyReused. Тихий
//     no-op скрыл бы, что второе, реально другое письмо не встало в очередь.
//     Ключ глобален, а не в пределах пользователя: у письма пользователь есть
//     не всегда (уведомление на занятый адрес шлётся тому, кого мы не знаем).
//
//  5. ДОСТАВКА AT-LEAST-ONCE, И ЭТО СКАЗАНО ВСЛУХ. Между Transport.Send и
//     Store.Finish процесс может упасть; строка останется в sending с
//     истёкшей арендой, и следующий прогон отправит письмо второй раз. Окно
//     сужается тремя способами: аренда (Config.Lease) строго длиннее таймаута
//     отправки, чтобы два воркера не слали одну строку одновременно;
//     детерминированный Message-ID из id строки, по которому почтовые клиенты
//     схлопывают дубль в SMTP-пути (SES-совместимые API свой Message-ID
//     перезаписывают — там это не помогает, и это сказано в sesv2); политика
//     Config.Uncertain — повторить (умолчание: для ссылок подтверждения дубль
//     безвреден, а потеря — обращение в поддержку) или отложить в failed с
//     причиной uncertain на ручной разбор (для чеков и счетов, где дубль —
//     претензия).
//
//  6. FAIL CLOSED. Nil-порт и негодный Config — паника на старте. Неизвестный
//     Kind — ErrBadKind: набор типов закрыт, потому что Kind — метка метрики.
//     Наступивший NotAfter — статус expired, письмо не уходит: протухшая
//     ссылка сброса, доставленная через час после истечения, учит человека
//     не доверять письмам от нас. Ошибка стоп-листа — письмо НЕ отправлено и
//     будет повторено (ErrUnavailable), а не «отправим, раз не смогли
//     проверить». Постоянный отказ провайдера (RejectedError) — failed без
//     повторов: ретрай на MessageRejected — это поведение спамера, и
//     провайдер считает его именно так.
//
//  7. ТРАНСПОРТ НЕ ЗНАЕТ ОЧЕРЕДИ. Transport.Send получает собранный Envelope и
//     не имеет доступа к Store: адаптер провайдера не может «оптимистично»
//     пометить письмо отправленным. Исход помечает только Deliver, только
//     после ответа транспорта.
//
//  8. ФЛАГА «СЛАТЬ СИНХРОННО» И «БЕЗ ОЧЕРЕДИ» НЕТ. Режим разработки — это
//     подмена Transport (mailtest.Transport, лог-транспорт), а не флаг,
//     обходящий outbox. Флаг обязательно окажется включённым на проде на одну
//     ночь, и в ту ночь регистрация снова упадёт вместе с провайдером.
//
//  9. АДРЕС НОРМАЛИЗУЕТСЯ ОДИН РАЗ (NormalizeAddress): обрезка, нижний регистр,
//     синтаксис по RFC 5322 без display-name. Стоп-лист и дедуп сравнивают
//     нормализованные строки; " User@Mail.ru" и "user@mail.ru" — один адрес,
//     иначе стоп-лист обходится пробелом.
//
// # Чего в пакете НЕТ
//
// Список для двух читателей: того, кто ищет здесь функцию, и того, кто
// переносит пакет в другой проект. Каждый пункт — решение с причиной.
//
//  1. ШАБЛОНОВ НЕТ. Пакет принимает готовые Subject/Text/HTML. Тексты — это
//     продукт (язык, бренд, тон), а движок шаблонов у каждого проекта свой.
//     Единственное, чего стоит требовать от рендера потребителя, —
//     missingkey=error: письмо с пустой ссылкой хуже неотправленного.
//
//  2. МАССОВЫХ РАССЫЛОК НЕТ. Один получатель, никакого управления списками,
//     никакой машинерии List-Unsubscribe. Транзакционные письма освобождены от
//     требования one-click unsubscribe у Gmail/Yahoo, а Mail.ru прямо просит
//     слать транзакционное и промо с разных адресов. Потребителю, которому
//     нужен List-Unsubscribe на уведомлении, достаточно заголовка — он в
//     белом списке.
//
//  3. ВЛОЖЕНИЙ НЕТ. Понадобятся для чеков (PDF) — добавятся полем Envelope и
//     колонкой адаптера, не ломая существующего: транспорты SMTP и SES
//     умеют вложения, порт — нет, пока нет потребителя.
//
//  4. ВХОДЯЩЕЙ ПОЧТЫ НЕТ. Ни разбора ответов, ни обработки писем на
//     Reply-To.
//
//  5. РАЗБОРА ВЕБХУКОВ ПРОВАЙДЕРА В ЯДРЕ НЕТ. Есть порт Suppressor и метод
//     Service.Suppress; перевод чужого JSON в Suppression — адаптер
//     конкретного провайдера, потому что у Postbox вебхуков нет вовсе
//     (события в Cloud Logging и собственный стоп-лист на стороне
//     провайдера), а у Unisender Go — есть.
//
//  6. РАСПРЕДЕЛЁННОЙ БЛОКИРОВКИ НЕТ. Claim берёт строки с SKIP LOCKED и
//     арендой; два инстанса делят очередь без координации, и безопасность
//     этого — свойство самой строки (аренда), а не планировщика.
//
//  7. ПРИОРИТЕТОВ НЕТ. Одна очередь, порядок по next_attempt_at. У писем
//     аутентификации один приоритет, и вторая очередь появится вместе с
//     первым письмом, которому можно подождать.
//
//  8. DKIM В ЯДРЕ НЕТ. Подпись — забота транспорта: провайдеры с собственной
//     DKIM (Postbox, Unisender Go) подписывают сами по DNS-записям домена;
//     адаптер smtp умеет подписать своим ключом там, где провайдер не
//     подписывает.
//
// # Состояние
//
// Реализованы типы, порты, Config и чистый Prepare — то, что фиксирует
// контракт. Enqueue, Deliver, Purge, адаптеры и двойники добавляются после
// обсуждения ADR-0001 с владельцем.
