// Команда sesfake — SES v2-совместимый фейк провайдера для dev/stage: принимает
// POST /v2/email/outbound-emails (тот же API у Yandex Cloud Postbox и AWS SES),
// хранит принятое и релеит письма в почтовый ящик стенда по SMTP. Цепочка
// стенда: backend → sesv2 → sesfake → SMTP → Mailpit; боевой HTTP-транспорт
// запускается на каждом деплое, а UI остаётся тем же (ADR-0001, «Двойники»).
//
// Безопасность: это стенд, не прод.
//
//  1. БЕЗ -secret ПОДПИСЬ НЕ ПРОВЕРЯЕТСЯ. Сверяется только форма SigV4
//     (заголовок, подписанные заголовки, регион и сервис) — как у
//     aws-ses-v2-local. Полная проверка включается заданным -secret.
//  2. РЕЛЕЙ БЕЗ TLS И БЕЗ AUTH. -relay ходит в SMTP открытым текстом: адрес
//     обязан быть внутри docker-сети стенда.
//  3. /store ОТДАЁТ ТЕЛА ПИСЕМ БЕЗ АУТЕНТИФИКАЦИИ. Порт наружу не выставлять:
//     там ссылки подтверждения и сброса пароля.
//  4. ХРАНЕНИЕ В ПАМЯТИ С ЛИМИТОМ -store-limit (по умолчанию 1000 последних);
//     рестарт стирает всё. Лог релея — только id письма и ошибка: ни адреса,
//     ни темы, ни тела в логах нет.
//
// Флаги дублируются переменными окружения SESFAKE_LISTEN, SESFAKE_SECRET,
// SESFAKE_REGION, SESFAKE_RELAY, SESFAKE_REJECT, SESFAKE_STORE_LIMIT — они
// задают значения по умолчанию, флаг командной строки сильнее.
//
// Сборка из каталога mail:
//
//	go build ./cmd/sesfake
//	docker build -f cmd/sesfake/Dockerfile .
