// Package mailpg — mail.Store на github.com/jackc/pgx/v5: outbox письмами в
// таблице email_outbox базы потребителя.
//
// Схема — миграции goose в каталоге migrations/, их отдаёт Migrations();
// накатывает раннер потребителя со своей таблицей версий mail_schema_version
// (ADR-0011). CheckSchema на старте сверяет схему, но не применяет её. Store
// работает и в пуле, и в транзакции вызывающего: New(pool) для фоновой
// доставки, WithTx(tx) — для вставки письма вместе с бизнес-фактом. Проект и
// причины — docs/adr/0001-mail.md.
//
//	store := mailpg.New(pool)
//	if err := store.CheckSchema(ctx); err != nil { … }  // миграции не накатаны?
//	env, err := svc.Prepare(msg)                        // чистая валидация
//	res, err := store.WithTx(tx).Enqueue(ctx, env)      // та же транзакция
//
// Безопасность:
//
//  1. ТЕЛО ПИСЬМА НЕ ПОПАДАЕТ В ОШИБКИ. У pgconn.PgError в Detail лежит
//     «Failing row contains (…)» — вся строка с телом и ссылкой с токеном;
//     границу держит общий postgres.Sanitize, от ошибки остаются SQLSTATE,
//     Message и имя ограничения (errors.go). Своя копия этой границы была бы
//     лишним шансом разойтись там, где расхождение стоит утечки (ADR-0005).
//     Логов в адаптере нет вовсе.
//  2. WithTx — ОДНА ТРАНЗАКЦИЯ С ФАКТОМ ПОТРЕБИТЕЛЯ. Компилятор этого не
//     проверяет, поэтому контракт держит тест TestStore_WithTx_IsAtomic:
//     после ROLLBACK нет ни строки outbox, ни факта.
//  3. ТЕЛО СТИРАЕТ БАЗА, А НЕ ТОЛЬКО КОД. CHECK email_outbox_body_cleared_chk
//     не примет терминальную строку с тем письмом: правку в обход адаптера
//     отвергнет Postgres.
//  4. FOR UPDATE SKIP LOCKED — ДВА ВОРКЕРА НЕ БЕРУТ ОДНУ СТРОКУ, письмо не
//     уходит дважды из-за параллельного Claim; доказано тестом гонки
//     TestStore_Claim_TwoWorkersRace.
//  5. FAIL CLOSED. Nil-пул и nil-транзакция — паника на старте; ноль
//     обновлённых строк в Finish — не успех, а mail.ErrUnavailable, как и
//     любой сбой Postgres.
//  6. ПОВТОР ПО КЛЮЧУ НЕ РОНЯЕТ ТРАНЗАКЦИЮ. Enqueue разбирает конфликт через
//     ON CONFLICT (dedup_key) DO NOTHING: перехват 23505 перевёл бы
//     транзакцию потребителя в aborted (enqueue.go).
//
// Чего нет (решения, не пробелы): раннера миграций — Migrations() накатывает
// раннер потребителя, CheckSchema только сверяет (две правды о схеме, DDL-права
// у приложения и гонка реплик — не наше); таблицы email_suppressions — стоп-лист второго этапа
// (ADR-0001, «Стоп-лист»); своего пула, настроек соединения и повторов —
// пул даёт потребитель, повторы назначает ядро.
