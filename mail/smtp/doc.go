// Package smtp — адаптер mail.Transport на github.com/wneessen/go-mail: одно
// письмо — одно соединение, STARTTLS по умолчанию обязателен, постоянный отказ
// сервера отличается от временного по коду SMTP. Перенос internal/common/mail
// из ЛайфУрока; изменения и причины — docs/adr/0001-mail.md, «Транспорты».
//
// Безопасность:
//
//  1. TLS ОБЯЗАТЕЛЕН ПО УМОЛЧАНИЮ. Пустой Config.TLS — mandatory; TLSNone
//     принимается только с AllowPlaintext. Ручки InsecureSkipVerify нет.
//  2. ПАРОЛЬ НЕ УХОДИТ В ОТКРЫТУЮ БЕЗ AllowPlaintext. LOGIN/PLAIN по
//     незашифрованному соединению — ошибка (исключение go-mail: localhost).
//  3. НИ ТЕЛА, НИ ТЕМЫ, НИ АДРЕСА В ОШИБКАХ. Текст go-mail содержит адрес и
//     ответ сервера; ошибка собирается заново из стадии и кодов. Логов нет.
//  4. 5xx НЕ ПОВТОРЯЕТСЯ — *mail.RejectedError. 4xx, сеть, TLS, таймаут и
//     ошибка без кода — временный сбой, ядро повторит.
//  5. DATA ПРИНЯТ — ПИСЬМО ОТПРАВЛЕНО. Ошибка RSET/QUIT после 250 на DATA —
//     успех, иначе Deliver отправил бы письмо второй раз.
//  6. CTX ПРИОРИТЕТНЕЕ TIMEOUT. go-mail после dial следит только за дедлайном
//     сокета; Send возвращается по ctx, чтобы попытка не пережила аренду.
//  7. MESSAGE-ID — ИЗ КОНВЕРТА, не случайный от go-mail: повтор той же строки
//     почтовый клиент схлопнет.
//
// Чего нет: постоянного соединения и пула (письмо — dial…QUIT), ретраев (дело
// Deliver), DKIM (подписывает провайдер), вложений (порт их не несёт), разбора
// ответа сервера помимо queue id в формах «queued as <id>» и «id=<id>».
