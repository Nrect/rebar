// Package auditotel — наблюдаемость журнала действий на OpenTelemetry metric
// API: декоратор audit.Sink со счётчиком audit_events{action,outcome}.
//
// Ядро метрик не пишет и otel не импортирует (CONVENTIONS §6); зависимость
// живёт здесь. Собирается так:
//
//	meter := otel.Meter("rebar.audit")
//	sink, err := auditotel.Wrap(auditpg.New(pool), meter)
//	rec := audit.NewRecorder(sink, cfg)
//
// Инструмент (meter даёт потребитель; имя и единица — часть контракта, на них
// стоят алерты):
//
//	| Метрика                        | Тип     | Что |
//	|--------------------------------|---------|-----|
//	| audit_events{action,outcome}   | counter | записанные события журнала по действию и исходу |
//
// Prometheus-экспортёр припишет счётчику _total. Алерты потребителя строятся
// на разделении исходов: «подбор пароля» —
// rate(audit_events_total{action="user.login",outcome="denied"}) выше обычного
// в разы; «отказы в правах пошли волной» — то же по своему действию;
// «журнал замолчал» — increase(audit_events_total[15m]) == 0 при живом
// трафике. Порог берётся от обычной нагрузки потребителя: она у каждого своя,
// и числа тут ставит он.
//
// Безопасность:
//
//  1. МЕТКИ — ЗАКРЫТЫЕ НАБОРЫ: action приходит из Config.Actions и проверен
//     ядром до записи, outcome — из AllOutcomes. Актор, цель, адрес,
//     идентификатор запроса и подробности в метки не попадают: кардинальность
//     метрики задаёт сборка процесса, а не внешний мир, а адрес и логин в
//     системе мониторинга — это персональные данные, которые оттуда уже не
//     удалить по требованию субъекта.
//  2. ДЕКОРАТОР НЕ ЧИТАЕТ ПОДРОБНОСТЕЙ И НИЧЕГО НЕ ЛОГИРУЕТ: из события
//     берутся только Action и Outcome, ошибка next уходит вызывающему и
//     никуда больше.
//  3. СЧИТАЕТСЯ ЗАПИСАННОЕ, А НЕ ПОПЫТКА: иначе дашборд показывал бы
//     события, которых в журнале нет, и разбор инцидента шёл бы по метрике,
//     а не по журналу.
//
// Чего нет (решения, не пробелы): счётчика отказов записи — ошибку получает
// вызывающий, и алерт на неё живёт в его же обработке ошибок, а не в двух
// местах сразу; гистограммы длительности записи — запись идёт в транзакции
// действия, и её длительность измеряется вместе с ним; трейсов — событие
// пишется внутри спана вызывающего; гейджей размера журнала — глубина
// append-only таблицы это её возраст, а не здоровье.
