// Package audittest — двойники портов audit для тестов потребителей и
// адаптеров. Двойник — не мок: ведёт себя как приёмник, чтобы тест проверял
// исход; потокобезопасен целиком, включая настройку: она правится методами под
// замком, а не публичными полями (CONVENTIONS §3). Ошибки двойника отличимы от
// доменных: ErrSinkFailed.
//
// Жители:
//
//   - Sink — audit.Sink в памяти: события копятся в порядке записи и после
//     неё не меняются — тот же append-only, который держит auditpg. Метода
//     очистки нет намеренно: он смоделировал бы удаление, которого у порта
//     нет; свежий двойник — это NewSink. SetErr задаёт отказ записи для
//     fail-closed тестов, Events / Last / ByAction / Count показывают
//     записанное. Момент At хранится так, как его хранит timestamptz у
//     auditpg: в UTC и до микросекунд.
