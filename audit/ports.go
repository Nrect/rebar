package audit

import "context"

// Sink — порт приёмника журнала.
//
// Реализация обязана быть append-only: записанное событие она не изменяет и
// не удаляет. Удаление по ретеншну — действие потребителя своим раннером
// (doc.go, «Чего нет»), а не метод порта.
//
// Ошибка возвращается вызывающему как есть и ничего за него не решает.
// Реализация, пишущая в базу потребителя, обязана уметь войти в транзакцию
// самого действия (auditpg.Sink.WithTx): там, где действие стоит денег,
// «действие без записи» и «запись без действия» одинаково недопустимы.
// Событие приходит уже проверенным и усечённым — чистить его повторно
// реализация не должна.
type Sink interface {
	Write(ctx context.Context, ev Event) error
}
