// Package auditpg — audit.Sink на github.com/jackc/pgx/v5: журнал строками в
// таблице audit_events базы потребителя. Границу ошибки Postgres держит
// github.com/nrect/rebar/postgres — зависимость, разрешённая адаптерам
// хранилища (ADR-0005); ядру audit она запрещена, там нет и не должно быть SQL.
//
// Схема лежит рядом файлом schema.sql с маркерами goose и копируется в каталог
// миграций потребителя как есть (либо применяется из кода: Schema — тот же
// файл, embed). CheckSchema на старте проверяет таблицу, но не применяет её:
// миграция остаётся у потребителя. Sink работает и в пуле, и в транзакции
// вызывающего: New(pool) — для записей вне бизнес-фактов, WithTx(tx) — чтобы
// запись легла вместе с самим действием.
//
//	sink := auditpg.New(pool)
//	if err := sink.CheckSchema(ctx); err != nil { … }   // миграция не применена?
//	ev, err := rec.Prepare(ctx, entry)                  // чистая проверка
//	err = sink.WithTx(tx).Write(ctx, ev)                // та же транзакция
//
// Безопасность:
//
//  1. ПОДРОБНОСТИ СОБЫТИЯ НЕ ПОПАДАЮТ В ОШИБКИ. У pgconn.PgError в Detail
//     лежит «Failing row contains (…)» — вся строка с логином, адресом и
//     подробностями действия; границу держит общий postgres.Sanitize, от
//     ошибки остаются SQLSTATE, Message и имя ограничения (errors.go).
//     Своя копия этой границы была бы лишним шансом разойтись там, где
//     расхождение стоит утечки (ADR-0005). Логов в адаптере нет вовсе.
//  2. WithTx — ОДНА ТРАНЗАКЦИЯ С ДЕЙСТВИЕМ. Компилятор этого не проверяет,
//     поэтому контракт держит тест TestSink_WithTx_IsAtomic: после ROLLBACK
//     нет ни строки журнала, ни самого факта.
//  3. APPEND-ONLY ДЕРЖИТ БАЗА. В адаптере нет ни UPDATE, ни DELETE
//     (TestAdapter_HasNoUpdateOrDelete), а UPDATE отвергает триггер
//     audit_events_append_only_trg — правку в обход пакета не примет Postgres.
//     CheckSchema требует у триггера режим ENABLE ALWAYS, а не только его
//     наличие: DISABLE TRIGGER и режим по умолчанию после восстановления
//     дампа снимают append-only, не убирая триггер из каталога.
//     DELETE база разрешает: ретеншн — политика потребителя.
//  4. ЗАКРЫТЫЕ НАБОРЫ ЗЕРКАЛЯТСЯ CHECK: outcome и actor_kind не примут
//     значения мимо AllOutcomes и AllActorKinds; guard-тест сверяет CHECK со
//     списками. У action CHECK'а нет намеренно — его набор задаёт
//     Config.Actions потребителя.
//  5. FAIL CLOSED. Nil-пул и nil-транзакция — паника на старте; любой сбой
//     Postgres — audit.ErrUnavailable, и решает по нему вызывающий.
//  6. ВРЕМЯ ПРИХОДИТ ПАРАМЕТРОМ. DEFAULT now() в схеме нет: иначе тесты ядра
//     на управляемых часах проверяли бы одно, а база писала другое.
//
// Чего нет (решения, не пробелы): чтения и поиска по журналу — выборки,
// страницы и права на просмотр домен потребителя, и модель доступа мы за него
// не выбираем; удаления и ретеншна — срок хранения персональных данных задаёт
// его политика, удаляет он своим раннером; раннера миграций — schema.sql
// применяет goose потребителя, CheckSchema только сверяет; своего пула и
// настроек соединения — пул даёт потребитель.
