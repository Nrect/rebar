// Package audit — журнал действий: кто, что, над чем, чем кончилось и когда.
//
// Потребитель кладёт актора в контекст обвязкой входа (NewContext) и зовёт
// Recorder.Record с действием из закрытого набора Config.Actions. Запись
// уходит в порт Sink: LogSink пишет структурную строку в log/slog, auditpg —
// строку в таблицу базы потребителя, причём в ту же транзакцию, что и само
// действие (Recorder.Prepare + auditpg.Sink.WithTx). Декоратор auditotel
// считает события метрикой.
//
// Ядро — stdlib + github.com/google/uuid; адаптеры (auditpg, auditotel) —
// подпакеты с одной библиотекой каждый.
//
//	ctx = audit.NewContext(ctx, audit.Actor{Kind: audit.ActorUser, ID: uid})
//	rec := audit.NewRecorder(audit.NewLogSink(slog.Default()), cfg)
//	err := rec.Record(ctx, audit.Entry{
//		Action: "user.login", Outcome: audit.OutcomeDenied,
//		IP: remoteIP, Details: map[string]string{"reason": "bad_password"},
//	})
//
// Безопасность:
//
//  1. НАБОР ДЕЙСТВИЙ ЗАКРЫТ (Config.Actions). Опечатка в имени иначе заводит
//     новый код действия навсегда: он уезжает меткой метрики в чужие
//     дашборды и алерты, откуда его уже не убрать. Держит Prepare
//     (ErrUnknownAction) и panic-валидация Config.
//  2. КЛЮЧИ ПОДРОБНОСТЕЙ, ПОХОЖИЕ НА СЕКРЕТ, — ОШИБКА (ErrForbiddenDetail):
//     пароль, токен, секрет, заголовок авторизации, кука
//     (ForbiddenDetailKeys). Молчаливое выбрасывание поля научило бы
//     вызывающего, что секреты писать можно: он не узнал бы, что поле не
//     доехало. Держит TestPrepare_ForbiddenDetailKeys.
//  3. АКТОР — ИЗ КОНТЕКСТА, НЕ ИЗ ТЕЛА ЗАПРОСА. Субъект, названный в запросе,
//     это то, что о себе сказал проверяемый. Поля Actor в Entry нет вовсе,
//     а не положенный обвязкой актор даёт ErrNoActor: тихая запись без
//     субъекта означала бы, что забытую обвязку нечем заметить.
//  4. ВРАЖДЕБНЫЙ ВВОД УСЕКАЕТСЯ И ЧИСТИТСЯ, А НЕ ОТВЕРГАЕТСЯ. Отказ на
//     негодном значении позволил бы стереть свой след одним переводом строки
//     в поле логина; управляющие руны заменяются, иначе «\n» дописывает в
//     текстовый лог вторую, поддельную строку аудита. Потолки —
//     MaxActorIDLen и соседи, Config.MaxDetailLen.
//  5. ЖУРНАЛ APPEND-ONLY. У порта Sink один метод — Write; в auditpg нет ни
//     UPDATE, ни DELETE, а UPDATE запрещает ещё и триггер схемы. Правка
//     строки журнала стирает историю, и «поправить опечатку» неотличимо от
//     «замести расхождение» (CORRECTNESS, закон 2).
//  6. РЕТЕНШН — У ПОТРЕБИТЕЛЯ. Срок хранения персональных данных задаёт его
//     политика и его закон, а не наш Config; удаляет он своим раннером по
//     своим срокам. Поэтому метода удаления в порту нет.
//  7. ОШИБКА ЗАПИСИ ВОЗВРАЩАЕТСЯ ВЫЗЫВАЮЩЕМУ (ErrUnavailable). Падать,
//     отказывать в действии или продолжать без записи — решение разное у
//     входа в систему и у возврата денег, и принимает его потребитель.
//     Пакет не глотает ошибку и не логирует её за него.
//
// Чего в пакете нет (решения, не пробелы):
//
//   - чтения и поиска по журналу: выборки, страницы и права на просмотр —
//     домен потребителя; отдав их пакетом, мы отдали бы и его модель доступа;
//   - удаления и ретеншна: см. п. 6;
//   - подписи цепочки записей (хэш предыдущей): защищает от того, у кого есть
//     доступ к базе, — то есть от нас же; настоящий страж здесь — отдельное
//     хранилище, а не колонка в той же таблице;
//   - асинхронной очереди и буфера: запись идёт в транзакции действия, а
//     буфер в памяти теряет ровно те события, ради которых журнал заводят;
//   - типов цели из закрытого набора: сущности перечисляет потребитель,
//     а в метки метрик Target не попадает;
//   - трейсинга и корреляции со спанами: идентификатор запроса едет полем
//     RequestID, а span'ы ставит обвязка потребителя.
