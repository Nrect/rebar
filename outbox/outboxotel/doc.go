// Package outboxotel — наблюдаемость очереди на OpenTelemetry: декоратор
// реестра хендлеров со счётчиком outbox_handled{kind,result}, гистограммой
// outbox_handle_duration{kind} и span'ом доставки, плюс Gauges — пять
// observable gauge, читающих снимок outbox.Stats.
//
// Ядро метрик не пишет и otel не импортирует (CONVENTIONS §6); зависимость
// живёт здесь. Meter — rebar.outbox. Собирается так:
//
//	h, err := outboxotel.New(meter, tracer, cfg)
//	h.Register("order.paid", paidHandler)
//	w, err := outbox.NewWorker(store, h.Registry(), cfg)
//	g, err := outboxotel.NewGauges(meter)
//	// после каждого прогона Drain:
//	stats, err := w.Stats(ctx)
//	g.Set(stats)
//
// Имена и единицы инструментов — часть контракта: на них стоят алерты
// потребителя (ADR-0002, «Наблюдаемость и алерты»). Главный из них — не
// глубина очереди, а outbox_oldest_due_age_seconds: только он ловит строку,
// которую вечно троттлят, — попытки у неё не расходуются, и в failed она не
// попадёт никогда.
//
// Безопасность:
//
//  1. МЕТКИ — ЗАКРЫТЫЕ НАБОРЫ: kind из outbox.Config.Kinds, result из
//     AllResults (семь исходов, guard-тест). AggregateID, payload и текст
//     ошибки метками не становятся: это данные, а не словарь, и они разносят
//     кардинальность метрик и уносят персональные данные в мониторинг,
//     откуда их уже не удалить по требованию субъекта.
//  2. ДЕКОРАТОР НЕ ЧИТАЕТ PAYLOAD И НИЧЕГО НЕ ЛОГИРУЕТ. Из доставки берутся
//     Kind, Attempts и Reclaimed; текст ошибки не попадает ни в метку, ни в
//     атрибут span'а, ни в его статус.
//  3. ОШИБКА ХЕНДЛЕРА ИДЁТ ДАЛЬШЕ БЕЗ ИЗМЕНЕНИЙ. Drain читает классы
//     структурно, по методам Permanent() и RetryAfter(); обёртка, потерявшая
//     цепочку, превратила бы постоянный отказ в бесконечные повторы.
//  4. ПАНИКА СЧИТАЕТСЯ И ЛЕТИТ ДАЛЬШЕ. Исход по умолчанию — panic, поэтому
//     взорвавшийся хендлер виден на дашборде; recover в декораторе нет, иначе
//     Drain перестал бы видеть панику и не назначил бы строке временную
//     ошибку.
//  5. ГЕЙДЖИ ЧИТАЮТ СНИМОК, А НЕ ХОДЯТ В БАЗУ НА КАЖДЫЙ SCRAPE: расписание у
//     потребителя, коллбэк отдаёт последний Set. Все пять — один коллбэк,
//     поэтому «pending» и «возраст» на дашборде из одного момента.
//  6. throttled ОТДЕЛЁН ОТ retry: названный провайдером срок не расходует
//     лимит попыток, и сведи их — строка, которую вечно троттлят, была бы
//     неотличима от строки, которая честно повторяется.
//  7. FAIL CLOSED. Nil-метр, nil-трейсер, негодный MaxAttempts и nil-хендлер —
//     паника на старте; дубль типа и негодный Kind роняет сам outbox.Registry,
//     обёртка его не смягчает.
//
// Чего нет (решения, не пробелы): счётчика outbox_redrives — redrive идёт
// через Worker, а не через реестр, и декоратора порта Store у пакета нет:
// кто нажал и зачем, знает аудит потребителя; счётчиков expired и released —
// до хендлера они не доходят, их видно гейджами и логом прогона (ADR-0002,
// «Наблюдаемость»); span'а прогона Drain — его даёт scheduler, у которого
// свои cron_*; автообновления снимка — Gauges в базу не ходит, Set зовёт
// потребитель после Drain; выбора имён инструментов — на них стоят чужие
// алерты, и настройка означала бы, что дашборд собирается заново у каждого.
