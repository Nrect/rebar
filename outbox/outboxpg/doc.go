// Package outboxpg — outbox.Store на github.com/jackc/pgx/v5: очередь событий
// и команд в таблице outbox_messages базы потребителя.
//
// Схема лежит рядом файлом schema.sql с маркерами goose и копируется в каталог
// миграций потребителя как есть (либо применяется из кода: Schema — тот же
// файл, embed). CheckSchema на старте проверяет таблицу, но не применяет её.
// Проект и причины — docs/adr/0002-outbox.md.
//
// ДВА ПУТИ ВСТАВКИ, И ОНИ ДЛЯ РАЗНЫХ ЛЮДЕЙ: потребитель зовёт пакетную
// Enqueue(ctx, tx, env) — она вставляет и тут же сверяет отпечаток повтора,
// потому что инвариант «громкая идемпотентность», который держится памятью
// вызывающего, не держится ничем; сырой метод порта Store.Enqueue остаётся
// воркеру, контрактным тестам и тому, кто строит свою обёртку.
//
//	store := outboxpg.New(pool)
//	if err := store.CheckSchema(ctx); err != nil { … }  // миграция не применена?
//	env, err := producer.Prepare(msg)                   // чистая валидация
//	res, err := outboxpg.Enqueue(ctx, tx, env)          // та же транзакция, что и факт
//
// Безопасность:
//
//  1. PAYLOAD НЕ ПОПАДАЕТ В ОШИБКИ. Границу держит postgres.Sanitize: у
//     pgconn.PgError в Detail лежит «Failing row contains (…)» — вся строка с
//     payload и заголовками; от ошибки Postgres остаются SQLSTATE, Message и
//     имя ограничения (errors.go). Логов в адаптере нет вовсе.
//  2. WithTx — ОДНА ТРАНЗАКЦИЯ С ФАКТОМ ПОТРЕБИТЕЛЯ. Компилятор этого не
//     проверяет, поэтому контракт держит тест TestEnqueue_WithTx_IsAtomic:
//     после ROLLBACK нет ни строки очереди, ни факта, ни занятого ключа.
//  3. ПОВТОР ПО КЛЮЧУ НЕ РОНЯЕТ ТРАНЗАКЦИЮ. Конфликт разбирается через
//     ON CONFLICT (kind, dedup_key) WHERE dedup_key <> ” DO NOTHING: перехват
//     23505 перевёл бы транзакцию потребителя в aborted и снёс бы бизнес-факт
//     вместе с событием (TestEnqueue_DuplicateDoesNotAbortTx).
//  4. FOR UPDATE SKIP LOCKED — ДВА ВОРКЕРА НЕ БЕРУТ ОДНУ СТРОКУ: арбитр здесь
//     база, а не Go, поэтому «проверил — взял» в коде отсутствует; доказано
//     тестом TestStore_Claim_FourWorkersRace.
//  5. FENCING. Finish меняет строку только при совпадении claim_token: ноль
//     строк — outbox.ErrClaimLost и ни одного изменения, поэтому воркер,
//     проснувшийся после паузы GC, не перепишет результат живого соседа
//     (TestStore_Finish_StaleTokenAffectsNoRows).
//  6. АРЕНДУ ДЕРЖИТ БАЗА, А НЕ КОД. CHECK outbox_messages_claim_chk не примет
//     ни processing без токена и срока, ни аренду у другого статуса: правку в
//     обход адаптера отвергает Postgres.
//  7. PAYLOAD ХРАНИТСЯ ВСЕГДА, ВКЛЮЧАЯ failed, а Purge не трогает failed:
//     без payload redrive невозможен, а молча исчезнувший dead-letter — это
//     потерянное событие без следов.
//  8. FAIL CLOSED. Nil-пул и nil-транзакция — паника на старте; неизвестный
//     исход Finish и любой сбой Postgres — outbox.ErrUnavailable, а не «ну и
//     ладно».
//
// Чего нет (решения, не пробелы): раннера миграций — schema.sql применяет
// goose потребителя, CheckSchema только сверяет (две правды о схеме, DDL-права
// у приложения и гонка реплик при выкате — не наше); своего пула и настроек
// соединения — их даёт потребитель; порядка внутри агрегата — SKIP LOCKED без
// FIFO осознанно (ADR-0002, «Чего нет»), индекс по агрегату заведён для
// отладочных выборок и будущего режима Serial; LISTEN/NOTIFY — опрос ведёт
// scheduler; своей копии границы ошибки — её держит postgres.Sanitize, общий
// для всех адаптеров хранилища (ADR-0005, «Межмодульные зависимости»).
