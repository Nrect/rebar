// Package outbox — транзакционный outbox для событий и команд: строка
// коммитится вместе с бизнес-фактом, фоновый воркер забирает пачку под
// арендой с fencing-токеном, отдаёт хендлеру по Kind, классифицирует ошибку,
// повторяет с джиттером, а исчерпав попытки — кладёт строку в видимый
// dead-letter с операторским redrive.
//
// Потребитель зовёт чистый Producer.Prepare и вставляет конверт СВОИМ
// адаптером в транзакции факта (outboxpg.WithTx): у пакета нет вставки через
// пул, поэтому «двойная запись» закрыта конструктивно, а не дисциплиной.
// Фоновый Worker.Drain и Worker.Purge ложатся в scheduler.Job.Run без
// обёртки. Отложенная команда — та же строка с NotBefore; протухшая — с
// NotAfter.
//
//	env, err := producer.Prepare(msg)          // до транзакции: чисто и без сети
//	res, err := store.WithTx(tx).Enqueue(ctx, env)
//	res, err = outbox.CheckDuplicate(env, res) // повтор законен только с тем же отпечатком
//
// Ядро — stdlib + github.com/google/uuid; адаптеры (outboxpg, outboxotel) —
// подпакеты с одной библиотекой каждый. Классы ошибок читаются структурно, по
// методам Permanent() bool и RetryAfter() (time.Duration, bool), поэтому
// хендлер может вернуть ошибку чужого пакета, и ни один импорт ради этого не
// нужен. Проект и причины — docs/adr/0002-outbox.md.
//
// Безопасность:
//
//  1. ENQUEUE ТОЛЬКО В ТРАНЗАКЦИИ ФАКТА. Prepare чистый, вставка — WithTx
//     адаптера; Enqueue через пул у пакета нет вовсе. Это единственное, что
//     физически предотвращает главную ошибку внедрения outbox: код, который
//     компилируется, работает и теряет события ровно как раньше.
//  2. AT-LEAST-ONCE СКАЗАН ВСЛУХ. Падение между Handle и Finish даёт вторую
//     доставку после истечения аренды, с Delivery.Reclaimed = true. Хендлер
//     ОБЯЗАН быть идемпотентным; политики Uncertain у пакета нет — что делать
//     с неизвестным исходом, знает домен, а не очередь.
//  3. FENCING. Finish меняет строку, только если она в processing и держит
//     тот же claim_token; ноль строк — ErrClaimLost и ни одного изменения.
//     Проснувшийся после паузы воркер A не перепишет результат воркера B.
//  4. FAIL CLOSED. Kind вне Config.Kinds не вставляется, Kind без хендлера не
//     забирается (Claim фильтрует по реестру); nil-порт и негодный Config —
//     паника на старте; Lease > HandlerTimeout валидируется, иначе второй
//     воркер заберёт строку, пока первый ещё работает.
//  5. ГРОМКАЯ ИДЕМПОТЕНТНОСТЬ. Тот же (Kind, DedupKey) с тем же отпечатком —
//     успех как повтор; с другим — ErrKeyReused, не тихий no-op: иначе
//     «начислить 100» под ключом «начислить 500» молча стало бы «уже сделано».
//  6. PERMANENT НЕ ПОВТОРЯЕТСЯ, THROTTLED УВАЖАЕТСЯ. Неизвестная ошибка —
//     временная: потерянное событие дороже лишней попытки. Названный срок
//     повтора упирается в Backoff.Max и в NotAfter, но НЕ РАСХОДУЕТ
//     MaxAttempts: «занято» — это не «не могу». Следствие сказано вслух:
//     строка без NotAfter под вечным троттлингом ждёт сколько угодно и в
//     failed(exhausted) не уйдёт никогда. Это выбор в пользу «не потерять
//     событие» — молча протухший платёж дороже растущей очереди; видимость
//     даёт гейдж Stats.OldestDueAge, он ровно для этого и заведён.
//  7. DEAD-LETTER ВИДИМЫЙ И ХРАНИМЫЙ. failed не чистится Purge, payload
//     остаётся — без него redrive невозможен. Секреты в payload шифрует
//     потребитель: пакет их не стирает и не логирует. LastError усечён до
//     MaxErrorLen и payload не содержит.
//  8. REDRIVE — ОПЕРАЦИЯ. Только из failed, со сбросом попыток, возвращает
//     «затронуто ли»; кто нажал и зачем — аудит потребителя, не пакета.
//  9. МЕТКИ ЗАКРЫТЫЕ. kind из Config.Kinds, result из набора исходов.
//     AggregateID и текст ошибки в метки не попадают: это данные, а не
//     словарь, и они разносят кардинальность.
//  10. ПАНИКА ХЕНДЛЕРА — ИСХОД СТРОКИ, А НЕ ПАДЕНИЕ ВОРКЕРА. Отмена ctx
//     останавливает пачку; строки, до которых очередь не дошла, возвращаются
//     в pending без потраченной попытки (released) — быстрая остановка не
//     отправляет работу в dead-letter.
//
// Наблюдаемость собирается снаружи, декоратором в outboxotel (CONVENTIONS §6):
// счётчик outbox_handled{kind,result}, гейджи pending, processing, failed,
// unhandled и oldest_due_age по снимку Stats. Алерты: возраст старейшей
// готовой строки (не глубина очереди), рост failed, ненулевой unhandled —
// последнему нужна выдержка: при выкате новой версии старый инстанс кратко
// показывает ненулевой unhandled на типах, которых он ещё не умеет, и это
// штатное состояние выката, а не авария. Пороги и запросы —
// docs/adr/0002-outbox.md.
//
// Чего в пакете нет (решения, не пробелы): порядка per-aggregate (SKIP LOCKED
// без FIFO — осознанно; режим Serial по индексу агрегата — v0.2);
// LISTEN/NOTIFY-будильника (опрос через scheduler; NOTIFY недолговечен и
// очередью не является); продления аренды (её заменяет Lease >
// HandlerTimeout); приоритетов и нескольких очередей; саги и state machine
// (отдельный пакет, когда появится второй процесс); Kafka и CDC (брокер не
// объединяет транзакцию Postgres с публикацией); шифрования payload (у
// потребителя); HTTP-ручек redrive (у потребителя, порт есть); политики
// Uncertain (решает хендлер по Reclaimed); inbox (это паттерн потребителя:
// вставка отметки в одной транзакции с эффектом).
package outbox
