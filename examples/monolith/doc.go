// Package monolith — приложение-потребитель, собранное на ВСЕХ модулях
// тулкита сразу.
//
// Это ГЕЙТ ПЕРЕД ТЕГАМИ, а не пример для витрины. Каждый модуль протестирован
// сам по себе; чего не проверял никто — что их порты сходятся у живого
// потребителя (ADR-0005, «examples/* — модули с replace, без версий»).
// Версий пример не получает и в теги не входит: он проверяет то, что лежит в
// дереве СЕЙЧАС, а не то, что опубликовано.
//
// # Четыре стыка, ради которых всё собрано
//
//  1. ХУК ЗАЧИСЛЕНИЯ (shoppg.Settler). Заказ, право и событие outbox ложатся
//     ТОЙ ЖЕ транзакцией, что и книга платежей; ошибка хука откатывает всё,
//     включая строку дедупа события, и отвечает 503 — даже если хук вернул
//     свою SlugError. Держат TestSettlerFailure_RollsBackEverything и
//     TestSettlerSlugError_KeepsWebhookRetryable.
//  2. ПОРТ session.Tokens (shoppg.Tokens). Единственная сборка, которой в
//     тулките нет ни у кого: authpg.WithTx().Insert плюс mail.Prepare плюс
//     mailpg.WithTx().Enqueue одной транзакцией.
//  3. ПЛАНИРОВЩИК. Пять фоновых задач подошли ему как есть: ни одной обёртки
//     под сигнатуру Run(ctx) (int, error) писать не пришлось (jobs.go).
//     Шестая, gauges_snapshot, — своя задача примера: снимки гейджей. Одна,
//     payments_reconcile, идёт под postgres/pglock — разбор ниже.
//  4. КЛАССЫ ОШИБОК. postgres.Sanitize → доменная ошибка → kit/errs/httperr;
//     503 от недоступного хранилища и 403 от правил различимы, а в теле
//     ответа нет ни строки базы, ни логина, ни токена. Класс несёт sentinel
//     модуля, таблица errors.go — только слаги продукта. Держат
//     TestErrorClasses_ReachHTTP, TestErrorBody_LeaksNothing и TestTranslate_*.
//
// # Порядок сборки
//
// НЕ СОВПАДАЕТ С ПОРЯДКОМ ЗАВИСИМОСТЕЙ МОДУЛЕЙ. mail и outbox собираются
// раньше auth и payment, потому что порты, которые реализует потребитель,
// тянут их к себе: postgres → otelboot → mail → outbox → auth → authz →
// entitlement → payment → objectstore → scheduler.
//
// Безопасность:
//
//  1. ДРАЙВЕР ЖИВЁТ В ОДНОМ КАТАЛОГЕ. pgx законен только в shoppg; ядро
//     примера про него не знает. Держат TestGuard_CoreHasNoDriver и правило
//     depguard в корне репозитория.
//  2. ОШИБКИ ПИШЕТ httperr. Наружу уходит слаг из закрытого набора и
//     request_id; текст доменной ошибки, имя таблицы, SQLSTATE, логин и токен
//     не уходят никогда. Ручкам людей отвечает ответчик со словарём продукта,
//     вебхуку — ответчик классом: правило словаря, совпавшее с ошибкой хука,
//     превратило бы 503 в 4xx. Держат TestGuard_NoDirectHTTPErrors,
//     TestErrorBody_LeaksNothing и TestWebhook_AnswersClassWithoutTranslate.
//  3. СБОЙ И ОТКАЗ РАЗЛИЧИМЫ. 503 против 403: «доступа нет» при упавшей базе
//     учит чинить права вместо базы, и инцидент тонет.
//  4. ЦЕНУ СЧИТАЕТ СЕРВЕР. Клиент называет товар и ключ идемпотентности;
//     сумма, состав и валюта берутся из каталога и морозятся в намерении.
//  5. КЛЮЧ ФАЙЛА СТРОИТ ХРАНИЛИЩЕ. Имя файла пользователя — данные: оно
//     лежит в колонке и в ключ не попадает никогда.
//  6. СХЕМЫ АДАПТЕРОВ СКОПИРОВАНЫ КАК ЕСТЬ и сверяются на старте
//     (CheckSchema): правка копии — вторая правда о схеме.
//  7. ОШИБКА КОНФИГУРАЦИИ ПАДАЕТ НА СТАРТЕ. Ни одна не проглатывается — в том
//     числе сборка транспорта почты: письмо подтверждения и есть критический
//     путь регистрации, и приложение, которое его не отправит, — это
//     сломанная регистрация с зелёным healthz. Держит
//     TestStart_RefusesBadTransportConfig.
//  8. ОТСУТСТВИЕ ТРАНСПОРТА — НАЗВАННЫЙ РЕЖИМ, А НЕ ИСХОД ОШИБКИ.
//     SMTP_TRANSPORT=unconfigured собирает mail.Unconfigured: стенд без
//     почтовика, письма копятся в очереди и честно падают с
//     ErrTransportUnconfigured, попытки не тратятся. Умолчание — smtp:
//     «писем не шлём» не должно доставаться тому, кто забыл про переменную.
//
// # Наблюдаемость
//
// Снимки гейджей — очереди mail и outbox, зависшие и расхождения payment —
// обновляет ОТДЕЛЬНАЯ задача gauges_snapshot на своём такте GAUGES_TICK, не
// scrape и не чужая задача (CONVENTIONS §6). На scrape частоту запросов к базе
// задавал бы Prometheus, умноженный на реплики и скрейперы; /metrics здесь —
// голый обработчик otelboot.
//
// Первый снимок — СРАЗУ при старте: App.Start зовёт RunNow задачи до запуска
// планировщика, как велит scheduler/doc.go. Минута нулей после деплоя была бы
// минутой, когда расхождение книг невидимо, — а payment_drift кормит денежный
// алерт с порогом 1.
//
// Алерт «снимки не обновляются»: у задачи свои ряды cron_*, и её смерть —
// отдельная видимая поломка, а не примесь к чужой.
//
//	time() - cron_last_success_timestamp_seconds{job="gauges_snapshot"} > 180
//
// 180 — три такта при умолчании GAUGES_TICK в минуту; порог следует за тактом.
//
// # Распределённая блокировка: одна задача из шести
//
// Первая линия старше (ADR-0008, PATTERNS §12): задачу, безопасную при любом
// числе реплик, в pglock не заворачивают — это поход в базу на каждый тик и
// ложное чувство, что без него было опасно. Разбор всех шести:
//
//	mail_deliver         нет: Claim — FOR UPDATE SKIP LOCKED и аренда, письмо берёт один воркер
//	outbox_drain         нет: то же, плюс claim_token; хендлеры идемпотентны
//	auth_sweep           нет: DELETE по времени — вторая реплика удалит ноль строк
//	objectstore_collect  нет: в CollectDryRun это чтение, Delete отсутствующего объекта —
//	                     не ошибка (порт Store), а FILES_DIR у каждой реплики свой:
//	                     под ключом убирала бы одна
//	gauges_snapshot      нет: гейджи процесса — под ключом у остальных реплик застыли бы
//	payments_reconcile   ДА: строк не захватывает — курсор в памяти, и каждая реплика
//	                     идёт той же очередью с той же головы. Эффекты гасятся ключом
//	                     провайдера, дедупом событий и CAS, но вызовы провайдера и
//	                     payments_total{op="reconcile"} множатся на число реплик;
//	                     payment.Reconciler сам требует внешнюю блокировку. Пропуск
//	                     тика дёшев: сверка берёт намерения старше StalePendingAfter
//
// Прогон сверки держит соединение общего пула на всё время: у ручек и
// остальных задач на одно соединение меньше.
//
// ПУЛ ПРЯМОЙ: shoppg.Open поднимает pgxpool на DATABASE_URL, пулера в примере
// нет. PgBouncer в режиме transaction выключил бы защиту молча — нужен режим
// session или прямое соединение (ADR-0008, «Условие развёртывания»).
//
// Наблюдатель — lockotel: cron_lock_total{job,result}, ряды рождаются нулём.
// Пропуск планировщик пишет успехом, и отличает его только этот счётчик —
// держит TestPaymentsReconcile_OneReplicaRuns. Алерт «ключ застрял» считается
// по сумме реплик:
//
//	sum by (job) (increase(cron_lock_total{job="payments_reconcile",result="acquired"}[5m])) == 0
//
// Окно — не короче нескольких тактов и нескольких scrape: при TICK в секунду
// пяти минут с запасом.
//
// # Что не сошлось: обходы постоянные
//
// Их НЕ СНИМАТЬ, когда сойдутся остальные порты. Это решения, а не отсрочка,
// и лежат они отдельным разделом ровно затем, чтобы их не «дочинили» заодно.
//
//  1. ПРИЧИНА ОТКАЗА ENTITLEMENT НЕ ПЕРЕЖИВАЕТ ХУК. authz.Policy возвращает
//     bool, поэтому «купил и кончилось» (deny_expired) и «не покупал»
//     (deny_no_grant) снаружи неразличимы. Обход: различаем только сам факт
//     сужения — authz.ReasonPolicy (errors.go, denialOf).
//     ПОЧЕМУ НАВСЕГДА: менять сигнатуру Policy — ломающее изменение ради
//     того, что уже обходится.
//  2. DEFAULTCOOKIECONFIG НЕ ГОДИТСЯ БЕЗ TLS. Она даёт имена с префиксом
//     __Host-, а он требует Secure, и на стенде по http конструктор паникует.
//     Обход: cookieConfig собирает конфигурацию руками (wiring.go).
//     ПОЧЕМУ НАВСЕГДА: именованная «конфигурация куки для стенда» — это
//     заготовка, которую однажды скопируют в прод с Secure: false. Ручная
//     сборка честнее: она видна в diff'е. Паника Middleware на __Host- без
//     Secure — страж, который сработал, а не баг.
//
// # Снято: порты сошлись
//
// Находки гейта, починенные в тулките. Обходов из примера не осталось —
// в этом и был смысл пересадки: пример обязан показывать сошедшиеся порты, а
// не аккуратный обход несошедшихся, иначе следующий потребитель скопирует
// обход вместе с ними.
//
//  1. У MAIL НЕ БЫЛО ЭКСПОРТИРОВАННОЙ ПРОВЕРКИ ПОВТОРА — 131c612.
//     mail.CheckDuplicate, зеркало outbox'ного; копия sameLetter снята
//     (shoppg/tokens.go).
//  2. У PAYMENT.SERVICE НЕ БЫЛО ЧИТАЮЩИХ МЕТОДОВ — 461bb65. IntentByID,
//     IntentByKey и Ledger на Service; чтение мимо домена снято, поле
//     payStore у App исчезло. IntentByKey нормализует ключ сам, как и Start;
//     пробу им до Start пример потом снял — повтор ключа разбирает Start.
//  3. У AUTHZ НЕ БЫЛО ОШИБКИ ОТКАЗА — 40ea4b7. authz.ErrDenied и
//     Authorizer.Require; свой ErrAccessDenied снят.
//  4. У ENTITLEMENT.STORE.GRANT НЕ БЫЛО ВРЕМЕНИ — f67c46b, ЛОМАЮЩЕЕ.
//     Grant(ctx, subjectID, g, at); адаптер выдач переписан — GrantAt, часы и
//     SetClock ушли целиком, а не остались обёрткой: обёртка сохранила бы
//     вопрос «зачем тут часы» с уже неверным ответом. Grant.GrantedAt
//     читается обратно в Open, поэтому «время параметром» теперь
//     проверяемо, а не на слово.
//  5. PGTEST.SCHEMA ОТДАВАЛА ПУЛ, А НЕ DSN — 742de4e. pgtest.SchemaDSN;
//     ручная сборка схемы и search_path снята.
//  6. У KIT/CONFIG НЕ БЫЛО НЕОБЯЗАТЕЛЬНОГО СЕКРЕТА — c4f25fe.
//     Loader.OptionalSecret; пароль SMTP снова секрет, а не голая строка.
//  7. ОКОНЧАТЕЛЬНЫЙ ОТКАЗ ПРОВАЙДЕРА ЖИЛ ПОД ErrUnavailable — 1922e9e,
//  3355881. Отказ, пришедший ОШИБКОЙ адаптера, заворачивался в
//     «попробуйте позже», и правило provider-rejected на этом пути было
//     мёртвым: таблица ответов тогда проверяла недоступность первой. Заодно
//     ErrUnsupported без своего правила упал бы в 500 — заведено 501, теперь
//     его даёт класс. Оба пути держит TestErrorClasses_ReachHTTP.
//  8. У ДВОЙНИКА ПРОВАЙДЕРА РУЧКИ БЫЛИ ГОЛЫМИ ПОЛЯМИ — 8bb7709. Методы
//     читали их под мьютексом, а тест писал мимо: гонка, как только двойник
//     дёргают из горутины сервера. Там же RejectNext — отказ без знания
//     Reference, которую HTTP-тест не знает: она рождается в ручке.
//  9. У SENTINEL'ОВ МОДУЛЕЙ НЕ БЫЛО КЛАССА — волна ADR-0007. Таблица
//     errors.go переписывала класс руками: 38 строк, из них семь — «503 с
//     именем подсистемы». Осталось 14 — где слаг меняет действие клиента или
//     адрес пришёл из формы; лишнюю и мёртвую строку роняют
//     TestTranslate_NoRedundantRule и TestTranslate_EveryRuleReachable.
//  10. SESSION ЗАВОДИЛ ЛИЧНОСТЬ ДО СБОРКИ ПИСЬМА. Логин, на который письмо не
//     собиралось, оставлял личность без письма, а повтор отвечал «принято».
//     Порт session.Recipients проверяет получателя до Create; здесь он —
//     mail.NormalizeAddress, совпадение с письмом держат
//     TestRecipients_MatchLetter и FuzzRecipients_MatchLetter.
