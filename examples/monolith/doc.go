// Package monolith — приложение-потребитель, собранное на ВСЕХ модулях
// тулкита сразу.
//
// Это ГЕЙТ ПЕРЕД ТЕГАМИ, а не пример для витрины. Каждый модуль протестирован
// сам по себе; чего не проверял никто — что их порты сходятся у живого
// потребителя (ADR-0005, «examples/* — модули с replace, без версий»).
// Версий пример не получает и в теги не входит: он проверяет то, что лежит в
// дереве СЕЙЧАС, а не то, что опубликовано.
//
// # Четыре стыка, ради которых всё собрано
//
//  1. ХУК ЗАЧИСЛЕНИЯ (shoppg.Settler). Заказ, право и событие outbox ложатся
//     ТОЙ ЖЕ транзакцией, что и книга платежей; ошибка хука откатывает всё,
//     включая строку дедупа события. Держит
//     TestSettlerFailure_RollsBackEverything.
//  2. ПОРТ session.Tokens (shoppg.Tokens). Единственная сборка, которой в
//     тулките нет ни у кого: authpg.WithTx().Insert плюс mail.Prepare плюс
//     mailpg.WithTx().Enqueue одной транзакцией.
//  3. ПЛАНИРОВЩИК. Пять фоновых задач подошли ему как есть: ни одной обёртки
//     под сигнатуру Run(ctx) (int, error) писать не пришлось (jobs.go).
//  4. КЛАССЫ ОШИБОК. postgres.Sanitize → доменная ошибка → kit/errs/httperr;
//     503 от недоступного хранилища и 403 от правил различимы, а в теле
//     ответа нет ни строки базы, ни логина, ни токена. Держат
//     TestErrorClasses_ReachHTTP и TestErrorBody_LeaksNothing.
//
// # Порядок сборки
//
// НЕ СОВПАДАЕТ С ПОРЯДКОМ ЗАВИСИМОСТЕЙ МОДУЛЕЙ. mail и outbox собираются
// раньше auth и payment, потому что порты, которые реализует потребитель,
// тянут их к себе: postgres → otelboot → mail → outbox → auth → authz →
// entitlement → payment → objectstore → scheduler.
//
// Безопасность:
//
//  1. ДРАЙВЕР ЖИВЁТ В ОДНОМ КАТАЛОГЕ. pgx законен только в shoppg; ядро
//     примера про него не знает. Держат TestGuard_CoreHasNoDriver и правило
//     depguard в корне репозитория.
//  2. ОШИБКИ ПИШЕТ ОДИН ОТВЕТЧИК. Наружу уходит слаг из закрытого набора и
//     request_id; текст доменной ошибки, имя таблицы, SQLSTATE, логин и токен
//     не уходят никогда. Держат TestGuard_NoDirectHTTPErrors и
//     TestErrorBody_LeaksNothing.
//  3. СБОЙ И ОТКАЗ РАЗЛИЧИМЫ. 503 против 403: «доступа нет» при упавшей базе
//     учит чинить права вместо базы, и инцидент тонет.
//  4. ЦЕНУ СЧИТАЕТ СЕРВЕР. Клиент называет товар и ключ идемпотентности;
//     сумма, состав и валюта берутся из каталога и морозятся в намерении.
//  5. КЛЮЧ ФАЙЛА СТРОИТ ХРАНИЛИЩЕ. Имя файла пользователя — данные: оно
//     лежит в колонке и в ключ не попадает никогда.
//  6. СХЕМЫ АДАПТЕРОВ СКОПИРОВАНЫ КАК ЕСТЬ и сверяются на старте
//     (CheckSchema): правка копии — вторая правда о схеме.
//
// # Что не сошлось
//
// Находки гейта: места, где порты тулкита не сошлись у потребителя, и как
// это обойдено здесь. Каждая — про тулкит, а не про пример.
//
//  1. У MAIL НЕТ ЭКСПОРТИРОВАННОЙ ПРОВЕРКИ ПОВТОРА. outbox.CheckDuplicate
//     заведён ровно для транзакционного пути; у mail тот же путь описан
//     (Prepare + mailpg.WithTx().Enqueue), но sameMessage не экспортирован, и
//     ErrKeyReused на нём недостижим. Обход: shoppg.sameLetter — копия трёх
//     строк пакета.
//  2. У PAYMENT.SERVICE НЕТ ЧИТАЮЩИХ МЕТОДОВ. IntentByID, IntentByKey и
//     Ledger есть у порта Store, но не у домена, и потребителю, которому надо
//     «то же намерение по тому же ключу», приходится ходить в стор мимо
//     сервиса. Обход: App хранит payment.Store и читает им.
//  3. У AUTHZ НЕТ ОШИБКИ ОТКАЗА. entitlement отдаёт ErrDenied, authz —
//     только Decision.Allowed; единой таблице «ошибка → HTTP» нужна ошибка.
//     Обход: свои ErrAccessDenied и ErrItemNotOpen (errors.go).
//  4. ПРИЧИНА ОТКАЗА ENTITLEMENT НЕ ПЕРЕЖИВАЕТ ХУК. authz.Policy возвращает
//     bool, поэтому «купил и кончилось» (deny_expired) и «не покупал»
//     (deny_no_grant) снаружи неразличимы. Обход: различаем только сам факт
//     сужения — authz.ReasonPolicy.
//  5. У ENTITLEMENT.STORE.GRANT НЕТ ВРЕМЕНИ. Порт времени не передаёт, а
//     эталонная схема требует granted_at без DEFAULT now(). Обход: часы в
//     адаптере плюс GrantAt с явным моментом на транзакционном пути.
//  6. DEFAULTCOOKIECONFIG НЕ ГОДИТСЯ БЕЗ TLS. Она даёт имена с префиксом
//     __Host-, а он требует Secure, и на стенде по http конструктор паникует.
//     Обход: cookieConfig собирает конфигурацию руками (wiring.go).
//  7. PGTEST.SCHEMA ОТДАЁТ ПУЛ, А НЕ DSN. Приложение поднимает пул само, и
//     схему прогона приходится заводить руками. Обход: schemaDSN в тестах.
//  8. У KIT/CONFIG НЕТ НЕОБЯЗАТЕЛЬНОГО СЕКРЕТА. Secret с minLen ≤ 0 паникует,
//     а пароль SMTP при SMTP_AUTH=none не нужен вовсе. Обход: Optional, то
//     есть без типа-редактора.
