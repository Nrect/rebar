// Package shoppg — Postgres-адаптеры ПОТРЕБИТЕЛЯ: таблица пользователей,
// заказы, выдачи прав и загруженные файлы, плюс два порта, которые тулкит не
// реализует за него.
//
// Каталог называется *pg не для красоты: типы драйвера (pgx.Tx) законны
// только в адаптерах, и depguard в корне репозитория разрешает импорт pgx
// ровно по этому имени каталога (.golangci.yml, правило pgx-only-in-adapters).
// Ядро примера (пакет monolith) про pgx не знает вовсе.
//
// # Что здесь живёт и почему это нельзя было взять готовым
//
//  1. Tokens — порт auth/session.Tokens целиком. Пакет отдаёт половину
//     (authpg.Tokens: Insert, ConsumeRow, RevokeOfSubject, PurgeExpired), а
//     вторая половина — эффект в таблице ПОЛЬЗОВАТЕЛЕЙ и письмо в очереди —
//     видна только здесь. Образец в auth/authpg/doc.go.
//  2. Settler — хук paymentpg: заказ, право и событие outbox ложатся ТОЙ ЖЕ
//     транзакцией, что и книга платежей.
//  3. Entitlements — entitlement.Store. Адаптера у пакета нет, схема —
//     эталонная из entitlement/doc.go, скопирована в migrations как есть.
//  4. Identities — auth.Identities поверх shop_users.
//
// Безопасность:
//
//  1. ГРАНИЦА ОШИБКИ ОДНА НА ВСЕХ — postgres.Sanitize, а не своя копия. В
//     pgconn.PgError.Detail лежит «Failing row contains (…)»: хэш пароля,
//     нормализованный логин, сумма заказа. Держит TestStore_Error_DoesNotLeak.
//  2. КОНФЛИКТ РАЗБИРАЕТСЯ ПО ИМЕНИ ОГРАНИЧЕНИЯ. ux_shop_users_login — это
//     занятый логин; «любое 23505 — занятый логин» превратило бы чужой
//     конфликт в тихий ответ «принято».
//  3. ВРЕМЯ ПРИХОДИТ ПАРАМЕТРОМ. DEFAULT now() в доменных колонках нет:
//     иначе тесты на управляемых часах проверяют одно, а база пишет другое.
//  4. ПОРЯДОК БЛОКИРОВОК ПРОДОЛЖАЕТ ПОРЯДОК ТУЛКИТА. paymentpg держит
//     намерение → события → книгу → хук; хук берёт заказ → выдачу → outbox, и
//     свои строки в отсортированном порядке (paymentpg/doc.go, «Порядок
//     блокировок»). Два порядка обхода — это дедлок в момент оплаты.
//  5. ЛОГОВ ЗДЕСЬ НЕТ. Что записать о сбое, решает вызывающий: у него
//     request_id и правила ретеншна.
