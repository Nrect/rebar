// Package authzpg — назначения ролей в Postgres: таблица
// authz_role_assignments и authz.RoleSource поверх неё.
//
// Хранилища ролей в ядре authz нет и не будет: у одного потребителя роль —
// колонка в таблице пользователей, у другого таблица членства в организации,
// у третьего роли приходят из внешнего каталога. Этот адаптер — готовый
// четвёртый вариант для тех, кому подходит: кто, кому, кем, когда и до какого
// срока. Схема — публичный интерфейс наравне с портами (schema.sql,
// CONVENTIONS §9); миграцию применяет потребитель своим раннером, пакет её
// только проверяет (CheckSchema).
//
// Безопасность:
//
//  1. ИСТЁКШЕЕ НАЗНАЧЕНИЕ НЕ ДАЁТ ПРАВ С МОМЕНТА ИСТЕЧЕНИЯ, а не с момента
//     уборки: RolesOf фильтрует по сроку в самом запросе. Иначе доступ
//     «залипал» бы до ближайшего прогона PurgeExpired.
//  2. СБОЙ БАЗЫ — authz.ErrUnavailable, то есть 503, а не «ролей нет» и 403:
//     403 во время недоступной базы учит поддержку чинить права вместо базы.
//  3. СТРОКА ТАБЛИЦЫ НЕ ПОПАДАЕТ В ОШИБКУ. Граница — postgres.Sanitize, одна
//     на весь тулкит: от ошибки остаются SQLSTATE, Message и имя ограничения,
//     а Detail («Failing row contains …», вся строка с идентификатором
//     субъекта) отбрасывается. Своей копии этой проверки в пакете нет
//     намеренно — пять копий в пяти адаптерах разойдутся там, где
//     расхождение стоит утечки (ADR-0005).
//  4. ВРЕМЯ ПРИХОДИТ ПАРАМЕТРОМ. Ни DEFAULT now() в колонках, ни now() в
//     запросах: иначе тесты на управляемых часах проверяют одно, а база
//     пишет другое. Момент проверки срока берётся из часов адаптера
//     (SetClock).
//  5. ИМЯ ПЕРВИЧНОГО КЛЮЧА — КОНТРАКТ. Assign разбирает конфликт по ИМЕНИ
//     ограничения (ON CONFLICT ON CONSTRAINT), а не по SQLSTATE: в таблице
//     может появиться второй уникальный индекс потребителя, и «повторная
//     выдача» не должна обозначать чужой конфликт. Имя проверяет CheckSchema.
//  6. ФОРМА РОЛИ ЗЕРКАЛИТСЯ CHECK. Роль, вставленная мимо кода в другом
//     регистре, не совпала бы ни с одной ролью Config и молча не дала бы
//     прав; база отвергает её сразу.
//  7. СХЕМА НЕ ПРИМЕНЯЕТСЯ ПАКЕТОМ. CheckSchema проверяет и перечисляет все
//     расхождения одной ошибкой; автомиграция из библиотеки дала бы две
//     правды о схеме, потребовала DDL-прав у приложения и гонку реплик при
//     выкате.
//  8. АДАПТЕР НЕ ЛОГИРУЕТ. Ни субъекта, ни роли, ни того, кто её выдал:
//     журнал — дело потребителя, у которого есть его формат и его ретеншн.
//
// Чего в пакете нет (решения, не пробелы): внешнего ключа на таблицу
// пользователей (пакет не знает её имени — FK добавляет потребитель своей
// миграцией; subject_id здесь TEXT, потому что authz.Subject.ID — строка, и
// потребителю с UUID-ключами в этой миграции придётся привести тип), таблицы
// аудита выдач (у потребителя свой журнал, а вторая правда о том, кто кому
// что выдал, расходится с первой), кэша ролей (отзыв
// обязан действовать сразу — authz, «Безопасность», п. 5), HTTP-API и UI
// управления ролями, ролей по организациям и проектам (это фильтр данных
// потребителя, а не проверка прав).
//
// Уборка: PurgeExpired(ctx, before, limit) — истёкшие назначения. Ретеншн и
// расписание задаёт потребитель; обёрнутый в замыкание вызов подходит под
// сигнатуру scheduler.Job.Run.
