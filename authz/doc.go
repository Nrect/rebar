// Package authz — минимальный RBAC: субъект → роли → разрешения, реестр
// операций с запретом по умолчанию и хук политики, который может только
// сузить решение.
//
// Потребитель объявляет закрытые наборы разрешений и ролей в Config, отдаёт
// порт RoleSource (роли живут у него: колонка в таблице пользователей, своя
// таблица членства, внешний каталог) и реестр правил на операции своего API.
// Authorizer.Can отвечает на «вправе ли», Authorizer.CanOp — на «вправе ли
// выполнить эту операцию»; решение приходит с причиной из закрытого набора,
// годной меткой метрики. Роли читаются на каждую проверку, поэтому отзыв
// роли действует немедленно.
//
// Ось «вправе ли ты делать это» отделена от «кто ты» (auth) и «что тебе
// открыто по покупке» (entitlement) осознанно: слить их — значит притащить
// кэш и сроки покупки в проверку ролей и сделать отзыв роли медленным.
// Точка подключения entitlement — хук Policy. Проект и причины —
// docs/adr/0003-auth-authz-entitlement.md.
//
// ИДЕНТИФИКАТОР СУБЪЕКТА — СТРОКА, а не uuid.UUID: у одного потребителя это
// UUID, у другого — идентификатор внешнего каталога, и ради этого ядро
// обходится без единой внешней зависимости. Плата ложится на потребителя с
// UUID-ключами: приводить тип придётся у него, в том числе в миграции с
// внешним ключом на authz_role_assignments.subject_id (там колонка TEXT).
//
// Ядро — только stdlib; authzpg (назначения ролей в Postgres: pgx и граница
// ошибки postgres.Sanitize) и authzhttp (middleware, stdlib) — подпакеты со
// своим белым списком импортов.
//
// Безопасность:
//
//  1. ЗАПРЕТ ПО УМОЛЧАНИЮ. Операция без правила в реестре — отказ
//     (deny_unclassified), субъект без объявленных ролей — отказ, нулевой
//     Subject — отказ. Полноту реестра стережёт инвариант-тест потребителя
//     (authztest.RequireAllClassified), иначе забытая проверка выглядит как
//     обычный хендлер.
//  2. СБОЙ ИСТОЧНИКА РОЛЕЙ — НЕДОСТУПНОСТЬ, А НЕ ОТКАЗ В ПРАВАХ.
//     ErrUnavailable и 503; «у вас нет прав» во время упавшей базы — ложь
//     клиенту и утопленный инцидент: чинить будут права, а не базу.
//  3. POLICY ТОЛЬКО СУЖАЕТ. Хук зовётся лишь после «да» от RBAC, поэтому
//     ответить «да» вместо «нет» он не может по конструкции: баг в хуке
//     стоит потери доступа, а не раздачи прав. Ошибка хука — тоже
//     недоступность, а не отказ.
//  4. НЕИЗВЕСТНОЕ РАЗРЕШЕНИЕ — ОШИБКА ПРОГРАММИСТА, А НЕ ТИХИЙ ОТКАЗ.
//     Проверка разрешения не из Config.Permissions даёт ErrUnknownPermission
//     и причину error; опечатка в константе иначе пряталась бы среди
//     законных 403 до первой жалобы на пропавший доступ. Проверяется раньше
//     анонимности — иначе у анонима она невидима.
//  5. РОЛИ ЧИТАЮТСЯ НА КАЖДУЮ ПРОВЕРКУ. Кэша в пакете нет: отзыв роли обязан
//     действовать сразу. Кэшировать — осознанное решение потребителя внутри
//     его RoleSource, с его TTL и его риском «отозвали, а доступ ещё живёт».
//  6. В МЕТКИ НЕ ПОПАДАЮТ НИ СУБЪЕКТ, НИ РЕСУРС. Наружу отдаётся только
//     Decision.Reason из закрытого набора AllReasons; кто именно и над чем —
//     в аудит потребителя, где этому место. Иначе идентификаторы взрывают
//     кардинальность и уносят персональные данные в мониторинг.
//  7. PUBLIC ТРЕБУЕТ WHY. Публичная операция без обоснования — паника на
//     старте: «открыл и забыл» не проходит молча, причина лежит рядом с
//     правилом и читается на ревью.
//  8. ЦИКЛЫ НАСЛЕДОВАНИЯ ЛОВЯТСЯ В КОНСТРУКТОРЕ. В работе цикл дал бы
//     бесконечную рекурсию на первой проверке прав, то есть падение процесса
//     на запросе пользователя. Порядок ролей задаётся явным Config.Inherits,
//     а не порядком объявления констант.
//  9. КОНФИГУРАЦИЯ КОПИРУЕТСЯ В КОНСТРУКТОРЕ. Правка карт Config после New
//     не меняет прав в работающем процессе: иначе случайная запись в общую
//     карту раздавала бы доступ без единого коммита в коде проверки.
//
// Чего в пакете нет (решения, не пробелы):
//
//   - хранения политик и их языка: нужны роли, наследование и реестр
//     операций; casbin и OpenFGA остаются допустимыми адаптерами за хуком
//     Policy — в тот день, когда появятся права по отношениям;
//   - прав на конкретные объекты: это другая ось (entitlement) со своим
//     кэшем и сроками; здесь она подключается хуком, а не смешивается;
//   - управления ролями через API и UI: назначает роли потребитель, пакет
//     даёт только хранилище назначений (authzpg) и порт чтения;
//   - шаблонных разрешений (wildcard, «order.*»): набор закрытый, потому что
//     шаблон делает невозможным ответ на вопрос «кто может это сделать»;
//   - кэша ролей — см. пункт 5 «Безопасности»;
//   - разделения по арендаторам сверх Subject.Realm: мультитенантность — это
//     фильтр данных, а не проверка прав, и живёт в запросах потребителя;
//   - наблюдаемости (authzotel со счётчиком authz.checks{result,reason}) —
//     v0.2; Reason спроектирован закрытым уже сейчас именно ради неё.
