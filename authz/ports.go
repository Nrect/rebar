package authz

import "context"

// RoleSource — откуда берутся роли субъекта. РЕАЛИЗУЕТ ПОТРЕБИТЕЛЬ: у одного
// роль — колонка в таблице пользователей, у другого таблица членства, у
// третьего внешний каталог. Готовая реализация поверх таблицы назначений —
// authzpg.Store.
//
// Контракт:
//
//   - субъекта нет — пустой список и nil, а НЕ ошибка: «неизвестный» это
//     отказ по правилу (deny_no_role), а не сбой;
//   - сбой хранилища — любая ошибка; authz завернёт её в ErrUnavailable, и
//     потребитель ответит 503;
//   - роли, не объявленные в Config, разрешений не дают и ошибкой не
//     считаются: строка в базе переживает удаление роли из конфига, и
//     падать на ней значило бы устроить себе аварию из-за старой строки;
//   - РОЛИ ЧИТАЮТСЯ НА КАЖДУЮ ПРОВЕРКУ. Отзыв роли обязан действовать сразу;
//     кэш — осознанное решение потребителя внутри его реализации, с его TTL
//     и его риском «отозвали, а доступ ещё живёт».
//
// Времена внутрь не передаются: срок действия назначения — дело реализации
// (authzpg фильтрует по своим часам, см. authzpg.Store.SetClock).
type RoleSource interface {
	RolesOf(ctx context.Context, s Subject) ([]Role, error)
}

// Policy — хук потребителя, который может ТОЛЬКО СУЗИТЬ решение. Зовётся
// исключительно после того, как RBAC сказал «да»; ответить «да» там, где
// RBAC сказал «нет», хук не может по конструкции, поэтому баг в нём
// ограничен потерей доступа, а не раздачей прав.
//
// Это же штатная точка подключения второй оси: роль даёт разрешение «читать
// материал», а хук спрашивает у entitlement, куплен ли конкретный материал.
//
// Ошибка хука — недоступность (ErrUnavailable), а не отказ: если entitlement
// не ответил, мы не знаем ответа и не вправе объявлять его отрицательным.
// nil-хук допустим и означает «не сужать».
type Policy func(ctx context.Context, s Subject, p Permission, r Resource) (allow bool, err error)
