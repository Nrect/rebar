// Package authzhttp — middleware поверх authz на stdlib: проверка разрешения
// или операции перед хендлером.
//
// Отказ пишет ПОТРЕБИТЕЛЬ своей функцией Deny: формат ошибки принадлежит его
// API, а не пакету, и пакет не выбирает за него ни статус, ни тело. Пакет
// гарантирует другое — при отказе хендлер НЕ ЗОВЁТСЯ; Deny, забывший
// написать ответ, отдаёт пустой 200, и это дефект потребителя, а не раздача
// прав.
//
// Ожидаемое отображение исхода в статус (пишет его потребитель):
//
//	errors.Is(err, authz.ErrUnavailable)      → 503: решение не принято
//	errors.Is(err, authz.ErrUnknownPermission) → 500: ошибка программиста
//	d.Reason == authz.ReasonNoSubject          → 401: субъекта нет
//	иначе                                      → 403
//
// Безопасность:
//
//  1. ОТКАЗ НЕ ПУСКАЕТ ДАЛЬШЕ. Ни при отказе по правилу, ни при сбое
//     следующий хендлер не вызывается: обёртка, отдающая управление «на
//     всякий случай», отменяет весь пакет.
//  2. ПРОВОДКА ПРОВЕРЯЕТСЯ НА СТАРТЕ. Require с необъявленным разрешением и
//     RequireOp с неклассифицированной операцией — паника при сборке
//     маршрутов: иначе опечатка превращается в 403 на каждом запросе к
//     маршруту и находится жалобой пользователя.
//  3. НУЛЕВЫЕ ПОЛЯ Config — ПАНИКА. Отсутствующий Deny означал бы «отказ без
//     ответа», отсутствующий Subject — «все анонимы».
//  4. ПАКЕТ НЕ ЛОГИРУЕТ. Ни субъекта, ни маршрута, ни причины: журнал — дело
//     потребителя, у которого есть его формат и его ретеншн.
//
// Чего в пакете нет: разбора сессии и куки (это auth), извлечения субъекта из
// запроса (порт Subjects у потребителя: субъект кладёт в контекст тот, кто
// его аутентифицировал), проверок по ресурсу из URL (ресурс известен
// хендлеру, а не маршруту — там и зовётся Authorizer.CanOn), готовых тел
// ошибок.
