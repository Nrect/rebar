// Package authztest — двойники и стражи authz для тестов потребителя.
// Двойник — не мок: он ведёт себя как источник ролей, чтобы тест проверял
// исход, а не список вызовов; потокобезопасен (тесты идут под -race).
// Ошибки двойника отличимы от доменных. Сбой источника и отменённый контекст
// приходят в authz.ErrUnavailable, как у authzpg; аноним получает nil до всех
// проверок, как и там (ADR-0007, «Двойники»).
//
// Жители:
//
//   - MemRoles — authz.RoleSource в памяти: назначение и отзыв ролей, снимок
//     копией, SetErr для fail-closed тестов, отказ по отменённому контексту.
//   - RequireAllClassified — все операции API классифицированы в реестре:
//     забытая проверка роняет тест, а не тихо открывает хендлер.
//   - RequireNoDeadRules — правил на исчезнувшие операции нет: такое правило
//     врёт читателю о поверхности API.
package authztest
