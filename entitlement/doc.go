// Package entitlement — что открыто субъекту по покупке: снимок выдач с
// дедлайном поверх порта Store, запрет по умолчанию и честный статус на сбое.
//
// Потребитель отдаёт порт Store (выдачи живут у него: таблица покупок,
// развёрнутый в предметы заказ, внешний биллинг) и получает Service.Allows —
// «открыт ли этот предмет этому субъекту» с причиной из закрытого набора, и
// Service.Require — то же решение ошибкой для хендлера.
//
// Это ТРЕТЬЯ ось доступа, отдельная от «кто ты» (auth) и «вправе ли ты
// действовать» (authz): у неё другой срок жизни ответа — право живёт до даты
// и кэшируется, а роль отзывается мгновенно и читается на каждую проверку.
// Слить их — значит притащить кэш и сроки покупки в проверку ролей. Зависимости
// между пакетами нет и не будет; штатная точка подключения — хук authz.Policy.
// Проект и причины — docs/adr/0003-auth-authz-entitlement.md.
//
// Ядро — stdlib и uuid; кэш и объединение одинаковых запросов написаны здесь
// же на sync.Mutex и карте ожидающих, а не взяты библиотекой: это полторы
// сотни строк, и переносимость ядра дороже (ADR-0005).
//
// Безопасность:
//
//  1. ЗАПРЕТ ПО УМОЛЧАНИЮ. Нет записи о выдаче — нет доступа (deny_no_grant);
//     нулевой субъект — отказ с ОТДЕЛЬНОЙ причиной (deny_no_subject: это
//     дефект проводки потребителя, а не отказ по правилу), негодный предмет —
//     тоже отказ; оба без похода в хранилище. Несобранный сервис отвечает
//     отказом и ErrUnavailable, а не «разрешено». Нулевое значение Decision —
//     тоже отказ: забытое присваивание не открывает доступ.
//  2. СБОЙ ХРАНИЛИЩА — НЕДОСТУПНОСТЬ, А НЕ ОТКАЗ В ПРАВАХ. ErrUnavailable и
//     503, никогда ErrDenied и 403: «доступа нет» во время упавшей базы —
//     ложь клиенту и утопленный инцидент, потому что чинить будут права, а не
//     базу. Отдавать старый снимок на сбое пакет тоже не станет.
//  3. ДЕДЛАЙН СНИМКА НЕ ПЕРЕЖИВАЕТ ИСТЕЧЕНИЕ ПРАВА. Снимок годен до
//     min(now+TTL, ближайший будущий expires_at), поэтому доступ не «залипает»
//     после конца оплаченного срока — того самого случая, когда деньги вернули,
//     а материал остался открыт. Это главный инвариант пакета.
//  4. СРОК ПРОВЕРЯЕТСЯ ВТОРОЙ РАЗ НА ВЫДАЧЕ РЕШЕНИЯ. Дедлайн держится нашими
//     часами; повторная сверка Grant.Open переживает и расхождение часов, и
//     хранилище, вернувшее истёкшую строку. Отдельная причина deny_expired:
//     «купил и кончилось» и «не покупал» — разные разговоры с клиентом.
//  5. ВЫДАЧА И ОТЗЫВ СБРАСЫВАЮТ СНИМОК, и сброс идёт ПОСЛЕ записи в
//     хранилище. Иначе отзыв доживал бы до конца TTL, а сброс до записи
//     оставлял окно, в котором соседний запрос закреплял снимок без новой
//     выдачи.
//  6. ОДНА ЗАГРУЗКА НА ВОЛНУ ПАРАЛЛЕЛЬНЫХ ЗАПРОСОВ. Вход в популярный
//     материал не превращается в шторм к базе. Загрузка идёт с контекстом,
//     отвязанным от контекста запроса: ушедший клиент не отменяет загрузку,
//     которую ждут остальные, — и наоборот, ждущий с отменённым контекстом
//     уходит сразу, не дожидаясь чужой загрузки.
//  7. КЭШ ОГРАНИЧЕН СВЕРХУ. Ключ карты — идентификатор из внешнего мира;
//     Config.MaxSubjects обязателен, иначе запросы с разными
//     идентификаторами съедают память процесса. Промах кэша стоит одной
//     загрузки, а не ошибки: на решение содержимое кэша не влияет.
//  8. НИ СУБЪЕКТА, НИ ПРЕДМЕТА НЕ УХОДИТ В МЕТКИ И В ТЕКСТЫ ОШИБОК. Наружу
//     отдаётся Decision.Reason из закрытого набора AllReasons; кто именно и
//     что именно — в аудит потребителя, где этому место. Идентификаторы в
//     метке взрывают кардинальность и уносят персональные данные в
//     мониторинг, откуда их уже не удалить по требованию субъекта.
//  9. КОНФИГУРАЦИЯ ПРОВЕРЯЕТСЯ НА СТАРТЕ. New паникует на nil-порте и
//     негодном Config; флага, выключающего кэш или дедлайн, нет — режим
//     «всегда в базу» это TTL в наносекунду, а не поле SkipCache, которое
//     рано или поздно окажется включённым в проде.
//
// # Эталонная схема адаптера
//
// Адаптера в v0.1 нет (см. «Чего в пакете нет»), но схема, по которой он
// пишется, — часть контракта: имена таблиц с префиксом пакета, без имени
// схемы, без внешних ключей на таблицы потребителя, время параметром и без
// DEFAULT now() (CONVENTIONS §9).
//
//	-- Продукт — то, что покупают; предмет — то, что открывается покупкой.
//	-- Каталог живёт здесь только затем, чтобы покупка разворачивалась в
//	-- выдачи; иерархий, пробных периодов и скидок в нём нет.
//	CREATE TABLE entitlement_products (
//	    id         uuid PRIMARY KEY,
//	    code       text NOT NULL,
//	    CONSTRAINT ux_entitlement_products_code UNIQUE (code)
//	);
//
//	CREATE TABLE entitlement_product_items (
//	    product_id uuid NOT NULL REFERENCES entitlement_products (id) ON DELETE CASCADE,
//	    item_id    text NOT NULL,
//	    PRIMARY KEY (product_id, item_id)  -- без имени: код его не называет
//	);
//
//	-- Выдача. subject_id без внешнего ключа: имени таблицы пользователей
//	-- пакет не знает, FK добавляет потребитель своей миграцией.
//	CREATE TABLE entitlement_grants (
//	    subject_id uuid        NOT NULL,
//	    item_id    text        NOT NULL,
//	    expires_at timestamptz,           -- NULL — бессрочно
//	    granted_at timestamptz NOT NULL,  -- момент из Store.Grant(…, at)
//	    source     text        NOT NULL,  -- заказ, промо, ручная выдача
//	    CONSTRAINT ux_entitlement_grants_subject_item PRIMARY KEY (subject_id, item_id)
//	);
//
// Store.Open читается префиксом первичного ключа
// (WHERE subject_id = $1 AND (expires_at IS NULL OR expires_at > $2)),
// поэтому отдельного индекса не нужно. Граница строгая: момент истечения уже
// закрыт — та же граница, что у Grant.Open. Повторная выдача продлевает срок
// (INSERT … ON CONFLICT ON CONSTRAINT ux_entitlement_grants_subject_item
// DO UPDATE), а не удваивает строку: повтор покупки — штатное событие; вместе
// со сроком обновляется и granted_at.
//
// ВРЕМЯ ПАРАМЕТРОМ — ЭТО ПРОВЕРЯЕМОЕ ТРЕБОВАНИЕ, а не пожелание: момент едет в
// Store.Grant параметром at, а Open возвращает его в Grant.GrantedAt. Без
// обратного чтения реализация с DEFAULT now() или со своими часами проходила
// бы весь контрактный набор — расхождение вылезло бы в колонке, по которой
// режут отчёты, и уже неисправимой. Держит сценарий набора «сохранён
// переданный момент, а не „примерно сейчас“».
//
// ИМЯ ДАЁТСЯ ТОМУ, ЧТО АДРЕСУЕТ КОД. Первичный ключ выдач адресуется
// (ON CONFLICT на продление), поэтому имя ему нужно и оно контракт; ключ
// entitlement_product_items не называет никто, и безымянный он честнее —
// имя без потребителя пришлось бы тащить вечно. Префикс ux_ у именованных
// PRIMARY KEY — общий с тулкитом (ux_payment_events_dedup).
//
// Чего в пакете нет (решения, не пробелы):
//
//   - pg-адаптера: у первого потребителя свой уже есть, а магазину пакет к
//     старту не нужен. Схема выше написана ровно затем, чтобы адаптер писался
//     за полдня, когда понадобится, — и не была придумана заново;
//   - иерархий продуктов, пробных периодов и скидок: это цена и каталог,
//     то есть payment и домен потребителя. Здесь — только «открыто до»;
//   - отзыва по расписанию: истёкшая выдача перестаёт давать доступ в момент
//     истечения, а не в момент уборки, поэтому фоновая чистка хранилища
//     ничего не решает и делает вид, что решает. Run убирает только негодные
//     снимки из памяти;
//   - долей, квот и счётчиков использования («три просмотра»): это состояние,
//     которое надо писать на каждый доступ, — другая задача с другими
//     гарантиями, и она не кэшируется;
//   - истории выдач и аудита: журнал ведёт потребитель, у него же лежат
//     основания (заказ, возврат, промо);
//   - наблюдаемости (entitlementotel со счётчиком
//     entitlement.checks{result,reason} и попаданиями кэша) — v0.2; Reason
//     спроектирован закрытым уже сейчас именно ради неё.
