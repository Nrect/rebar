// Package entitlementtest — двойник хранилища прав и контрактный набор для
// тестов потребителя.
//
// Двойник — не мок: он ведёт себя как хранилище (выдача по предмету одна,
// повтор продлевает срок, истёкшая не отдаётся, наружу уходит копия), чтобы
// тест проверял исход, а не список вызовов. Потокобезопасен — тесты идут под
// -race; ошибки двойника задаются полем и отличимы от доменных.
//
// Пакет СОБИРАЕТСЯ БЕЗ ТЕСТОВЫХ ЗАВИСИМОСТЕЙ: его файлы не _test.go, их
// компилирует потребитель, и testify здесь означал бы testify в go.mod
// каждого, кто взял двойник. Отсюда же голый testing в контрактном наборе
// (CONVENTIONS §3).
//
// Жители:
//
//   - MemStore — entitlement.Store в памяти: выдача, отзыв, фильтр по сроку,
//     счётчик загрузок Opens и задержка Hold/Release, которой тест собирает
//     волну параллельных запросов на холодном кэше.
//   - RunStoreSuite — контрактный набор порта: один и тот же для двойника и
//     для любого адаптера, иначе они разойдутся, а тесты потребителя,
//     написанные на двойнике, будут зелены при сломанном проде.
