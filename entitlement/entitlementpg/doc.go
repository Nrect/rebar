// Package entitlementpg — выдачи в Postgres: таблица entitlement_grants и
// entitlement.Store поверх неё.
//
// Порт Store реализует потребитель, и у многих выдачи уже живут в своей
// таблице; этот адаптер — готовый вариант для остальных: кому, что, до какого
// срока и когда выдано. Схема — миграции goose в каталоге migrations/, их
// отдаёт Migrations(); накатывает раннер потребителя со своей таблицей версий
// entitlement_schema_version (ADR-0011). CheckSchema на старте сверяет схему,
// но не применяет её. Поведение порта держит тот же контрактный набор, что и
// двойник, — entitlementtest.RunStoreSuite.
//
// Безопасность:
//
//  1. ИСТЁКШАЯ ВЫДАЧА НЕ ОТДАЁТСЯ С МОМЕНТА ИСТЕЧЕНИЯ: граница expires_at > now
//     стоит в самом запросе, та же, что у Grant.Open, и уборки не ждёт.
//  2. ВРЕМЯ ПРИХОДИТ ПАРАМЕТРОМ: ни DEFAULT now(), ни now() в запросах, часов
//     нет; Open отдаёт сохранённый granted_at, иначе этого не проверить.
//  3. ПОТОЛОК ПРЕДМЕТА ЗЕРКАЛИТСЯ CHECK: выдачи пишут и мимо ядра (хук
//     платежей), а пустой предмет вёл бы себя как шаблон. Нарушение — по
//     имени ограничения, entitlement.ErrInvalidGrant.
//  4. СТРОКА ТАБЛИЦЫ НЕ ПОПАДАЕТ В ОШИБКУ: граница postgres.Sanitize, одна на
//     тулкит, отбрасывает Detail с идентификатором субъекта.
//  5. СБОЙ БАЗЫ — entitlement.ErrUnavailable, то есть 503, а не «ничего не
//     куплено» и 403.
//  6. ИМЕНА ОГРАНИЧЕНИЙ — КОНТРАКТ: повтор выдачи встаёт на первичный ключ по
//     имени и не роняет транзакцию потребителя; имена сверяет CheckSchema.
//  7. СХЕМА НЕ ПРИМЕНЯЕТСЯ ПАКЕТОМ: автомиграция дала бы две правды о схеме,
//     DDL-права у приложения и гонку реплик при выкате.
//  8. АДАПТЕР НЕ ЛОГИРУЕТ: кто и что купил — дело журнала потребителя.
//
// Чего в пакете нет (решения, не пробелы):
//
//   - раннера миграций: Migrations() накатывает раннер потребителя, причины —
//     пункт 7 выше;
//   - таблиц каталога: порт их не пишет, а Down адаптера снёс бы каталог
//     потребителя; мигрирует его он сам (entitlement, «Эталонная схема
//     адаптера»);
//   - внешнего ключа на таблицу пользователей: её имени пакет не знает, FK
//     добавляет потребитель своей миграцией;
//   - уборки истёкших выдач: доступ закрывает запрос в момент истечения, а
//     хранить ли строку дальше — ретеншн и история покупок потребителя;
//   - индекса по сроку: Open читается префиксом первичного ключа;
//   - часов и SetClock: момент — параметр порта;
//   - кэша: снимок с дедлайном держит entitlement.Service;
//   - наблюдаемости: entitlementotel — v0.2, как у ядра.
