package entitlement

import (
	"context"
	"time"

	"github.com/google/uuid"
)

// Store — где лежат выдачи. РЕАЛИЗУЕТ ПОТРЕБИТЕЛЬ: у одного это таблица
// покупок, у другого — развёрнутый в предметы заказ, у третьего внешний
// биллинг. Готовый pg-адаптер — entitlementpg; эталонная схема — в doc.go.
//
// Контракт:
//
//   - Open отдаёт выдачи, ОТКРЫТЫЕ В МОМЕНТ now: истёкшие не возвращаются
//     (expires_at IS NULL OR expires_at > now — граница строгая, момент
//     истечения уже закрыт). Время приходит параметром, часов у хранилища
//     нет: иначе тест на SetClock проверяет одно, а база пишет другое
//     (CORRECTNESS, закон 8);
//   - выдач нет — ПУСТОЙ СПИСОК И nil, а не ошибка: «ничего не куплено» это
//     отказ по правилу, а не сбой;
//   - Grant предмета вне 1..MaxItemIDLen БАЙТ отвечает ErrInvalidGrant, и
//     выдачи не остаётся: выдачи пишут и мимо сервиса (хук платежей в той же
//     транзакции), а пустой предмет вёл бы себя как шаблон. Байты, а не
//     символы: у базы граница — octet_length;
//   - любая другая ошибка означает «ответа нет»: сервис завернёт её в
//     ErrUnavailable, и потребитель ответит 503, а не 403;
//   - Grant повторной выдачей того же предмета НЕ УДВАИВАЕТ строку и НИКОГДА
//     НЕ СОКРАЩАЕТ срок: бессрочная с любой стороны даёт бессрочную, из двух
//     сроков остаётся поздний. Покупки, доехавшие не в том порядке (повтор
//     вебхука, redrive), не имеют права отнять оплаченный доступ;
//   - момент выдачи приходит ПАРАМЕТРОМ at и ложится в granted_at; часов у
//     хранилища нет по той же причине, что и у Open. Поле g.GrantedAt на
//     записи ИГНОРИРУЕТСЯ, а Open обязан заполнять его сохранённым моментом:
//     иначе требование эталонной схемы «время параметром, не DEFAULT now()»
//     не проверяется ничем. Повторная выдача обновляет его ВСЕГДА, даже когда
//     срок не сдвинулся: он значит «когда выдавали последний раз»;
//   - Revoke несуществующей выдачи — не ошибка: отзыв идемпотентен, иначе
//     повтор отмены платежа падал бы у потребителя;
//   - срез, отданный из Open, принадлежит вызывающему: реализация не имеет
//     права держать на него ссылку.
type Store interface {
	Open(ctx context.Context, subjectID uuid.UUID, now time.Time) ([]Grant, error)
	Grant(ctx context.Context, subjectID uuid.UUID, g Grant, at time.Time) error
	Revoke(ctx context.Context, subjectID uuid.UUID, itemID string) error
}
