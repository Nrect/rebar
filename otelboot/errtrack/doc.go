// Package errtrack — трекер ошибок, совместимый с Sentry (sentry.io,
// GlitchTip). Отвечает на вопрос «эта паника пятая за час или первая?»,
// который логи сами по себе не закрывают.
//
// Выключен, пока не задан DSN: Init без DSN — no-op, все функции пакета
// дешёвые пустышки, ошибки нет. Включение — конфигурацией, без правки кода.
// Точки врезки: recover-middleware (CapturePanic) и логгер (WrapLogger, где
// каждая запись уровня Error уходит событием).
//
//	flush, err := errtrack.Init(os.Getenv("SENTRY_DSN"), "production", buildVersion)
//	defer flush(ctx)
//	log := errtrack.WrapLogger(slog.Default())
//
// Безопасность:
//
//  1. DSN НЕ ПОПАДАЕТ НИ В ЛОГ, НИ В ОШИБКУ. В DSN лежит ключ проекта, а
//     ошибка разбора у sentry печатает URL целиком; Init возвращает свою
//     ошибку без адреса.
//  2. БЕЗ DSN — ТИШИНА, А НЕ ОШИБКА: dev и тесты не должны требовать трекер и
//     не должны сыпать предупреждениями о его отсутствии.
//  3. СОБСТВЕННЫЙ ХАБ, НЕ sentry.CurrentHub(): пакет не трогает глобальное
//     состояние sentry, и потребитель со своим sentry.Init продолжает
//     работать как раньше.
//  4. SkipKey ГАСИТ ДУБЛЬ: паника уходит через CapturePanic (богаче и
//     группируется правильно), а её же Error-лог с этим атрибутом второго
//     события не создаёт.
//  5. СТЕК ПАНИКИ ПЕРЕДАЁТСЯ АРГУМЕНТОМ: собственный стек sentry снимается
//     после разворачивания и указывает на middleware, а не на место паники.
//
// Чего в пакете нет (решения, не пробелы): трейсинга и профилирования Sentry
// (наблюдаемость — otelboot), breadcrumbs и user-контекста (в них легко
// утекают персональные данные), собственной очереди и ретраев (за буфер и
// отправку отвечает sentry-go), глобального Enabled() (потребитель знает,
// передал ли он DSN).
