// Package otelboot — бутстрап наблюдаемости: один Start поднимает провайдер
// метрик с экспортёром Prometheus, обработчик /metrics, build_info и
// провайдер трейсов OTLP/HTTP (noop, пока не задан endpoint).
//
// Это boot-клей, а не доменный пакет: портов и двойников здесь нет, вся
// зависимость от otel сосредоточена в одном месте, чтобы её не было в
// остальном коде. Имя сервиса, версия и окружение — поля Config, так что
// пакет переносится в чужой проект без правок.
//
//	p, err := otelboot.Start(ctx, otelboot.Config{
//		ServiceName: "shop", Version: buildVersion, Commit: buildCommit,
//		Environment: "production", TracesEndpoint: os.Getenv("OTEL_TRACES_ENDPOINT"),
//		RuntimeMetrics: true, SetGlobals: true,
//	})
//	defer p.Shutdown(context.Background())
//	go http.ListenAndServe("127.0.0.1:9090", p.Metrics) // отдельный порт, см. пункт 1
//
// Трекер ошибок (Sentry-совместимый) — подпакет errtrack.
//
// Безопасность:
//
//  1. /metrics ОТДАЁТСЯ БЕЗ АВТОРИЗАЦИИ. Providers.Metrics вешает потребитель —
//     на отдельный порт во внутренней сети, не на публичный роутер: метрики
//     рассказывают версию сборки, объём трафика и внутренние имена.
//  2. ИМЯ ПРОДУКТА НЕ ЗАШИТО: service.name — Config.ServiceName. Константа
//     сделала бы пакет копией одного проекта, а телеметрию двух сервисов —
//     неразличимой.
//  3. NOOP НЕ ТРОГАЕТ ЧУЖИЕ ГЛОБАЛИ. otel.SetMeterProvider ставится только по
//     Config.SetGlobals, а otel.SetTracerProvider и W3C-пропагаторы — ещё и
//     только для реального провайдера. Иначе тест или второй инстанс молча
//     затирал бы разводку потребителя.
//  4. SHUTDOWN ОБЯЗАТЕЛЕН И ИДЕМПОТЕНТЕН: он сбрасывает батч спанов, а без
//     этого теряются как раз последние трейсы перед выходом — те, ради
//     которых чаще всего и смотрят в трейсинг.
//  5. SampleRatio NaN-SAFE. NaN проходит любое сравнение как ложь и в
//     TraceIDRatioBased даёт молча пустые трейсы; здесь он отвергается на
//     старте вместе с бесконечностями и значениями вне (0,1].
//  6. TracesEndpoint ПРОВЕРЯЕТСЯ САМИМ ПАКЕТОМ: otlptracehttp на неразобранном
//     URL молча оставляет умолчание localhost:4318 — трейсинг выглядел бы
//     живым и никуда не уезжал. Сам адрес в текст ошибки не попадает: в URL
//     коллектора может оказаться basic-auth.
//  7. СОБСТВЕННЫЙ РЕЕСТР Prometheus, не DefaultRegisterer: на глобальном два
//     инстанса в одном процессе (тесты, стенд рядом с бэкендом) падают на
//     дублирующей регистрации.
//
// Чего в пакете нет (решения, не пробелы): экспорта логов (логи собирает
// агент с stdout, второй канал — вторая точка отказа), OTLP-push метрик
// (коллектор сам ходит за /metrics), профилирования, трейсинга Sentry
// (errtrack шлёт только ошибки), авторизации на /metrics (её место — сеть и
// порт потребителя, см. пункт 1).
