// MaxIdempotencyKeyLen — потолок длины ключа в байтах. Без потолка враждебный
// клиент набивает уникальный индекс мегабайтными ключами, и деградирует не он,
// а таблица платежей.
const MaxIdempotencyKeyLen = 200

// NormalizeKey — ЕДИНСТВЕННАЯ точка нормализации ключа во всём пакете.
//
// Вызывается первой строкой каждого публичного метода, принимающего ключ
// (Start, Capture, Cancel, Refund) — до пробы, до сигнатуры, до записи и до
// уникального индекса. Ни транспорт, ни адаптер, ни Store ключ не трогают:
// контракт Store прямо говорит «ключ приходит уже нормализованным».
//
// Без единой точки " k" и "k " — разные ключи: они разъезжаются мимо
// уникального индекса, и двойной клик становится двойным списанием.
func NormalizeKey(raw string) (string, error) {
	key := strings.TrimSpace(raw)
	if key == "" {
		return "", fmt.Errorf("%w: key is empty", ErrIdempotencyKeyInvalid)
	}
	if len(key) > MaxIdempotencyKeyLen {
		return "", fmt.Errorf("%w: key is %d bytes, max is %d",
			ErrIdempotencyKeyInvalid, len(key), MaxIdempotencyKeyLen)
	}
	// Проверяем UTF-8 отдельно: битый байт декодируется в U+FFFD, а он
	// печатный — одна лишь проверка на печатность пропустила бы мусор в ключ,
	// который потом поедет в сравнение байтов и в лог.
	if !utf8.ValidString(key) {
		return "", fmt.Errorf("%w: key is not valid UTF-8", ErrIdempotencyKeyInvalid)
	}
	for _, r := range key {
		if !unicode.IsPrint(r) {
			return "", fmt.Errorf("%w: key contains a non-printable rune", ErrIdempotencyKeyInvalid)
		}
	}
	return key, nil
}

// startFingerprint — каноническая сигнатура покупки. Отвечает ровно на один
// вопрос: «тот же ключ — та же операция?».
//
// sha256, а не сырые поля: строка не для реконструкции сделки (для неё есть сам
// intent), дайджеста достаточно, и он фиксированной длины — индекс не пухнет.
//
// Кодирование канонично: сырые 16 байт uuid, big-endian int64 у чисел и
// ПРЕФИКС ДЛИНЫ перед каждой переменной секцией. Префиксы обязательны: без них
// ("ab","c") и ("a","bc") склеиваются в один дайджест, и покупка ДРУГОГО товара
// выглядела бы законным повтором — клиент получил бы чужую ссылку на оплату
// вместо своей.
//
// В СИГНАТУРУ ВХОДИТ ВЕСЬ СОСТАВ, а не только итог. Итог не определяет заказ:
// {A 699 + B 499} и {B 699 + A 499} дают одну и ту же 1198, а обязывают к
// разному, — и при сигнатуре по итогу второй заказ вернулся бы клиенту как
// «законный повтор» первого, то есть ссылкой на оплату ЧУЖОГО состава. Число
// позиций пишется перед ними по той же причине, что и префиксы длины:
// переменная секция без префикса склеивается с соседней.
//
// Что НЕ входит и почему:
//   - return_url — презентационный параметр; включив его, мы превратили бы
//     безобидный ретрай из другой вкладки в жёсткий 409;
//   - описание платежа и Title позиции — то же самое, плюс они зависят от
//     локали витрины, а деньги от неё не зависят;
//   - чек — он производен от суммы и адресата, а сумма в сигнатуре уже есть:
//     смена почты в профиле между двумя нажатиями «Оплатить» не должна
//     превращать законный повтор в 409;
//   - сам ключ идемпотентности — он скоуп, а не содержимое операции;
//   - время — сигнатура обязана совпасть между попытками, разделёнными
//     секундами.
func startFingerprint(req StartRequest, provider ProviderName) []byte {
	var b bytes.Buffer
	b.Write(req.PayerID[:])
	writeLenPrefixed(&b, req.Reference)
	writeLenPrefixed(&b, req.Currency)
	writeLenPrefixed(&b, string(provider))
	writeLenPrefixed(&b, string(req.Method))
	// Одностадийность входит в сигнатуру: холд и списание — разные операции над
	// теми же деньгами, и повтор с другим значением обязан быть 409, а не
	// ссылкой на платёж не того рода.
	writeInt64(&b, boolToInt64(req.AutoCapture))
	writeInt64(&b, req.AmountMinor)
	writeInt64(&b, int64(len(req.Items)))
	for _, item := range req.Items {
		writeInt64(&b, int64(item.Position))
		writeLenPrefixed(&b, item.ProductID)
		writeInt64(&b, item.AmountMinor)
		writeInt64(&b, int64(item.Quantity))
	}

	sum := sha256.Sum256(b.Bytes())
	return sum[:]
}

func writeLenPrefixed(b *bytes.Buffer, s string) {
	writeInt64(b, int64(len(s)))
	b.WriteString(s)
}

// writeInt64 — канонический big-endian.
//
// binary.Write, а не ручной cast в uint64: кодирование то же, но без
// конверсии знакового в беззнаковое, которую линтер справедливо считает
// переполнением. Ошибку игнорируем осознанно: запись в bytes.Buffer не может
// не удаться — он растёт, пока есть память, и паникует, если её нет.
func writeInt64(b *bytes.Buffer, v int64) {
	_ = binary.Write(b, binary.BigEndian, v)
}

func boolToInt64(v bool) int64 {
	if v {
		return 1
	}
	return 0
}

// sameOperation — законный ли это повтор.
//
// Сравнение обычным bytes.Equal, а не constant-time: сигнатура не секрет.
// Она детерминированно выводится из параметров, которые вызывающий и так знает
// (он их только что прислал), поэтому подбирать её по таймингу нечего и незачем.
//
// Пустая сохранённая сигнатура законным повтором НЕ считается. Амнистия
// «пустая — значит старая строка» была бы fail-open, а цена ошибки — адаптер,
// потерявший колонку в SELECT или в INSERT, превращает ЛЮБОЙ чужой запрос с тем
// же ключом в законный повтор, и клиент получает ссылку на оплату ЧУЖОГО заказа
// по чужой цене. Отказ при этом незаметный: юнит-тесты на двойнике, который
// поле не теряет, остаются зелёными. Пустая сигнатура даёт 409, то есть громко.
func sameOperation(stored, current []byte) bool {
	return bytes.Equal(stored, current)
}

// providerKey — ключ идемпотентности, который уезжает ПРОВАЙДЕРУ при создании
// платежа.
//
// Выводится из НАШЕГО id намерения, а не из клиентского ключа. Клиентский ключ
// уникален лишь в пределах одного плательщика: два разных покупателя,
// приславшие "buy-1", столкнулись бы в пространстве ключей провайдера, и второй
// получил бы платёж первого.
//
// Префикс из Config: один магазин провайдера обслуживает несколько наших сред
// (прод, стенд) и несколько потребителей, и без префикса их id намерений живут
// в одном пространстве ключей.
//
// Производный ключ детерминирован, глобально уникален и переживает рестарт —
// на этом и держится дозавершение: повтор CreatePayment после падения возвращает
// ТОТ ЖЕ платёж, а не второй.
func providerKey(prefix string, intentID uuid.UUID) string {
	return prefix + ":intent:" + intentID.String()
}

// providerCaptureKey — ключ списания холда. Выводится только из намерения:
// зачисление на намерение одно (частичный уникальный индекс книги), значит его
// id и достаточно, а повтор после сбоя связи не должен списать холд дважды.
func providerCaptureKey(prefix string, intentID uuid.UUID) string {
	return prefix + ":capture:" + intentID.String()
}

// providerCancelKey — ключ снятия холда, по той же причине выводится из
// намерения.
func providerCancelKey(prefix string, intentID uuid.UUID) string {
	return prefix + ":cancel:" + intentID.String()
}

// providerRefundKey — ключ возврата, который уезжает провайдеру.
//
// Выводится из намерения И из клиентского ключа, потому что частичных возвратов
// на одно намерение бывает несколько: ключ обязан быть ОДНИМ на все попытки
// вернуть ЭТИ деньги (иначе повтор после сбоя связи двигает деньги второй раз) и
// РАЗНЫМ для второго частичного возврата (иначе провайдер вернул бы по тому же
// ключу первую сумму).
//
// Клиентский ключ хешируется, а не подставляется: он приходит из внешнего мира,
// бывает длиной в 200 байт и попадает в чужую систему — там ему хватит
// фиксированных 64 символов hex.
//
// Плата за такой выбор — окно, в котором наша сумма и уже выполненный
// провайдером возврат расходятся (провайдер вернул, книга не записала, повтор
// пришёл с другой суммой). Закрывает окно не ключ, а сверка ответа:
// см. checkRefundEcho.
func providerRefundKey(prefix string, intentID uuid.UUID, key string) string {
	return prefix + ":refund:" + intentID.String() + ":" + hashKey(key)
}

// captureLedgerKey — ключ строки зачисления в книге. Детерминирован: два
// прохода одного события дают один ключ, и вторая строка не вставится даже
// мимо дедупа событий.
func captureLedgerKey(intentID uuid.UUID, providerEventID string) string {
	return "capture:" + intentID.String() + ":" + providerEventID
}

// refundLedgerKey — ключ компенсирующей строки: намерение плюс хеш клиентского
// ключа.
//
// Именно клиентского, а не события провайдера: возвратов на одно зачисление
// несколько, и различать их обязано намерение оператора («вернуть ещё 500»), а
// не id, который провайдер придумает уже после того, как деньги ушли. Тот же
// ключ с другой суммой — 409 по отпечатку (см. Service.Refund).
func refundLedgerKey(intentID uuid.UUID, key string) string {
	return "refund:" + intentID.String() + ":" + hashKey(key)
}

// hashKey — hex sha256 клиентского ключа: фиксированная длина и никакого
// клиентского текста в ключах, которые уезжают провайдеру и ложатся в индекс.
func hashKey(key string) string {
	sum := sha256.Sum256([]byte(key))
	return hex.EncodeToString(sum[:])
}
