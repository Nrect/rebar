// Package paymentotel — наблюдаемость платежей на OpenTelemetry metric API:
// декоратор payment.Provider со счётчиком
// payment_provider_calls{provider,type,result}, payment.Observer со счётчиком
// payments{op,reason} и Gauges — два observable gauge, читающих снимок сверки.
//
// Ядро метрик не пишет и otel не импортирует (CONVENTIONS §6); зависимость
// живёт здесь. Meter — rebar.payment. Собирается так:
//
//	p, err := paymentotel.Wrap(provider, meter)
//	obs, err := paymentotel.NewObserver(meter)
//	svc := payment.NewService(store, p, obs, cfg)
//	g, err := paymentotel.NewGauges(meter)
//	// после каждого прогона сверки:
//	stuck, err := svc.CountStuckPending(ctx)
//	drift, err := svc.Drift(ctx, 1000)
//	g.Set(paymentotel.Snapshot{Stuck: stuck, Drift: drift})
//
// Инструменты (имена и единицы — часть контракта, на них стоят алерты
// потребителя; ADR-0004, «Наблюдаемость и алерты»):
//
//	| Метрика                                      | Тип          | Что |
//	|----------------------------------------------|--------------|-----|
//	| payments{op,reason}                          | counter      | исход каждой операции сервиса; все пары AllOps × AllReasons заводятся нулём |
//	| payment_provider_calls{provider,type,result} | counter      | вызовы провайдера: ok / rejected (ответил определённо) / error (ответа нет) |
//	| payment_intents_stuck                        | gauge        | незакрытые намерения старше Config.StalePendingAfter — деньги в подвешенном состоянии |
//	| payment_drift{kind}                          | gauge        | расхождения книг по роду из payment.AllDriftKinds |
//	| cron_*{job="payments_reconcile"}             | из scheduler | прогоны сверки, длительность, последний успех |
//
// Prometheus-экспортёр припишет счётчикам _total. Алерты:
//
//   - «деньги на закрытом намерении» — рост payments_total{reason="status_conflict"},
//     порог 1;
//   - «провайдер назвал не ту сумму» — рост payments_total{reason="amount_mismatch"},
//     порог 1;
//   - «расхождение книг» — payment_drift > 0, порог 1, разбор обязателен;
//   - «намерения зависли» — payment_intents_stuck > 0 пятнадцать минут;
//   - «провайдер недоступен» — доля result="error" по provider выше собственной
//     базовой доли за прошлую неделю пять минут: порог зависит от трафика
//     потребителя, и число в переносимой библиотеке стало бы чужим порогом;
//   - «интеграция сломана» — доля result="rejected" по type около 100 % дольше
//     N минут: это не отказы клиентов, а сломанный ключ или адрес (N — по
//     трафику: при редких вызовах один отказ тоже даёт 100 %);
//   - «сверка умерла» — time() − cron_last_success_timestamp_seconds{job="payments_reconcile"}
//     больше двух интервалов.
//
// Безопасность:
//
//  1. МЕТКИ — ЗАКРЫТЫЕ НАБОРЫ: op из payment.AllOps, reason из
//     payment.AllReasons, type из AllCallTypes, result из AllResults, kind из
//     payment.AllDriftKinds; provider — payment.ProviderName, форму
//     [a-z0-9_]{1,32} проверяет NewService, и рядов столько, сколько
//     провайдеров. Сумма, валюта, id намерения, ссылка заказа и текст ошибки
//     меткой не становятся: это кардинальность и данные в мониторинге, откуда
//     их не удалить по требованию субъекта.
//  2. ДЕКОРАТОР НЕ ЧИТАЕТ ЗАПРОС И НИЧЕГО НЕ ЛОГИРУЕТ: из вызова берутся метод
//     и класс ошибки; тело вебхука, чек и ключи уходят в next и никуда больше.
//  3. ОТВЕТ И ОШИБКА NEXT — БЕЗ ИЗМЕНЕНИЙ: сервис ветвится по errors.Is, и
//     обёртка, потерявшая ErrUnavailable, превратила бы 503 на вебхук в 400 —
//     провайдер больше не пришёл бы с оплатой.
//  4. NAME() ПРОБРАСЫВАЕТСЯ И НЕ СЧИТАЕТСЯ: по имени сервис узнаёт провайдера
//     в каждом событии и пишет его в намерение — подменённое имя сделало бы
//     каждое событие чужим; вызова провайдера за Name нет.
//  5. rejected И error НЕ СВОДЯТСЯ, И ГРАНИЦА — ТА ЖЕ, ЧТО У СЕРВИСА: отказ
//     провайдера — обычная работа, его молчание — инцидент; rejected ровно
//     там, где сервис не отдаёт ErrUnavailable. Неизвестная ошибка — error.
//  6. ГЕЙДЖИ ЧИТАЮТ СНИМОК, А НЕ ХОДЯТ В БАЗУ НА КАЖДЫЙ SCRAPE: Set зовёт
//     потребитель после сверки. Записи Drift не хранятся, только числа по
//     роду: в записи плательщик и ссылка заказа.
//  7. РОД ВНЕ НАБОРА НЕ ТЕРЯЕТСЯ И МЕТКОЙ НЕ СТАНОВИТСЯ: такие записи идут
//     рядом payment_drift без kind — алерт горит, а строка стора в метку не
//     попадает.
//  8. FAIL CLOSED НА СБОРКЕ: nil-порт и nil-метр — паника на старте; ошибка
//     создания инструмента возвращается — метрик у потребителя может не быть,
//     а платежи нужны.
//  9. РЯДЫ ИСХОДОВ РОЖДАЮТСЯ НУЛЁМ: ряд, появившийся сразу единицей,
//     increase() не видит, а у двух денежных алертов порог 1 — первое событие
//     и есть тревога.
//
// Чего нет (решения, не пробелы): гистограммы длительности — долгий вызов
// режет таймаут адаптера, и он приходит в счётчик как error; трейсов — вызов
// идёт под span'ом ручки вебхука или задания сверки потребителя;
// автообновления снимка — Gauges в базу не ходит; выбора имён инструментов —
// на них стоят чужие алерты.
package paymentotel
