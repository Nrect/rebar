// Package prorate — пропорция за неиспользованную часть срока: чистые функции
// без типов ядра payment и без единой зависимости, кроме stdlib.
//
// Нужен там, где закон или оферта дают отказаться от услуги в любое время с
// оплатой фактически оказанной части (в РФ — ст. 32 ЗоЗПП). Сумму возврата
// считает потребитель и передаёт её в payment.Refund явно: правило «сколько
// вернуть» — политика продавца, а не платёжного пакета.
//
// Безопасность:
//
//  1. ОКРУГЛЕНИЕ ВВЕРХ, В ПОЛЬЗУ ПОКУПАТЕЛЯ, а использованные единицы — вниз.
//     Спор о копейке стоит дороже копейки.
//  2. ПРОПОРЦИЯ БЕРЁТСЯ ПОЗИЦИЯМИ (Split), а не итогом: Σ позиций обязана в
//     точности равняться сумме возврата, иначе чек не сойдётся с расчётом.
//  3. ПОТОЛКИ MaxTotal и MaxUnits — доказательство отсутствия переполнения
//     int64 в умножении, а не бизнес-лимит.
//  4. ЕДИНИЦА СРОКА — РОВНО unit СЕКУНД, без календаря и часовых поясов:
//     перевод часов не должен менять сумму возврата.
//  5. ЧАСЫ НАЗАД — НОЛЬ ИСПОЛЬЗОВАННОГО. Рассинхрон машин толкуется в пользу
//     покупателя, а отрицательное число единиц дало бы возврат больше
//     полученного.
//
// Чего в пакете нет: денег с валютой (суммы — голые int64 в минорных
// единицах), календарной арифметики (месяц как «до того же числа»), политики
// удержаний и штрафов — это правила продавца.
