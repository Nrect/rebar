// Package paymentpg — payment.Store на github.com/jackc/pgx/v5: намерения,
// состав, приём событий провайдера и append-only книга денег в базе
// потребителя.
//
// Схема лежит рядом файлом schema.sql с маркерами goose и копируется в каталог
// миграций потребителя как есть (либо применяется из кода: Schema — тот же
// файл, embed). CheckSchema на старте сверяет схему, но не применяет её.
// Store работает и в пуле, и в транзакции потребителя: New(pool, opts) для
// вебхука и сверки, WithTx(tx) — чтобы намерение легло вместе с его заказом.
// Проект и причины — docs/adr/0004-payment.md.
//
//	store := paymentpg.New(pool, paymentpg.Options{Settler: shop{}})
//	if err := store.CheckSchema(ctx); err != nil { … }   // миграция не применена?
//	res, reason, err := svc.Webhook(ctx, req)            // статус, книга и хук — одна транзакция
//
// # Порядок блокировок
//
// намерение → события → книга → хук потребителя, и он ОДИН на все методы.
// Внутри хука потребитель обязан продолжить его же: заказ → резервы → остатки
// в отсортированном порядке → outbox. Два порядка обхода тех же строк — это
// взаимная блокировка ровно в момент оплаты, то есть 503 на оплате.
//
// Безопасность:
//
//  1. СОДЕРЖИМОЕ СТРОКИ НЕ ПОПАДАЕТ В ОШИБКИ. У pgconn.PgError в Detail лежит
//     «Failing row contains (…)» — вся строка: сумма, ссылка потребителя,
//     состав. От ошибки Postgres остаются SQLSTATE, Message и имя ограничения
//     (errors.go); логов в адаптере нет вовсе. Держит
//     TestStore_Error_DoesNotLeakRowContents.
//  2. АТОМАРНОСТЬ — КОНТРАКТ, ДОКАЗАННЫЙ ТЕСТОМ. Статус, книга, строка дедупа
//     события и эффект хука коммитятся вместе. Компилятор этого не проверяет,
//     поэтому держит TestStore_ApplyEvent_IsAtomic: ошибка хука откатывает в
//     том числе строку дедупа — иначе повтор вебхука увидел бы дубль, не
//     применил бы ничего, а провайдер получил бы 200 на неучтённую оплату.
//  3. КОНФЛИКТ РАЗБИРАЕТСЯ ПО ИМЕНИ ОГРАНИЧЕНИЯ, А НЕ ПО КОДУ. У намерения два
//     уникальных ограничения с противоположными исходами: занятый ключ
//     идемпотентности — повтор (ErrIdempotencyRace), занятая ссылка — отказ
//     (ErrReferenceBusy). «Любое 23505 — дубль» вернуло бы клиенту чужую ссылку
//     на оплату. Держит TestStore_CreateIntent_IdempotencyRaceVsReferenceBusy.
//  4. КНИГА APPEND-ONLY ДЕРЖИТСЯ БАЗОЙ. Триггеры payment_ledger_immutable_trg
//     и payment_ledger_no_truncate_trg объявлены ENABLE ALWAYS: инвариант,
//     который держится только дисциплиной кода, обходится миграцией или
//     правкой в проде молча. Держат TestStore_LedgerIsAppendOnly и
//     TestSQL_HasNoLedgerMutations (в адаптере нет ни одного UPDATE или DELETE
//     по книге).
//  5. ПОТОЛОК ВОЗВРАТОВ — ДВА РУБЕЖА. Σrefund ≤ Σcapture проверяется под
//     блокировкой намерения и дублируется триггером книги: первый снимает
//     гонку двух частичных возвратов, второй ловит запись в обход сервиса.
//     Держит TestStore_ApplyRefund_SecondOverCaptureIsRejected.
//  6. ДЕНЬГИ СВЕРЯЮТСЯ ДО ПРИЗНАНИЯ ПОВТОРА. Событие с чужой суммой на уже
//     оплаченном намерении получает amount_mismatch, а не тихий 200 «поздняя
//     доставка»: иначе единственный сигнал о чужих суммах глохнет ровно там,
//     где деньги уже наши. Держит TestStore_ApplyEvent_AmountMismatchAfterCapture.
//  7. ТЕРМИНАЛЬНЫЕ СТАТУСЫ НЕ ВОСКРЕСАЮТ. Предикат домена вычисляется под
//     блокировкой строки, ноль обновлённых строк — конфликт, а не успех;
//     перевести намерение в succeeded мимо книги не даёт и сама база
//     (payment_intents_settled_chk). Держит
//     TestStore_ApplyEvent_LatePendingDoesNotDowngrade.
//  8. ВРЕМЯ ТОЛЬКО ПАРАМЕТРОМ. DEFAULT now() в доменных колонках нет: иначе
//     тесты на управляемых часах проверяют одно, а база пишет другое. Момент
//     зачисления берётся из события и зажимается в [created_at, now] — время
//     внешнего мира не проверено ничем, а колонка, по которой режут выручку,
//     после зачисления неисправима.
//  9. FAIL CLOSED. Nil-пул и nil-транзакция — паника на старте; любой сбой
//     Postgres — payment.ErrUnavailable (503, провайдер повторит), а не тихий
//     успех; схему адаптер не применяет, а сверяет, включая режим ENABLE ALWAYS
//     у триггеров книги.
//
// Чего нет (решения, не пробелы): раннера миграций — schema.sql применяет goose
// потребителя (две правды о схеме, DDL-права у приложения и гонка реплик при
// выкате — не наше); таймаутов и повторов на сериализационных ошибках — их
// назначает потребитель своим раннером транзакций, у библиотеки нет права
// решать за его SLA; своего пула и настроек соединения; логов и метрик —
// наблюдаемость декоратором в paymentotel; FK на таблицы потребителя — пакет
// не знает имени его таблицы заказов, FK добавляет он сам; SKIP LOCKED и
// advisory-блокировок — очереди в этом пакете нет, сверку кормит курсор.
