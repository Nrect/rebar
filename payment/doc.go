// Package payment — приём платежей: намерение оплаты, зачисление по событию
// провайдера, холд, возврат, сверка.
//
// Потребитель считает цену своим правилом и зовёт Service.Start с составом,
// суммой и ключом идемпотентности; пакет морозит сделку в намерении и просит у
// провайдера платёж. Деньги становятся нашими только от события провайдера —
// вебхуком (Service.HandleWebhook) или поллингом сверки (Service.Reconcile),
// причём обоими путями через ОДИН код применения. Зачисление, смена статуса и
// эффекты потребителя — одна транзакция (контракт Store.ApplyEvent); книга
// append-only, возврат — встречная запись, частичных возвратов бывает
// несколько. Что не сошлось, показывает сверка: StalePending,
// CountStuckPending, Drift.
//
// Ядро — stdlib + github.com/google/uuid; чистая пропорция за неиспользованный
// срок — подпакет prorate; двойники — paymenttest. Адаптеры хранилища и
// провайдера живут подпакетами и пишутся по портам этого пакета.
//
// Безопасность:
//
//  1. КЭША НЕТ И НЕ БУДЕТ. Закэшированный ответ «оплачено» — это отданный
//     бесплатно товар, а закэшированный «не оплачено» — деньги, взятые без
//     товара. Ответ на вопрос об оплате берётся из хранилища.
//  2. ЗАЧИСЛЯЕТ ТОЛЬКО СОБЫТИЕ ПРОВАЙДЕРА. Возврат браузера на success-страницу
//     подделывается открытием адреса; ручки «я оплатил» у пакета нет.
//  3. ИСТОЧНИК ПРАВДЫ — ПРОВАЙДЕР, А НЕ ТЕЛО ЗАПРОСА, и проверяется это ДО
//     похода в БД: подпись по сырым байтам либо, у провайдера без подписи,
//     адрес из опубликованного диапазона плюс перечтение объекта через API
//     (адаптеру разрешён ровно один исходящий вызов — тот самый).
//     Неподтверждённый запрос не должен стоить нам соединения из пула.
//  4. ДЕНЬГИ — int64 В МИНОРНЫХ, КНИГА APPEND-ONLY. Возврат — встречная запись
//     со ссылкой, а не отрицательная сумма и не UPDATE; потолок Σrefund ≤
//     capture держится блокировкой намерения И триггером книги.
//  5. ИДЕМПОТЕНТНОСТЬ ГРОМКАЯ. Ключ нормализуется в одной точке (NormalizeKey);
//     тот же ключ и те же параметры — прежний результат как УСПЕХ, тот же ключ
//     и другие — ошибка. Отпечаток включает СОСТАВ: тот же итог из других
//     позиций — это другая операция.
//  6. КЛЮЧ ПРОВАЙДЕРУ — ПРОИЗВОДНЫЙ от нашего id намерения и префикса Config.
//     Клиентский ключ уникален лишь в пределах плательщика, и два покупателя с
//     ключом "buy-1" столкнулись бы в пространстве ключей провайдера.
//  7. СУММА, ВАЛЮТА И СОСТАВ ЗАМОРОЖЕНЫ В НАМЕРЕНИИ. Смена прайса между
//     «показали кнопку» и «пришло событие» не меняет подтверждённую сделку;
//     частичного зачисления холда поэтому нет.
//  8. РАСХОЖДЕНИЕ СУММ НЕ ЗАЧИСЛЯЕТСЯ НИ В КАКУЮ СТОРОНУ. Пришло меньше — либо
//     подмена, либо частичная оплата, которой в модели нет; больше — переплата,
//     вернуть которую автоматически нечем.
//  9. ТЕРМИНАЛЬНЫЕ СТАТУСЫ НЕ ВОСКРЕСАЮТ. События приходят at-least-once и в
//     произвольном порядке: запоздалый pending не даунгрейдит succeeded, а
//     succeeded на отменённом намерении — громкий конфликт с алертом, а не
//     автозачисление.
//  10. АТОМАРНОСТЬ — КОНТРАКТ ПОРТА, А НЕ ТИП. Смена статуса, запись в книгу и
//     эффекты потребителя обязаны быть одной транзакцией; компилятор этого не
//     проверит, поэтому контракт доказывается тестом адаптера
//     TestStore_ApplyEvent_IsAtomic и подстрахован частичным уникальным
//     индексом зачисления.
//  11. ФЛАГА-ВЫКЛЮЧАТЕЛЯ НЕТ. Ни SkipSignature, ни TrustClientAmount, ни
//     AutoSettleOnRedirect: каждый такой флаг — готовая кнопка «отдать платное
//     бесплатно», и она окажется включённой на проде на одну ночь.
//     Разработческий режим достигается ПОДМЕНОЙ ПОРТА Provider.
//  12. ЧЕК ПРОВЕРЯЕТСЯ ДО ПОХОДА К ПРОВАЙДЕРУ: к проведённому расчёту
//     фискальный документ дописать нечем. Секрет магазина, ключ подписи и
//     описание с персональными данными не попадают ни в лог, ни в текст ошибки,
//     ни в URL — ошибки называют id намерения, а не то, что прислал клиент.
//
// # Чего в пакете НЕТ
//
// Каждый пункт — решение с причиной, а не пробел; список нужен тому, кто ищет
// здесь функцию и не находит.
//
//  1. РЕКУРРЕНТА. Автосписание по сохранённой карте требует не таблицы токенов,
//     а дуннинга: сколько раз повторять неудавшееся списание и когда сдаться,
//     плюс кнопка отмены, предупреждение и след согласия. Ляжет сверху: книга
//     уже append-only и идемпотентна.
//  2. МУЛЬТИВАЛЮТНОСТЬ. Валюта одна на расчёт (Config.Currency), Money.Add
//     паникует на смешении. Разным валютам нужен курс на момент сделки и его
//     снапшот в намерении.
//  3. СКЛАД И РЕЗЕРВ. Оплата обязана резервировать остаток, иначе последнюю
//     единицу продадут дважды, — и делать это в ТОЙ ЖЕ транзакции. Место для
//     этого есть (хук адаптера, см. ports.go), самой машины нет: она отдельный
//     пакет (inventory).
//  4. ДОСТАВКА. Её стоимость входит в сумму и в чек обычной строкой, а её
//     статус живёт дольше платежа — это пакет delivery и машина статусов заказа.
//  5. ВЫДАЧА ПРАВ И ЭФФЕКТЫ ПОКУПКИ. Пакет двигает деньги; пометить заказ
//     оплаченным, списать резерв, открыть доступ — работа хука адаптера в той
//     же транзакции либо потребителя после коммита по Reason.
//  6. АДАПТЕР ПРОВАЙДЕРА И ЕГО SDK. В ядре только порт Provider: адаптер живёт
//     подпакетом и тащит ровно одну библиотеку (а лучше stdlib), иначе SDK
//     провайдера приезжает в каждый проект, который подключил платежи.
//  7. ПЛАНИРОВЩИК. Reconciler.Run(ctx) (int, error) подходит планировщику как
//     есть, но интервал, джиттер и остановку задаёт потребитель.
//
// # Наблюдаемость
//
// Исход каждой операции уходит порту Observer — обязательной зависимости
// NewService: op из AllOps, reason из AllReasons, и кардинальность не растёт ни
// от каталога, ни от текстов провайдера. Кому метрики не нужны — LogObserver, а
// не nil: забытый наблюдатель молчал бы ровно на денежных алертах.
//
//	payments_total{op,reason}                     исходы Start/HandleWebhook/Capture/Cancel/Refund/Reconcile (paymentotel.NewObserver)
//	payment_provider_calls{provider,type,result}  вызовы провайдера (paymentotel.Wrap)
//	payment_intents_stuck                         gauge, CountStuckPending: вебхуки перестали доходить
//	payment_drift{kind}                           gauge, Drift: деньги и учёт разошлись, порог алерта 1
//
// Алерты с порогом 1: reason=status_conflict (деньги на закрытом намерении),
// reason=amount_mismatch (провайдер назвал не ту сумму), любой payment_drift.
// Парный к ним — «оплат нет вовсе» по payments_total{reason="settled"}: gauge
// зависших ночью тоже ноль, и без парного алерта тишина неотличима от поломки.
