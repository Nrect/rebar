// ApplyOutcome — что стор СДЕЛАЛ, вычислив присланный доменом предикат.
// Закрытый набор: домен ветвится по нему, а адаптер не выбирает исход, а
// сообщает его.
type ApplyOutcome string

const (
	// OutcomeApplied — предикат сошёлся, все записи выполнены.
	OutcomeApplied ApplyOutcome = "applied"
	// OutcomeDuplicateEvent — операцию с этим ключом уже применяли: событие с
	// этим (provider, event_id) либо строка книги с этим ключом. Никаких других
	// записей не сделано; счётчик доставок увеличен.
	OutcomeDuplicateEvent ApplyOutcome = "duplicate_event"
	// OutcomeUnknownIntent — намерения нет. Событие всё равно записано: орфан
	// обязан быть видимым, а не потерянным.
	OutcomeUnknownIntent ApplyOutcome = "unknown_intent"
	// OutcomeAmountMismatch — сумма или валюта не сошлись. Ни статус, ни книга
	// не тронуты.
	OutcomeAmountMismatch ApplyOutcome = "amount_mismatch"
	// OutcomeAlreadyInTarget — намерение уже в целевом статусе И деньги события
	// сошлись. Норма at-least-once доставки, а не сбой. Сумма входит в условие
	// намеренно: «приехала та же оплата» — это утверждение о ТЕХ ЖЕ деньгах, и
	// событие с чужой суммой обязано получить OutcomeAmountMismatch, а не тихий
	// 200 только потому, что успело после зачисления.
	OutcomeAlreadyInTarget ApplyOutcome = "already_in_target"
	// OutcomeStatusConflict — статус вне ExpectFrom. Разбирает домен: у одних
	// клеток это запоздалое событие, у других — деньги на закрытом намерении.
	OutcomeStatusConflict ApplyOutcome = "status_conflict"
	// OutcomeIgnored — записано только событие: домен прислал пустой To,
	// то есть заранее решил ничего не применять.
	OutcomeIgnored ApplyOutcome = "ignored"
	// OutcomeRefundTooLarge — возврат не влезает в нетто книги под блокировкой.
	// Домен проверяет то же самое до похода к провайдеру, но между его проверкой
	// и записью проходит чужой возврат, и последнее слово за книгой.
	OutcomeRefundTooLarge ApplyOutcome = "refund_too_large"
)

// AllOutcomes — полный список; держит guard-тест.
var AllOutcomes = []ApplyOutcome{
	OutcomeApplied, OutcomeDuplicateEvent, OutcomeUnknownIntent, OutcomeAmountMismatch,
	OutcomeAlreadyInTarget, OutcomeStatusConflict, OutcomeIgnored, OutcomeRefundTooLarge,
}

// TransitionRequest — смена статуса БЕЗ движения денег.
type TransitionRequest struct {
	IntentID uuid.UUID
	// ExpectFrom — статусы, из которых переход законен. Считает домен по
	// таблице переходов; пустой список это ошибка программиста.
	ExpectFrom []Status
	To         Status
	// ProviderPaymentID и Confirmation проставляются вместе с
	// created → pending: платёж у провайдера появился ровно в этот момент.
	ProviderPaymentID string
	Confirmation      Confirmation
	Now               time.Time
}

// TransitionResult — исход и состояние намерения ПОСЛЕ операции; при отказе —
// фактическое текущее состояние, по которому домен и разбирает конфликт.
type TransitionResult struct {
	Outcome ApplyOutcome
	Intent  Intent
}

// ApplyEventRequest — применение события провайдера.
//
// Пустой To означает «только записать событие»: домен заранее решил его не
// применять (орфан, неизвестный тип, запоздалый даунгрейд), но потерять запись
// нельзя — по ней разбирают инциденты и считают число доставок.
type ApplyEventRequest struct {
	// IntentID — uuid.Nil означает орфана: реализация обязана записать строку
	// события с intent_id IS NULL и вернуть OutcomeUnknownIntent. Именно
	// записать: потерянный орфан — это невидимая утечка ключа подписи либо
	// вебхук со стенда, прилетевший в прод.
	IntentID uuid.UUID
	Event    Event
	// ExpectFrom обязателен при непустом To.
	ExpectFrom []Status
	To         Status
	// ExpectAmountMinor и ExpectCurrency — сумма, которую ОБЯЗАНЫ иметь и
	// строка намерения, и событие. Проверяются, только когда есть Ledger:
	// у события отмены суммы может не быть вовсе.
	ExpectAmountMinor int64
	ExpectCurrency    string
	// Ledger — что дописать в книгу. Непусто ТОГДА И ТОЛЬКО ТОГДА, когда
	// To == StatusSucceeded, и обе половины обязательны. Книга без зачисления —
	// деньги на переходе, который деньгами не является; зачисление без книги —
	// статус проехал, книга нет (DriftSucceededNoCapture), состояние
	// запрещённое и неисправимое: книга append-only, строка терминальна.
	//
	// Ledger.IntentID ОБЯЗАН совпадать с IntentID. Разойдись они — статус
	// сменится у одного намерения, а денежная запись ляжет другому: у первого
	// это то же succeeded_no_capture, у второго — занятый уникальный индекс
	// зачисления, то есть его собственная законная оплата не запишется уже
	// никогда.
	Ledger *LedgerEntry
	Now    time.Time
}

// ApplyEventResult — исход и состояние намерения после операции.
type ApplyEventResult struct {
	Outcome ApplyOutcome
	Intent  Intent
}

// ApplyRefundRequest — возврат: компенсирующая запись в книгу.
//
// Отзыва прав, сброса кэша и прочих эффектов здесь нет: их делает хук адаптера
// (см. «Хук потребителя» ниже) в той же транзакции либо потребитель после
// коммита по Reason.
type ApplyRefundRequest struct {
	IntentID       uuid.UUID
	CaptureEntryID uuid.UUID
	// Refund — Kind == LedgerRefund, ReversesEntryID == &CaptureEntryID,
	// IntentID == IntentID запроса, ActorID — тот, кто нажал «вернуть».
	//
	// Совпадение намерений обязательно: реализация блокирует IntentID, и запись
	// на другое намерение уехала бы мимо блокировки. Видно это не было бы ничем —
	// возвращённое намерение выглядит невозвращённым, непричастное выглядит
	// возвращённым, а потолок Σrefund ≤ capture считается по чужой книге.
	Refund LedgerEntry
	Now    time.Time
}

// ApplyRefundResult — исход и записанная (либо ранее записанная) строка.
type ApplyRefundResult struct {
	Outcome ApplyOutcome
	Entry   LedgerEntry
}

// Store — порт хранилища. В сигнатурах только примитивы, uuid, time.Time и типы
// этого пакета: ни pgx, ни pgtype, ни типов провайдера — именно это делает
// пакет копируемым (CONVENTIONS §1).
//
// Все методы получают время параметром: стор никогда не зовёт time.Now() сам,
// иначе «намерение протухло ровно сейчас» нечем протестировать (CONVENTIONS §9).
//
// # Порядок блокировок
//
// intent → events → ledger → хук потребителя. Он один на все методы: два
// порядка обхода тех же строк — это дедлок на зачислении, то есть 503 в момент
// оплаты. Хук идёт последним и берёт СВОИ таблицы уже под нашими блокировками.
type Store interface {
	// CreateIntent вставляет намерение в статусе StatusCreated ВМЕСТЕ с
	// составом (in.Items): состав — часть намерения, и намерение без состава
	// это списание, к которому нечего приложить чеком.
	//
	// Реализация ОБЯЗАНА иметь два ограничения и различать их:
	//
	//  1. UNIQUE (payer_id, idempotency_key), ПОЛНЫЙ, а не частичный:
	//     провалившаяся попытка ключ не освобождает. Ключ идентифицирует
	//     попытку, а не намерение — повтор после отказа обязан возвращать тот же
	//     отказ, а новая попытка требует нового ключа. Нарушение → ErrIdempotencyRace.
	//
	//  2. Частичный UNIQUE (reference) по НЕтерминальным статусам — «одно живое
	//     намерение на Reference». Второй платёж за тот же заказ означал бы два
	//     списания за одну покупку; после терминального статуса первого второе
	//     заводится штатно. Нарушение → ErrReferenceBusy.
	//
	// Различать нарушения реализация обязана ПО ИМЕНИ индекса, а не по коду
	// ошибки: оба нарушения — один и тот же SQLSTATE, а исходы у них
	// противоположные (повтор против отказа), и «любое 23505 — это повтор»
	// вернуло бы клиенту чужую ссылку на оплату.
	//
	// ParamsFingerprint ОБЯЗАН сохраняться байт в байт. Потерянная колонка не
	// ломает ни один тест, зато снимает правило «тот же ключ — та же операция»:
	// см. IntentByKey.
	//
	// Состав приходит УЖЕ проверенным (CheckItems): позиции идут 0..n-1, Σ сумм
	// равна in.AmountMinor. Реализация их не пересчитывает и не переставляет:
	// цена — не её решение и не решение этого пакета.
	CreateIntent(ctx context.Context, in Intent) error

	// IntentByKey — проба идемпотентности. Ключ приходит УЖЕ нормализованным
	// (NormalizeKey), реализация его не трогает.
	//
	// Скоуп ключа — (payer_id, key), не глобальный: глобальное пространство
	// ключей позволило бы угадать чужой ключ и получить чужой результат, то
	// есть чужую ссылку на оплату.
	//
	// ParamsFingerprint ОБЯЗАН возвращаться байт в байт, как сохранён, а Items —
	// полностью и в порядке позиций. Именно по отпечатку домен отличает законный
	// повтор от чужой операции под тем же ключом; пустая сигнатура — это 409, а
	// не «наверное, повтор», поэтому забытое в SELECT поле проявится отказом, а
	// не выданной чужой ссылкой на оплату.
	//
	// Отсутствие строки — это (Intent{}, false, nil), а не ошибка.
	IntentByKey(ctx context.Context, payerID uuid.UUID, key string) (Intent, bool, error)

	// IntentByID — чтение для вебхука, сверки и админки. Items возвращаются так
	// же, как в IntentByKey: состав, приходящий «иногда», однажды окажется
	// пустым там, где по нему собирают чек.
	IntentByID(ctx context.Context, id uuid.UUID) (Intent, bool, error)

	// Transition — CAS смены статуса БЕЗ движения денег: created → pending
	// после ответа провайдера, created/pending → failed|canceled|expired.
	//
	// Денег не касается намеренно: у операции, которая не двигает деньги, не
	// должно быть возможности их сдвинуть. Зачисление живёт только в ApplyEvent.
	//
	// Ноль обновлённых строк — это НЕ успех: реализация обязана перечитать
	// строку и вернуть фактический статус с Outcome != OutcomeApplied. «Ну и
	// ладно» здесь означает потерянный конфликт.
	Transition(ctx context.Context, req TransitionRequest) (TransitionResult, error)

	// ApplyEvent — ЕДИНСТВЕННАЯ операция зачисления.
	//
	// КОНТРАКТ АТОМАРНОСТИ. Всё перечисленное происходит в ОДНОЙ транзакции
	// либо не происходит вовсе:
	//   1) блокировка строки намерения (SELECT ... FOR UPDATE); у орфана
	//      блокировать нечего, и шаг пропускается;
	//   2) вставка строки дедупа (provider, provider_event_id); повтор —
	//      OutcomeDuplicateEvent и никаких других записей. Строка дедупа обязана
	//      предшествовать любой МУТАЦИИ и работает арбитром: кто занял её — тот и
	//      делает работу. Взаимный порядок первых двух шагов реализация выбирает
	//      сама (блокировка раньше вставки, иначе две доставки про одно намерение
	//      дедлочат друг друга на внешнем ключе);
	//   3) проверка предиката, который прислал ДОМЕН, и порядок его частей —
	//      часть контракта: сперва статус (не целевой и вне req.ExpectFrom —
	//      OutcomeStatusConflict), затем, если req.Ledger != nil, сумма и валюта
	//      СТРОКИ намерения и СОБЫТИЯ против req.ExpectAmountMinor/ExpectCurrency
	//      (OutcomeAmountMismatch), и только потом «статус уже целевой»
	//      (OutcomeAlreadyInTarget). Сверка денег идёт ПЕРЕД признанием события
	//      запоздалой копией: иначе после зачисления событие succeeded с любой
	//      суммой получает 200 и метку «поздняя доставка», то есть единственный
	//      сигнал о чужих суммах глохнет ровно там, где деньги уже наши;
	//   4) CAS статуса в req.To; момент зачисления берётся из
	//      req.Event.OccurredAt (событие может доехать через час после списания,
	//      и выручка «за январь» уехала бы в февраль), но ЗАЖИМАЕТСЯ в
	//      [intent.CreatedAt, req.Now]: время события приходит из внешнего мира и
	//      не проверено ничем, а колонка, по которой режут выручку, после
	//      зачисления неисправима;
	//   5) append req.Ledger в книгу (если не nil);
	//   6) хук потребителя (см. «Хук потребителя») — после книги, до commit.
	//      Его ошибка откатывает ВСЁ, включая строку дедупа события: иначе
	//      повтор вебхука увидел бы дубль и не применил бы ничего, а провайдер
	//      получил бы 200 на неучтённую оплату.
	//
	// Реализация НЕ ПРИНИМАЕТ РЕШЕНИЙ: она вычисляет присланный предикат и
	// возвращает исход. Какие ExpectFrom законны и что делать с каждым исходом
	// знает только домен, и только там это покрыто юнит-тестами.
	//
	// Пустой req.To — «только записать событие»: шаги 4–6 пропускаются,
	// возвращается OutcomeIgnored. Пустой req.ExpectFrom при непустом To —
	// ошибка программиста: вернуть ErrBadTransition, а не «подходит любой
	// статус».
	//
	// ЧЕСТНАЯ ЦЕНА ЭТОГО ПОРТА: атомарность здесь — контракт в комментарии, а не
	// тип. Компилятор её не проверит, и подпись метода не мешает реализовать
	// шаги тремя независимыми транзакциями. Поэтому контракт обязан быть
	// доказан интеграционным тестом адаптера TestStore_ApplyEvent_IsAtomic:
	// уронить хук и потребовать, чтобы откатились И статус, И строка книги, И
	// строка дедупа, а повтор события применился. Без этого теста контракт —
	// украшение. Вторая линия обороны, независимая от него, — частичный
	// уникальный индекс зачисления: даже при двух прошедших CAS вторая строка
	// зачисления физически не вставится.
	ApplyEvent(ctx context.Context, req ApplyEventRequest) (ApplyEventResult, error)

	// ApplyRefund — зеркало ApplyEvent для возврата: тот же контракт
	// атомарности, строка refund и хук потребителя одной транзакцией.
	//
	// ПОТОЛОК ВОЗВРАТОВ — Σrefund ≤ Σcapture — проверяется ЗДЕСЬ, под
	// блокировкой намерения, и дублируется триггером книги. Домен считает то же
	// самое до похода к провайдеру, но между его чтением и записью проходит
	// чужой возврат: последнее слово за книгой, и превышение — это
	// OutcomeRefundTooLarge, а не запись.
	//
	// Идемпотентность строки — UNIQUE (intent_id, idempotency_key) в книге, а НЕ
	// UNIQUE (reverses_entry_id): частичных возвратов на одно зачисление бывает
	// несколько. Нарушение ключа → OutcomeDuplicateEvent вместе с уже
	// существующей строкой; домен разбирает её как повтор.
	ApplyRefund(ctx context.Context, req ApplyRefundRequest) (ApplyRefundResult, error)

	// Ledger — записи намерения по возрастанию created_at.
	Ledger(ctx context.Context, intentID uuid.UUID) ([]LedgerEntry, error)

	// StalePending — намерения в НЕтерминальных статусах (created, pending,
	// authorized), созданные раньше olderThan и стоящие в очереди СТРОГО ПОСЛЕ
	// after. Кормит сверку.
	//
	// Порядок обязан быть (created_at, id) по возрастанию — тем же ключом, каким
	// устроен курсор: реализация, отдающая пачку в другом порядке, превращает
	// продвижение курсора в тихий пропуск намерений (см. IntentCursor).
	StalePending(ctx context.Context, olderThan time.Time, after IntentCursor, limit int) ([]Intent, error)

	// CountStuckPending — сколько ВСЕГО незакрытых намерений старше olderThan.
	// Кормит gauge, а не выборку, поэтому потолка у него нет: LIMIT превратил бы
	// «зависших 5000» в «зависших 200» ровно в тот момент, когда число и есть
	// содержание тревоги.
	//
	// Отдельный метод, а не len(StalePending(...)): очередь сверки ограничена
	// размером пачки, и считать по ней значило бы упереть gauge в потолок
	// пачки. Порог «старше olderThan» у обоих ОБЯЗАН быть один и тот же —
	// см. Service.staleBefore.
	CountStuckPending(ctx context.Context, olderThan time.Time) (int64, error)

	// Drift — расхождения книг: оплачено без записи зачисления, зачислено на
	// неоплаченном намерении, возвращено больше полученного.
	Drift(ctx context.Context, now time.Time, limit int) ([]DriftRecord, error)
}

// # Хук потребителя (контракт для адаптера хранилища)
//
// Ядро о выдаче прав, резервах, статусах заказа и сбросе кэша не знает и знать
// не должно: это не деньги. Но эффекты, которые обязаны случиться ВМЕСТЕ с
// зачислением, нельзя делать второй транзакцией — падение между ними оставляет
// человека заплатившим и не получившим. Поэтому у адаптера хранилища есть хук,
// и его форма — часть контракта пакета, хотя тип живёт в адаптере (там типы
// драйвера законны, здесь нет):
//
//	type Settler interface {
//	    OnSettled(ctx context.Context, tx pgx.Tx, in payment.Intent, entry payment.LedgerEntry) error
//	    OnRefunded(ctx context.Context, tx pgx.Tx, in payment.Intent, entry payment.LedgerEntry) error
//	}
//
// Правила, которые адаптер обязан выполнить:
//
//   - хук зовётся ПОСЛЕ записи книги и ДО commit, той же транзакцией, и получает
//     ту самую tx: иначе «в одной транзакции» — это пожелание;
//   - ошибка хука откатывает ВСЁ, включая строку дедупа события, и уезжает
//     наружу как ErrUnavailable → 503 → провайдер повторит;
//   - состав расчёта хук берёт из in.Items — он снапшот и лежит в намерении;
//   - свои строки хук берёт в детерминированном порядке (по отсортированному
//     ключу): две одновременные оплаты пересекающихся заказов иначе возьмут их
//     в противоположном порядке, и это дедлок в момент оплаты;
//   - nil-хук законен и означает «эффектов нет»; двойник paymenttest.MemStore
//     зовёт его тоже (без tx), чтобы потребитель проверял состав транзакции
//     юнит-тестом.
//
// Что в хук НЕ уезжает: сброс кэша и отправка писем. Первое не откатывается,
// второе уходит наружу — их место после commit, по Reason возвращённому
// доменом.

// CreatePaymentRequest — что мы просим у провайдера.
type CreatePaymentRequest struct {
	// IntentID уезжает в metadata провайдера: по нему вебхук находит намерение.
	IntentID uuid.UUID
	PayerID  uuid.UUID
	// Reference — ссылка потребителя (id заказа): уезжает в metadata рядом с
	// IntentID, чтобы платёж в кабинете провайдера искался по номеру заказа.
	Reference   string
	AmountMinor int64
	Currency    string
	// Description — человекочитаемое назначение платежа. ПДн в него не кладут:
	// оно печатается в выписке банка и в кабинете провайдера.
	Description string
	ReturnURL   string
	// Method — способ оплаты из Config.Methods; пусто, если выбирает плательщик
	// у провайдера.
	Method Method
	// Capture — одностадийная оплата: списать сразу. false означает холд, и
	// адаптер, который холдов не умеет, обязан вернуть ErrUnsupported, а не
	// списать молча.
	Capture bool
	// IdempotencyKey — производный (providerKey), а НЕ клиентский.
	IdempotencyKey string
	// Receipt — фискальный чек, который провайдер обязан пробить в момент
	// расчёта. Запрашивается ИМЕННО ЗДЕСЬ: к проведённому платежу чек дописать
	// нечем. nil законен только при выключенном Config.RequireReceipt.
	Receipt *Receipt
}

// CreatePaymentResult — ответ провайдера на создание платежа.
type CreatePaymentResult struct {
	ProviderPaymentID string
	Confirmation      Confirmation
	// Status — как провайдер оценил платёж сразу. Домен отображает его только в
	// StatusPending либо StatusFailed и ни в какой другой: путь в succeeded и в
	// authorized лежит исключительно через подтверждённое событие.
	Status EventType
}

// CaptureRequest — списание холда.
type CaptureRequest struct {
	ProviderPaymentID string
	// AmountMinor и Currency — сумма намерения целиком. Частичного списания в
	// модели нет: сумма заморожена в намерении, и списать другую значило бы
	// разойтись с составом и с уже пробитым чеком.
	AmountMinor    int64
	Currency       string
	IdempotencyKey string
	// Receipt — чек расчёта. У двухстадийной оплаты расчёт происходит В МОМЕНТ
	// СПИСАНИЯ, а не постановки холда, поэтому чек уезжает сюда.
	Receipt *Receipt
}

// RefundProviderRequest — возврат платежа на указанную сумму.
//
// Сумма ОБЯЗАТЕЛЬНА и не выводится из платежа: частичный возврат законен, и
// «вернуть всё» — лишь его частный случай.
type RefundProviderRequest struct {
	ProviderPaymentID string
	AmountMinor       int64
	Currency          string
	IdempotencyKey    string
	// Receipt — СВОЙ чек возврата («возврат прихода»), а не тот, что уехал с
	// покупкой. Закон требует фискального документа на каждый расчёт, и возврат
	// денег — такой же расчёт: без встречного чека приход остаётся пробитым, а
	// возврат — нет, и расходятся не наши книги, а наша отчётность.
	Receipt *Receipt
}

// WebhookRequest — сырое уведомление провайдера.
//
// Тело — байты, а не разобранная структура: подпись, если она у провайдера
// есть, считается по СЫРЫМ байтам. Перемаршаленный JSON даст другую подпись, и
// проверка станет ритуалом.
type WebhookRequest struct {
	Raw []byte
	// Headers — map[string][]string, а не http.Header: подпись это данные, а не
	// HTTP. Порт, принимающий http.Header, нельзя вызвать из теста, не собрав
	// запрос, и нельзя переиспользовать для очереди.
	Headers map[string][]string
	// RemoteIP — адрес отправителя, как его определил периметр потребителя
	// (доверенный прокси).
	//
	// Заведён потому, что у части провайдеров подписи НЕТ вовсе: там
	// подлинность — это адрес из опубликованного диапазона плюс перечитывание
	// объекта через API. Пустая строка законна у провайдера с подписью и
	// означает «периметр адрес не сообщил»; адаптер, который на неё опирается,
	// обязан считать это отказом, а не «проверять нечем».
	RemoteIP string
}

// Provider — порт платёжного провайдера.
//
// Пакет не знает ни HTTP-схемы провайдера, ни его JSON, ни его словаря
// статусов: всё это знает адаптер.
type Provider interface {
	// Name — имя провайдера: попадает в БД, в ключ дедупа и в метку метрики.
	Name() ProviderName

	// CreatePayment создаёт платёж у провайдера и возвращает подтверждение.
	//
	// ОБЯЗАН быть идемпотентным по req.IdempotencyKey: повторный вызов с тем же
	// ключом возвращает ТОТ ЖЕ платёж, а не второй. На этом держится
	// восстановление после падения между вставкой намерения и походом к
	// провайдеру — сервис просто зовёт метод ещё раз.
	CreatePayment(ctx context.Context, req CreatePaymentRequest) (CreatePaymentResult, error)

	// ParseWebhook подтверждает подлинность уведомления и приводит его к Event.
	//
	// ИСТОЧНИК ПРАВДЫ — ПРОВАЙДЕР, А НЕ ТЕЛО ЗАПРОСА, и подтверждение идёт
	// ПЕРВЫМ, до любого разбора и до любого похода в БД. Форм две, обе законны:
	//
	//   - подпись по СЫРЫМ байтам, сравнение тайминг-безопасное
	//     (subtle.ConstantTimeCompare), секрет в лог не попадает никогда;
	//   - у провайдера без подписи — req.RemoteIP из опубликованного диапазона
	//     (проверяется ДО похода куда-либо) плюс перечитывание объекта через API
	//     провайдера, откуда и строится Event; из тела берётся только id
	//     объекта.
	//
	// Адаптеру разрешён РОВНО ОДИН исходящий вызов — тот самый проверочный GET.
	// Он и есть проверка подлинности; всё сверх него съедает бюджет запроса
	// чужой латентностью. Его сбой — ErrUnavailable (503, провайдер повторит),
	// а не ErrMalformedEvent (400, провайдер больше не придёт).
	//
	// Неподтверждённое уведомление — ErrInvalidSignature, и тело при этом не
	// разбирается вовсе. Событие, которое адаптер не сумел отобразить в
	// известный EventType, получает EventIgnored.
	ParseWebhook(ctx context.Context, req WebhookRequest) (Event, error)

	// GetPayment — состояние платежа у провайдера; кормит сверку потерянных
	// вебхуков.
	//
	// Реализация обязана заполнить Event.ProviderEventID ДЕТЕРМИНИРОВАННО и ТЕМ
	// ЖЕ правилом, что и в ParseWebhook (например "<provider>:<id>:<status>").
	// Иначе вебхук и сверка не дедуплицируются друг с другом и применяют одно
	// и то же событие дважды.
	GetPayment(ctx context.Context, providerPaymentID string) (Event, error)

	// Capture списывает холд; идемпотентен по req.IdempotencyKey.
	//
	// Адаптер провайдера без двухстадийной оплаты возвращает ErrUnsupported —
	// это отказ по конструкции, а не сбой: ретраить его бессмысленно.
	Capture(ctx context.Context, req CaptureRequest) (Event, error)

	// Cancel снимает холд (или отменяет неоплаченный платёж); идемпотентен по
	// ключу. Без холдов — ErrUnsupported.
	Cancel(ctx context.Context, providerPaymentID, idempotencyKey string) (Event, error)

	// Refund — возврат на req.AmountMinor; идемпотентен по req.IdempotencyKey.
	//
	// Реализация ОБЯЗАНА вернуть в Event сумму и валюту фактически выполненного
	// возврата, если провайдер их сообщает: домен сверяет их со своей цифрой и
	// отказывается записывать в книгу сумму, которой не было
	// (см. checkRefundEcho).
	Refund(ctx context.Context, req RefundProviderRequest) (Event, error)
}
