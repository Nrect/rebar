// Package paymenttest — двойники портов payment для тестов потребителей и
// адаптеров. Двойник — не мок: он ведёт себя как контрагент, чтобы тест
// проверял исход, а не «метод вызвали с аргументами». Потокобезопасны (тесты
// идут под -race), поля правятся прямо из теста.
//
// Ошибки двойников отличимы от доменных (ErrNoEvent, ErrNoPayment,
// ErrProviderDown, ErrStore): тест не должен принять свою заглушку за решение
// пакета.
//
// Жители:
//
//   - MemStore — payment.Store в памяти: уникальность (payer_id, ключ) с
//     отпечатком, «одно живое намерение на Reference», дедуп событий,
//     книга с потолком Σrefund ≤ capture, хуки OnSettled/OnRefunded (тот же
//     контракт, что у адаптера, но без tx) и Err для fail-closed тестов.
//   - MemProvider — payment.Provider: идемпотентен по ключу, детерминированный
//     ProviderEventID (вебхук и сверка дедуплицируются друг с другом), холды
//     через Capture/Cancel либо ErrUnsupported при SetNoHolds. Публичных полей
//     нет: ручки — методами под замком (Set*Err, RejectNext, RejectReference…),
//     потому что тест потребителя меняет их, пока его HTTP-сервер зовёт
//     провайдер из другой горутины; CreateHook зовётся вне замка.
//   - Observer — payment.Observer: запоминает исходы по порядку, Outcomes
//     отдаёт копию.
//   - Clock — управляемые часы для payment.Service.SetClock.
//
// Двойника, который постит НАСТОЯЩИЙ вебхук по HTTP, здесь нет: он живёт рядом
// с адаптером провайдера (cmd/psfake), потому что знает его формат.
