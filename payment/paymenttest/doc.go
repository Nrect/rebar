// Package paymenttest — двойники портов payment для тестов потребителей и
// адаптеров. Двойник — не мок: он ведёт себя как контрагент, чтобы тест
// проверял исход, а не «метод вызвали с аргументами». Потокобезопасны (тесты
// идут под -race).
//
// ПУБЛИЧНЫХ ПОЛЕЙ НЕТ: настройка и отказы правятся методами под тем же замком,
// под которым их читают методы порта (SetErr, RejectNext, FailReference…).
// Поле безопасно, лишь пока тест выставляет его до первого вызова; потребитель,
// который тестирует через живой HTTP-сервер, пишет его из горутины теста, пока
// ручка читает в горутине сервера, — и -race краснеет у него (CONVENTIONS §3).
// Хук, изображающий внешнее событие (CreateHook), зовётся вне замка; хук,
// который по контракту порта исполняется внутри транзакции (OnSettled,
// OnRefunded), — под замком двойника, и трогать двойник ему нельзя.
//
// Ошибки двойников отличимы от доменных (ErrNoEvent, ErrNoPayment,
// ErrProviderDown, ErrStore): тест не должен принять свою заглушку за решение
// пакета.
//
// Жители:
//
//   - MemStore — payment.Store в памяти: уникальность (payer_id, ключ) с
//     отпечатком, «одно живое намерение на Reference», дедуп событий,
//     книга с потолком Σrefund ≤ capture, хуки SetOnSettled/SetOnRefunded
//     (тот же контракт, что у адаптера, но без tx) и SetErr для fail-closed
//     тестов.
//   - MemProvider — payment.Provider: идемпотентен по ключу, детерминированный
//     ProviderEventID (вебхук и сверка дедуплицируются друг с другом), холды
//     через Capture/Cancel либо ErrUnsupported при SetNoHolds, отказы —
//     RejectReference по ссылке и RejectNext без неё, сбои — Set*Err.
//   - Observer — payment.Observer: запоминает исходы по порядку, Outcomes
//     отдаёт копию.
//   - Clock — управляемые часы для payment.Service.SetClock.
//
// Двойника, который постит НАСТОЯЩИЙ вебхук по HTTP, здесь нет: он живёт рядом
// с адаптером провайдера (cmd/psfake), потому что знает его формат.
